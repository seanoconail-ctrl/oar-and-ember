import { chromium } from '@playwright/test';
import { createServer } from 'vite';
const server = await createServer({ root: '/home/user/oar-and-ember', server: { port: 5298 }, logLevel: 'error' });
await server.listen();
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 640, height: 360 } });
page.on('console', (m) => console.log('console:', m.type(), m.text().slice(0, 300)));
page.on('pageerror', (e) => console.log('pageerror', e.message.slice(0, 500)));
await page.goto('http://localhost:5298/?quality=full&view=play&name=Ash&body=A&capture&zone=ZONE_SK_MACHAIR&at=54,16&day=3');
await page.waitForTimeout(40000);
console.log(await page.evaluate(() => document.querySelector('canvas#screen')?.getAttribute('data-state')), (await page.evaluate(() => document.body.innerText)).slice(0, 500));
await browser.close(); await server.close();
