def icon(name):
    g = blank(BW, BH)
    for y, r in enumerate(ICONS[name]):
        for x, ch in enumerate(r):
            if ch != '.':
                g[y + 1][x + 1] = ICON_COL[ch]
    return g


# ------------------------------------------------------------------------- the clock
def sky_icon(kind):
    g = blank(14, 14)
    cx, cy = 7, 7
    for y in range(14):
        for x in range(14):
            d = math.hypot(x + 0.5 - cx, y + 0.5 - cy)
            if kind == 'sun':
                if d < 3.6:
                    g[y][x] = c('fire', 6 if d < 2 else 5)
                elif d < 4.4:
                    g[y][x] = c('fire', 4)
                elif d < 6.2 and (round(math.atan2(y + 0.5 - cy, x + 0.5 - cx) / (math.pi / 4)) % 2 == 0):
                    a = math.atan2(y + 0.5 - cy, x + 0.5 - cx) / (math.pi / 4)
                    if abs(a - round(a)) < 0.18:
                        g[y][x] = c('fire', 5)
            elif kind == 'dusk':
                if y >= 9:
                    if y == 9:
                        g[y][x] = c('ink', 1) if 1 <= x <= 12 else '.'
                    continue
                if d < 4.6:
                    g[y][x] = c('fire', 5 if d < 3 else 4)
            else:
                # A crescent moon, pale.
                d2 = math.hypot(x + 0.5 - cx - 2.2, y + 0.5 - cy + 1.2)
                if d < 4.6 and d2 > 3.8:
                    g[y][x] = c('wool', 6 if d < 3.4 else 5)
    # A dark rim so it reads on any ground.
    out = [r[:] for r in g]
    for y in range(14):
        for x in range(14):
            if g[y][x] != '.':
                continue
            if any(0 <= y + dy < 14 and 0 <= x + dx < 14 and g[y + dy][x + dx] != '.' and g[y + dy][x + dx] != c('ink', 1)
                   for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                out[y][x] = INK
    return out


# ------------------------------------------------------------------------- the timing ring
def ring(radius, col, width=1.0, dither=False):
    g = blank(32, 32)
    for y in range(32):
        for x in range(32):
            d = math.hypot(x + 0.5 - 16, (y + 0.5 - 16) * 1.0)
            if abs(d - radius) < width / 2 + 0.25:
                if dither and (x + y) % 2:
                    continue
                g[y][x] = col
    return g


