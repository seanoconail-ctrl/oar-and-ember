RAMP = {}
for e in _pal['entries']:
    if 'ramp' in e:
        RAMP.setdefault(e['ramp'], {})[e['step']] = e['code']


def c(ramp, step):
    steps = RAMP[ramp]
    k = max(min(steps), min(max(steps), int(round(step))))
    return steps[k]


INK = c('ink', 0)


def blank(w, h):
    return [['.'] * w for _ in range(h)]


def rows(g):
    return [''.join(r) for r in g]


def write(name, size, pivot, frames, about):
    w, h = size
    out = ['# Generated by assets/art/authoring/ui_stage07.py. Do not edit by hand: change the script',
           '# and run it again.'] + [f'# {a}' for a in about] + [
        f'sheet: {name}', 'kind: decal', 'palette: book07', f'size: {w}x{h}',
        f'pivot: {pivot[0]},{pivot[1]}', f'footprint: {w}x{h}', 'facings: -', 'placeholder: false']
    states = []
    for (state, i), _ in frames:
        if state not in states:
            states.append(state)
    for st in states:
        n = sum(1 for (s, _), _ in frames if s == st)
        out.append(f'anim.{st}: frames {n}, ticks 1')
    for (state, i), g in frames:
        out += ['', f'frame {state} - {i}'] + rows(g) + ['end']
    with open(f'{SHEETS}/{name}.txt', 'w') as f:
        f.write('\n'.join(out) + '\n')
    print(f'wrote {name}')


# ------------------------------------------------------------------------- the stamina bar
BW, BH = 12, 12        # frame canvas; the bar is 10 px tall at rows 1..10


def column(kind):
    g = blank(BW, BH)
    g[1][0] = c('tar', 3)
    g[10][0] = c('tar', 1)
    for y in range(2, 10):
        if kind == 'fill':
            g[y][0] = c('grass', 9 if y == 2 else 8 if y < 5 else 7 if y < 8 else 6)
        elif kind == 'spent':
            g[y][0] = c('ink', 1) if y > 2 else c('earth', 1)
        elif kind == 'groove':
            g[y][0] = c('stone', 1 if (y % 3) else 0)
        elif kind == 'glow':
            g[y][0] = c('fire', 6 if y < 5 else 5)
        elif kind == 'notch':
            g[y][0] = c('bracken', 3)
    if kind == 'notch':
        g[1][0] = c('bracken', 4)
        g[10][0] = c('bracken', 2)
    return g


def cap(left):
    g = blank(BW, BH)
    for y in range(1, 11):
        for x in range(4):
            edge = (x == 0) if left else (x == 3)
            if (y in (1, 10)) and edge:
                continue
            g[y][x] = c('bracken', 3 if y < 4 else 2) if not edge else c('tar', 2)
    for y in (4, 7):
        g[y][1 if left else 2] = c('bracken', 4)
    return g


