    write('ui_clock', (14, 14), (7, 7), [((k, 0), sky_icon(k)) for k in ('sun', 'dusk', 'moon')], [
        'The day clock\'s sky: the sun by day, the sun on the horizon at first and last light, the moon.'])
    frames = []
    for i in range(8):
        frames.append((('ring', i), ring(14 - i * 1.4, c('wool', 6), 1.2, dither=i < 2)))
    frames.append((('mark', 0), ring(4.2, c('fire', 5), 1.4)))
    hit = ring(5.2, c('fire', 6), 1.6)
    for k in range(8):
        a = k * math.pi / 4
        for r in (7, 8):
            hit[int(16 + math.sin(a) * r)][int(16 + math.cos(a) * r)] = c('fire', 5)
    frames.append((('hit', 0), hit))
    write('ui_timing', (32, 32), (16, 16), frames, [
        'A hands-on action\'s timing (Book 2 section 07): a ring closing on the mark over the work; a',
        'press as it meets the mark earns the timing bonus; the flash shows a good press.'])


