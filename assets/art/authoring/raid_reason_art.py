# ---------------------------------------------------------------------------- the goods' parts
def sack(s, cx, base, w=15, h=12, mark=True):
    """A barley sack sitting on its base: rounded, slumped, its neck tied off with a cord, the
    storehouse's mark (a ring with a stroke) daubed on its face."""
    for y in range(h):
        v = y / (h - 1)
        half = (w / 2) * (0.5 + 0.5 * math.sin(math.pi * (0.15 + 0.6 * v)))
        for x in range(int(cx - half), int(cx + half) + 1):
            u = (x - (cx - half)) / max(1, 2 * half)
            shade = 4.7 - u * 1.9 - v * 0.6 + (hash01(x, y, 7) - 0.5) * 0.5
            if (x + y * 2) % 5 == 0:
                shade -= 0.4                                    # the weave
            s.px(x, base - h + 1 + y, C('wool', shade))
    # The neck gathered and tied: a cord round it, the ears of the cloth above.
    top = base - h + 1
    for x in range(int(cx - 2), int(cx + 3)):
        s.px(x, top - 1, C('wool', 4.4 - (x > cx) * 1.0))
    for x in range(int(cx - 1), int(cx + 2)):
        s.px(x, top - 2, C('wool', 5 - (x > cx)))
    s.px(int(cx), top - 3, C('wool', 4))
    for x in range(int(cx - 3), int(cx + 3)):
        s.px(x, top, C('tar', 2.4))                             # the cord
    if mark:
        # The storehouse's mark: a ring with a stroke through it, in tar.
        mx, my = int(cx - 1), base - h // 2
        for a in range(20):
            ang = a / 20 * math.tau
            s.px(int(round(mx + 2.6 * math.cos(ang))), int(round(my + 2.2 * math.sin(ang))), C('tar', 1.4))
        for k in range(-4, 5):
            s.px(mx + k, my - int(round(k * 0.6)), C('tar', 1.0))


def nails(s, cx, base):
    """A bundle of nails in a knotted rag, iron heads glinting at its open neck."""
    for y in range(5):
        half = 3.4 - abs(y - 2.6) * 0.5
        for x in range(int(cx - half), int(cx + half) + 1):
            s.px(x, base - 4 + y, C('earth', 4.2 - (x > cx) * 1.1 - y * 0.2))
    for k, (dx, dy) in enumerate([(-2, -5), (-1, -6), (0, -5), (1, -6), (2, -5), (0, -7)]):
        s.px(int(cx + dx), base + dy, C('stone', 6.6 + (k % 3) * 0.9))
    s.px(int(cx + 3), base - 5, C('earth', 3))                 # the knot's ear
    s.px(int(cx + 4), base - 6, C('earth', 3.6))


def net(s, x0, x1, base, depth=6):
    """A mended net heaped in folds: brown twine in diamonds, a few cork floats, a pale new mend."""
    for x in range(x0, x1):
        u = (x - x0) / max(1, x1 - x0 - 1)
        top = base - depth * math.sin(math.pi * u) ** 0.6 - (hash01(x, 0, 21) - 0.5) * 1.4
        for y in range(int(top), base + 1):
            diamond = (x + y) % 3 == 0 or (x - y) % 3 == 0
            col = C('earth', 5 - (y - top) * 0.3) if diamond else C('earth', 1.6)
            if 0.55 < u < 0.7 and diamond:
                col = C('sand', 5)                              # the new mend, pale twine
            s.px(x, y, col)
    for fx in range(x0 + 2, x1 - 1, 5):
        u = (fx - x0) / max(1, x1 - x0 - 1)
        fy = int(base - depth * math.sin(math.pi * u) ** 0.6) + 1
        s.px(fx, fy, C('sand', 5))
        s.px(fx + 1, fy, C('sand', 3))


# ---------------------------------------------------------------------------- the skin boat
def skinboat(oar=True, goods=True):
    """The scavengers' currach seen from the south in the three-quarter view, drawn up and listing
    a little, bow to the west, stern to the east (where the steering oar is lashed)."""
    w, h = 116, 48
    s = Sprite(w, h, w // 2, h - 7)
    x0, x1 = 6, 108

    def lines(t):
        body = math.sin(math.pi * t) ** 0.35
        # The bow lifts blunt and high (west); the stern is fuller and lower (east).
        rise = 14 * max(0.0, 1 - t / 0.3) ** 2.2 + 5 * max(0.0, (t - 0.8) / 0.2) ** 2
        near = 22 - rise - 2 * t
        far = near - 6.5 * body
        keel = 22 - 2 * t + 2 + 8.5 * body - rise * 0.25
        return near, far, keel

    for x in range(x0, x1):
        t = (x - x0) / (x1 - x0 - 1)
        near, far, keel = lines(t)
        for y in range(int(far), int(keel) + 1):
            if y < near:
                # The inside: the wicker laths under the hide, darker towards the bilge.
                depth = (y - far) / max(1, near - far)
                col = C('tar', 1.3 + depth * 1.0)
                if (x % 4 == 0) and depth > 0.2:
                    col = C('tar', 3.2 - depth * 0.8)           # a lath of the wicker frame
                if y <= far + 1:
                    col = C('driftwood', 4)
            else:
                v = (y - near) / max(1, keel - near)
                # The tarred hide: smooth, a sheen at the turn of the bilge, ribs showing faintly.
                sheen = 1.6 * math.exp(-((v - 0.28) / 0.14) ** 2)
                rib = 0.4 if (x - x0) % 9 == 0 and 0.05 < t < 0.95 else 0.0
                col = C('tar', 2.8 + sheen + rib - v * 1.6 + (hash01(x, y, 5) - 0.5) * 0.3)
                # The seam where two hides are sewn together, its stitches a shade lighter.
                if abs(v - 0.58) < 0.05:
                    col = C('tar', 3.6) if x % 4 == 0 else C('tar', 1.0)
            s.px(x, y, col)
        # The gunwale: a doubled withy, the hide lashed over it.
        s.px(x, int(near), C('driftwood', 5 if x % 5 else 3))
        s.px(x, int(near) + 1, C('driftwood', 2) if x % 6 == 1 else C('tar', 3.4))
        s.px(x, int(far), C('driftwood', 3))
    # Thwarts across the inside, and two oars lying fore and aft along them.
    for tx_ in (34, 56, 80):
        t = (tx_ - x0) / (x1 - x0 - 1)
        near, far, _ = lines(t)
        for y in range(int(far) + 1, int(near)):
            s.px(tx_, y, C('driftwood', 4.4))
            s.px(tx_ + 1, y, C('driftwood', 2.2))
    for k, dy in enumerate((-4, -2)):
        for x in range(22, 90):
            t = (x - x0) / (x1 - x0 - 1)
            y = int(22 - 2 * t + dy)
            if s.mask[y, x]:
                s.px(x, y, C('driftwood', 5 - k))
    if goods:
        # The sack and the nails amidships, the net heaped over the stern thwart.
        near_mid, _, _ = lines(0.47)
        sack(s, 52, int(near_mid) + 1)
        nails(s, 63, int(near_mid) + 1)
        near_st, _, _ = lines(0.7)
        net(s, 70, 88, int(near_st) + 1)
    if oar:
        # Thorkel's steering oar, lashed on the near quarter at the stern: the loom rising above
        # the gunwale, lashed at its boss with a withy, the blade down in the sand, the tiller.
        ax, ay, bx, by = 92, 1, 104, 36
        for k in range(70):
            f = k / 69
            x = ax + (bx - ax) * f
            y = ay + (by - ay) * f
            wide = 0 if f < 0.6 else int(1 + (f - 0.6) * 7)
            for d in range(-wide, wide + 1):
                s.px(int(round(x + d)), int(round(y)), C('driftwood', 5.5 - (d > 0) * 1.5 - f * 1.4))
        for y in (16, 17, 18):
            for x in range(96, 100):
                s.px(x, y, C('wool', 3 + (y == 17)))
        for x in range(84, 94):
            s.px(x, 3 + (x - 84) // 4, C('driftwood', 4))
    return s.outline()


def write_skinboat():
    size, pivot = (124, 64), (62, 58)
    frames = []
    for key, oar, goods in (('oar', True, False), ('bare', False, False),
                            ('oar_goods', True, True), ('bare_goods', False, True)):
        rows_ = raw_rows(skinboat(oar, goods), size, pivot)
        # Every frame stands on the keel's lowest row (the oar's blade rests on the sand beside it).
        low = max(y for y, r in enumerate(rows_) if r.strip('.'))
        shift = pivot[1] - low
        blank = '.' * size[0]
        moved = [blank] * size[1]
        for y, r in enumerate(rows_):
            if 0 <= y + shift < size[1]:
                moved[y + shift] = r
        frames.append(((key, '-', 0), moved))
    write('prop_skiff', sheet_text(
        'prop_skiff', 'prop', size, pivot, frames,
        {'oar': (1, 1), 'bare': (1, 1), 'oar_goods': (1, 1), 'bare_goods': (1, 1)},
        HEADER + ["The wreck-scavengers' skin boat in Seal Cave, drawn up in the mouth (Book 4 section 02;",
                  'decision DH-137): tarred hides on a wicker frame, Thorkel\'s steering oar on the quarter or',
                  'taken, and its Carrick goods (a marked barley sack, a bundle of nails, a net) or none.'],
        shadow='110x10', footprint='110x12'))


# ---------------------------------------------------------------------------- the load
def goods_load(facing):
    """The goods as one load: the marked sack, the net folded in a roll across its shoulders, the
    nails tied at its neck."""
    w, h = 28, 22
    s = Sprite(w, h, w // 2, h - 1)
    base = h - 1
    sack(s, 13, base, w=18, h=15, mark=facing in 'se')
    # The net, rolled and laid across the sack's shoulders, its ends hanging a little.
    top = base - 15 + 4
    for x in range(4, 23):
        sag = 1 if x in (4, 5, 21, 22) else 0
        for d in range(3):
            y = top + d + sag
            diamond = (x + d) % 3 == 0 or (x - d) % 3 == 0
            s.px(x, y, C('earth', 4.8 - d * 0.6) if diamond else C('earth', 2.0))
    for fx in (7, 13, 19):
        s.px(fx, top + 1, C('sand', 5))
    nails(s, 21, base - 10)
    if facing == 'w':
        s.rgb = s.rgb[:, ::-1].copy()
        s.mask = s.mask[:, ::-1].copy()
    return s


def main():
    write_skinboat()
    write_load('prop_carrick_goods', goods_load,
               ["The skin boat's Carrick goods as one load (decision DH-139): a marked barley sack, the",
                'nails tied at its neck and the net folded over it, lying or carried on the shoulder.'],
               (40, 48), '24x6')


if __name__ == '__main__':
    main()
