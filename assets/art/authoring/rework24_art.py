def rows_of(spr, size, pivot, outline=True):
    s = spr.padded(1)
    if outline:
        s.outline()
    rgb, mask = place(s, size, pivot)
    return codes(rgb, mask)


def raw_rows(spr, size, pivot):
    """A sprite on a canvas with its anchor (not its lowest row) on the pivot."""
    w, h = size
    rgb = np.zeros((h, w, 3), np.float32)
    mask = np.zeros((h, w), bool)
    dx, dy = pivot[0] - spr.ax, pivot[1] - spr.ay
    for y, x in zip(*np.nonzero(spr.mask)):
        X, Y = x + dx, y + dy
        if 0 <= X < w and 0 <= Y < h:
            rgb[Y, X] = spr.rgb[y, x]
            mask[Y, X] = True
    return codes(rgb, mask)


def read_sheet(name):
    """The frames of an existing sheet as Sprites (palette codes back to colours)."""
    path = f'{REPO}/assets/art/sheets/{name}.txt'
    head, frames, cur, rows = {}, {}, None, []
    for line in open(path, encoding='utf8'):
        line = line.rstrip('\n')
        if cur is None:
            if line.startswith('frame '):
                cur = tuple(line.split()[1:])
                rows = []
            elif ':' in line and not line.startswith('#'):
                k, v = line.split(':', 1)
                head[k.strip()] = v.strip()
        elif line == 'end':
            frames[cur] = rows
            cur = None
        else:
            rows.append(line)
    w, h = (int(v) for v in head['size'].split('x'))
    px, py = (int(v) for v in head['pivot'].split(','))
    out = {}
    for key, rs in frames.items():
        s = Sprite(w, h, px, py)
        for y, r in enumerate(rs):
            for x, c in enumerate(r):
                if c != '.':
                    s.px(x, y, CODE_RGB[c])
        out[key] = s
    return out, (w, h), (px, py)


def line(s, x0, y0, x1, y1, col, width=1):
    n = int(max(abs(x1 - x0), abs(y1 - y0))) + 1
    for k in range(n + 1):
        t = k / max(1, n)
        x, y = x0 + (x1 - x0) * t, y0 + (y1 - y0) * t
        for d in range(width):
            s.px(int(round(x)) + d, int(round(y)), col)


# --------------------------------------------------------------------- strongbox and stores
def strongbox(facing):
    side = facing in 'ew'
    w, h = (11, 10) if side else (15, 10)
    s = Sprite(w, h, w // 2, h - 1)
    for y in range(h):
        for x in range(w):
            top = y < 4
            step = 2 + (1 if top else 0) - (1 if x > w - 3 else 0)
            col = C('tar', step)
            if x in (0, w - 1) or y in (0, 4, h - 1) or (not side and x == w // 2):
                col = C('stone', 3 if not top else 4)        # the iron straps
            if (x + y) % 5 == 0 and (x in (0, w - 1) or y in (0, 4)):
                col = C('stone', 6)                         # rivet heads
            s.px(x, y, col)
    s.px(w // 2, 6, C('stone', 7))                          # the lock plate
    s.px(w // 2, 7, C('stone', 5))
    return s


def bundle(facing):
    side = facing in 'ew'
    w, h = (13, 12) if side else (17, 12)
    s = Sprite(w, h, w // 2, h - 1)
    for y in range(h):
        for x in range(w):
            dx = (x + 0.5 - w / 2) / (w / 2)
            dy = (y + 0.5 - h / 2 - 1) / (h / 2)
            if dx * dx + dy * dy > 1.05:
                continue
            shade = 4 - dx * 1.1 - dy * 1.3 + (hash01(x, y, 3) - 0.5) * 0.8
            s.px(x, y, C('sand', int(shade)))                # sacking
    for x in range(w):                                      # the lashing round it, twice
        for yy in (4, 8):
            if s.mask[yy, x]:
                s.px(x, yy, C('earth', 2 if x % 2 else 3))
    # The cauldron's iron rim and a salt fish's tail at the top.
    for x in range(w // 2 - 4, w // 2 + 4):
        s.px(x, 1, C('stone', 2))
        s.px(x, 2, C('tar', 1))
    s.px(w // 2 + 3, 0, C('stone', 6))
    s.px(2, 3, C('stone', 7))
    s.px(1, 2, C('stone', 6))
    return s


