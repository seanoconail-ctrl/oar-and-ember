# ------------------------------------------------------------------------------- the net
def net(phase, cut):
    """The net over Hild, waist deep: cords and floats over her shoulders and the water round her.
    `cut` 0 (whole) .. 3 (parted, falling away)."""
    w, h = 36, 34
    s = Sprite(w, h, 18, h - 1)
    cords = C('earth', 1)
    wet = C('tar', 1)
    for y in range(4, h - 6):
        for x in range(2, w - 2):
            dx = (x - 18) / 15
            dy = (y - 18) / 14
            if dx * dx + dy * dy > 1:
                continue
            wave = math.sin((x * 0.4 + phase * 1.6)) * 0.6
            on = (x + int(y + wave)) % 4 == 0 or (x - int(y + wave)) % 4 == 0
            if not on:
                continue
            if cut > 0:
                # Parted: a gap opening down the middle, widening each frame.
                if abs(x - 18) < cut * 4 + (y % 3):
                    continue
                if cut >= 2 and y < 10 + cut * 3:
                    continue
            s.px(x, y + (cut * 2 if cut > 0 else 0), cords if (x + y) % 3 else wet)
    # Cork floats along the top edge, bobbing.
    for k, x in enumerate((6, 12, 24, 30)):
        y = 6 + round(math.sin(phase * 1.6 + k) * 0.7) + (cut * 3 if cut > 1 else 0)
        s.px(x, y, C('bracken', 3))
        s.px(x + 1, y, C('bracken', 2))
    return s


def wave(k):
    """A wave breaking over Hild: a crest rising, spilling white over her shoulders, and running off."""
    w, h = 44, 40
    s = Sprite(w, h, 22, h - 1)
    t = k / 5
    top = int(32 - 26 * math.sin(math.pi * t))
    for x in range(2, w - 2):
        crest = top + int(3 * math.sin(x * 0.5 + k))
        for y in range(max(0, crest), h - 4):
            depth = y - crest
            if depth > 6 + 4 * t and (x + y + k) % 3:
                continue
            col = C('sea', 10 if depth < 2 else 9 if depth < 4 else 8)
            if hash01(x, y, k) < 0.25:
                col = C('sea', 10)
            s.px(x, y, col)
    return s


