def write_sail_raise():
    leanto, size, pivot = read_sheet('prop_sail_leanto')
    base = leanto[('s0', '-', '0')]
    w, h = size
    frames = []
    # Folded: the sail in a heap at the foot of the wall, two oars lying across it.
    fold = Sprite(w, h, pivot[0], pivot[1])
    for y in range(h - 14, h - 2):
        for x in range(10, w - 16):
            dy = y - (h - 8)
            if abs(dy) * 3 + abs(x - w / 2) * 0.3 > 18:
                continue
            band = (y + x // 6) % 4
            fold.px(x, y, C('wool', 3 + (band == 0) - (band == 2)))
    for k, (x0, y0) in enumerate(((6, h - 6), (12, h - 12))):
        line(fold, x0, y0, x0 + w - 18, y0 - 6 + 4 * k, C('driftwood', 5 + k % 2), 1)
        line(fold, x0, y0 + 1, x0 + w - 18, y0 - 5 + 4 * k, C('driftwood', 3), 1)
    frames.append((('folded', '-', 0), rows_of(fold, size, pivot)))
    # Hauled up: the cloth rising from the foot, sagging, taking its shape frame by frame.
    for k in range(8):
        f = (k + 1) / 8
        spr = Sprite(w, h, pivot[0], pivot[1])
        for y, x in zip(*np.nonzero(base.mask)):
            yy = min(pivot[1] - 1, int(pivot[1] - (pivot[1] - y) * f + (1 - f) * 3 * math.sin(x * 0.2)))
            spr.px(x, yy, base.rgb[y, x])
        frames.append((('raise', '-', k), raw_rows(spr.outline(), size, pivot)))
    # Filling and settling: the cloth billowing out and easing back, the ropes snapping taut.
    for k in range(6):
        amp = [2, 3, 2, 1, 1, 0][k]
        src = leanto[('s0', '-', str(k % 16))]
        spr = Sprite(w, h, pivot[0], pivot[1])
        for y, x in zip(*np.nonzero(src.mask)):
            # The cloth billows; the oars and the foot rope stay put.
            sx = x + (int(round(amp * math.sin(y * 0.15))) if y < pivot[1] - 14 else 0)
            spr.px(sx, y, src.rgb[y, x])
        frames.append((('fill', '-', k), raw_rows(spr.outline(), size, pivot)))
    write('prop_sail_raise', sheet_text(
        'prop_sail_raise', 'prop', size, pivot, frames,
        {'folded': (1, 1), 'raise': (8, 9), 'fill': (6, 10)},
        HEADER + ['The sail shelter raised (Book 7 section 06, S0; decision DE-20): the torn sail folded beside',
                  'two oars; hauled up between them, the ropes tightening; the cloth filling and settling into',
                  'the lean-to (prop_sail_leanto).'],
        shadow='60x8', footprint=f'{w}x{h}'))
    # The lean-to cut away for the steerer under it: the cloth's weave and seams kept, lit warm.
    inside = []
    for k in range(16):
        src = leanto[('s0', '-', str(k))]
        spr = Sprite(w, h, pivot[0], pivot[1])
        m = src.mask
        edge = m & ~(np.roll(m, 1, 0) & np.roll(m, -1, 0) & np.roll(m, 1, 1) & np.roll(m, -1, 1))
        for y, x in zip(*np.nonzero(m)):
            keep = edge[y, x] or (x + 2 * y) % 7 == 0 or (y % 6 == 0 and x % 2 == 0)
            if not keep:
                continue
            col = src.rgb[y, x] * 0.85 + C('fire', 5) * 0.15
            spr.px(x, y, col)
        inside.append((('cut', '-', k), raw_rows(spr, size, pivot)))
    write('fx_shelter_cut', sheet_text(
        'fx_shelter_cut', 'decal', size, pivot, inside, {'cut': (16, 12, 'loop')},
        HEADER + ['The lean-to cut away while the steerer is under it (Book 7 section 06): the sail\'s edges,',
                  'seams and weave kept, warm from the fire beneath, its loose edge moving as the lean-to does.']))


def write_inside():
    size, pivot = (40, 32), (20, 30)
    frames = []
    for k, (ramp, base) in enumerate((('fleece', 3), ('seal', 2), ('wool', 3), ('earth', 3))):
        s = Sprite(36, 12, 18, 11)
        for y in range(12):
            for x in range(36):
                dx = (x - 18) / 17
                dy = (y - 6) / 5.5
                if dx * dx + dy * dy > 1 + 0.1 * math.sin(x * 0.9 + k):
                    continue
                shade = base + (1 if y < 5 else 0) - (1 if y > 8 else 0) + (hash01(x, y, k) > 0.8)
                s.px(x, y, C(ramp, shade))
        for x in range(4, 32, 5):
            s.px(x, 3 + k % 2, C(ramp, base + 2))
        frames.append((('furs', '-', k), rows_of(s, size, pivot)))
    # Oars and gear stowed along the wall: two oars leaning, a coil of rope, a bucket.
    g = Sprite(36, 28, 18, 27)
    for k in range(2):
        line(g, 4 + k * 5, 27, 10 + k * 5, 1, C('driftwood', 5), 2)
        line(g, 10 + k * 5, 1, 12 + k * 5, 0, C('driftwood', 6), 1)
    for a in range(0, 360, 12):
        r = 4
        g.px(int(24 + math.cos(math.radians(a)) * r), int(23 + math.sin(math.radians(a)) * r * 0.6), C('earth', 3))
    for y in range(20, 27):
        for x in range(30, 35):
            g.px(x, y, C('driftwood', 4 if x < 33 else 3))
    frames.append((('gear', '-', 0), rows_of(g, size, pivot)))
