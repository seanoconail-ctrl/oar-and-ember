def figure(k):
    """A still, tall figure half in the mist at the very edge of sight. Never explained."""
    w, h = 14, 56
    s = Sprite(w, h, 7, h - 1)
    for y in range(4, h):
        half = 2.2 if y < 10 else 3.5 + (y - 10) * 0.05
        for x in range(w):
            if abs(x - 7) <= half:
                fade = y > h - 16 and (x + y + k) % 2 == 0
                if not fade:
                    s.px(x, y, C('stone', 1 if abs(x - 7) < half - 1 else 2))
    for y in range(0, 5):
        for x in range(5, 9):
            s.px(x, y, C('stone', 1))
    return s


def far_light(k):
    s = Sprite(16, 16, 8, 15)
    r = 2 + (k % 4 == 1) + (k % 4 == 2)
    for y in range(-r, r + 1):
        for x in range(-r, r + 1):
            d = x * x + y * y
            if d <= r * r and ((x + y + k) % 2 == 0 or d <= 1):
                s.px(8 + x, 8 + y, C('sky', 5) if d <= 1 else C('sky', 4))
    return s


