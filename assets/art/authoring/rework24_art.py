def door(k, barred=False):
    """The broch's driftwood door on rope hinges at the doorway's west side, swinging in (north)."""
    w, h = 32, 48
    s = Sprite(w, h, w // 2, h - 1)
    open_f = k / 3
    width = int(round(28 * math.cos(open_f * math.pi / 2 * 0.95)))
    for y in range(4, h):
        for x in range(2, 2 + max(2, width)):
            plank = (x - 2) // 5
            col = C('driftwood', 4 + (plank % 2) - (y > h - 6) + (1 if x == 2 else 0))
            if (y + plank * 7) % 13 == 0:
                col = C('driftwood', 2)
            s.px(x, y - int((1 - math.cos(open_f * 1.2)) * 2), col)
        for yy in (10, h - 10):                              # the rope hinges
            s.px(1, yy, C('earth', 3))
            s.px(2, yy, C('earth', 2))
    if width > 6:
        for y in (14, h - 14):                               # the cross-battens
            for x in range(3, 2 + width - 1):
                s.px(x, y, C('driftwood', 6))
    if barred:
        for x in range(0, w):
            s.px(x, h // 2, C('driftwood', 7))
            s.px(x, h // 2 + 1, C('tar', 2))
    return s


def flap(k):
    """The shelter's flap of sail cloth, weighted with a stone: down, lifting, thrown up."""
    w, h = 20, 34
    s = Sprite(w, h, w // 2, h - 1)
    lift = [0, 0.5, 1][k]
    bottom = int(h - 1 - lift * 18)
    for y in range(2, bottom + 1):
        for x in range(3, w - 3):
            ripple = math.sin(y * 0.4 + k) * (1 + lift)
            if x + ripple < 3 or x + ripple > w - 4:
                continue
            col = C('wool', 4 - ((x + y // 3) % 5 == 0) + (y < 6))
            s.px(x, y, col)
    for x in range(8, 12):                                   # the weighting stone on its cord
        s.px(x, min(h - 1, bottom + 2), C('stone', 4))
    return s


