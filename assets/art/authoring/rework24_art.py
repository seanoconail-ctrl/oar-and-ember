# ----------------------------------------------------------------------------- the mast
MAST_TIP = (22, -40)      # from the foot (pivot): the lashing is 60 px up over a point 1 tile south-east


def mast(k, lashed):
    w, h = 44, 64
    s = Sprite(w, h, 8, h - 6)
    fx, fy = 8, h - 6
    sway = math.sin(k / 4 * math.tau) * 0.8
    tx, ty = fx + MAST_TIP[0] + sway, fy + MAST_TIP[1] - 8
    # The spar: tarred pine, split at its foot where it broke, wedged in the rock.
    for t in np.linspace(0, 1, 70):
        x = fx + (tx - fx) * t
        y = fy + (ty - fy) * t
        s.px(int(x), int(y), C('driftwood', 5 if t < 0.85 else 6))
        s.px(int(x) + 1, int(y), C('driftwood', 3))
        s.px(int(x) - 1, int(y), C('tar', 2) if t > 0.1 else C('driftwood', 2))
    for d in range(4):                                       # the splintered break at the foot
        s.px(fx - 2 + d, fy + 1 + (d % 2), C('driftwood', 6))
    # A trailing shroud, slack, down towards the water.
    for t in np.linspace(0, 1, 30):
        x = tx - 2 - 10 * t
        y = ty + 3 + 22 * t + 3 * math.sin(t * 3 + k)
        s.px(int(x), int(y), C('earth', 2))
    lx, ly = fx + MAST_TIP[0] + sway, fy + MAST_TIP[1]
    if lashed:
        b = bundle('s')
        for y, x in zip(*np.nonzero(b.mask)):
            s.px(int(lx - b.w // 2 + x), int(ly - 3 + y - 4), b.rgb[y, x])
        for yy in (-1, 2):                                   # the lashing round mast and bundle
            for x in range(-3, 4):
                s.px(int(lx + x), int(ly + yy), C('earth', 3))
    else:
        for x, y in ((0, 0), (1, 1), (-1, 2), (2, 3)):       # the cut ends hanging, frayed
            s.px(int(lx + x), int(ly + y), C('earth', 3 if y % 2 else 4))
    return s


