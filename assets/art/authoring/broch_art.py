# ------------------------------------------------------------------------------- the palette
_pal = json.load(open(f'{REPO}/assets/palette/book07.json'))
_ENTRIES = [e for e in _pal['entries'] if not e.get('reserved')]
_CODES = [e['code'] for e in _ENTRIES]
_RGB = np.array([[int(e['hex'][k:k + 2], 16) for k in (1, 3, 5)] for e in _ENTRIES], np.float32)


def codes(rgb, mask):
    """Nearest palette codes for an (h, w, 3) image where mask holds; '.' elsewhere."""
    h, w = mask.shape
    flat = rgb.reshape(-1, 3)
    d = ((flat[:, None, :] - _RGB[None, :, :]) ** 2).sum(-1)
    idx = d.argmin(1).reshape(h, w)
    out = []
    for y in range(h):
        out.append(''.join(_CODES[idx[y, x]] if mask[y, x] else '.' for x in range(w)))
    return out


def sheet_text(name, kind, size, pivot, frames, anims, about, shadow=None, facings='-',
               footprint=None, poses=None):
    w, h = size
    lines = [
        '# Generated by assets/art/authoring/broch_art.py from the approved Stage 7 mockup',
        '# (docs/art/mockup-src). Do not edit by hand: change the script and run it again.',
    ] + [f'# {a}' for a in about] + [
        f'sheet: {name}', f'kind: {kind}', 'palette: book07', f'size: {w}x{h}',
        f'pivot: {pivot[0]},{pivot[1]}', f'footprint: {footprint or f"{w}x{h}"}',
        f'facings: {facings}', 'placeholder: false',
    ]
    if shadow:
        lines.append(f'shadow: {shadow}')
    for state, (n, ticks) in anims.items():
        lines.append(f'anim.{state}: frames {n}, ticks {ticks}')
    for state, pose in (poses or {}).items():
        lines.append(f'pose.{state}: {pose}')
    for (state, facing, i), rows in frames:
        assert len(rows) == h and all(len(r) == w for r in rows), (name, state, i)
        lines.append('')
        lines.append(f'frame {state} {facing} {i}')
        lines += rows
        lines.append('end')
    return '\n'.join(lines) + '\n'


def place(spr, size, pivot):
    """A Sprite on a frame canvas: its lowest drawn row on the pivot row, its anchor column on
    the pivot column. Returns (rgb, mask)."""
    w, h = size
    rgb = np.zeros((h, w, 3), np.float32)
    mask = np.zeros((h, w), bool)
    rows = np.nonzero(spr.mask.any(1))[0]
    low = rows.max()
    dy = pivot[1] - low
    dx = pivot[0] - spr.ax
    for y, x in zip(*np.nonzero(spr.mask)):
        X, Y = x + dx, y + dy
        assert 0 <= X < w and 0 <= Y < h, ('prop does not fit', spr.w, spr.h, size)
        rgb[Y, X] = spr.rgb[y, x]
        mask[Y, X] = True
    return rgb, mask


# ---------------------------------------------------------------------------- the tower
def broch_bands():
    # No sail in the tower itself (the sails are props); a light from the upper left.
    B.SAIL['none'] = lambda x, y, z: np.zeros(np.broadcast(x, y, z).shape, bool)
    B.SUN = (0.75, 0.75)
    hz = B.raycast('none')
    S = B.surface('none', hz)
    ground = np.zeros((B.H, B.W, 3), np.float32)
    lit = np.ones((B.H, B.W), bool)
    img = B.paint_static(S, 'none', ground, lit, night=False)
    mask = S['kind'] > 0
    gy = S['y']
    top = B.CY - B.ROUT - 2
    nb = int(math.ceil((B.CY + B.ROUT + 3 - top) / BAND))
    half = B.ROUT + 4
    fw, fh = 2 * half, BAND + B.ZMAX + 8
    pv = (half, fh - 1)
    frames = []
    boxes = []
    for k in range(nb):
        y0 = top + k * BAND
        foot = y0 + BAND - 1
        m = mask & (gy >= y0) & (gy < y0 + BAND)
        rgb = np.zeros((fh, fw, 3), np.float32)
        fm = np.zeros((fh, fw), bool)
        for sy, sx in zip(*np.nonzero(m)):
            X = sx - B.CX + pv[0]
            Y = sy - foot + pv[1]
            if 0 <= X < fw and 0 <= Y < fh:
                rgb[Y, X] = img[sy, sx]
                fm[Y, X] = True
        frames.append((('wall', '-', k), codes(rgb, fm)))
        boxes.append(opaque_runs(fm))
    return frames, (fw, fh), pv, nb, top - B.CY, boxes


def opaque_runs(fm, gap=4):
    """The drawn parts of a band as boxes [x, y, w, h] (canvas pixels): one per run of columns
    with pixels, split where more than `gap` columns are empty. The game cuts a band away only
    where one of these covers the steerer, not wherever its canvas does."""
    cols = np.nonzero(fm.any(0))[0]
    runs = []
    if len(cols) == 0:
        return runs
    start = prev = int(cols[0])
    for c in [int(v) for v in cols[1:]] + [None]:
        if c is None or c - prev > gap:
            ys = np.nonzero(fm[:, start:prev + 1].any(1))[0]
            runs.append([start, int(ys[0]), prev - start + 1, int(ys[-1] - ys[0] + 1)])
            if c is not None:
                start = c
        if c is not None:
            prev = c
    return runs


def floor_s1():
    """The old flagged floor, uncovered in the cleared middle of the court and along the way to
    the door (the mockup's S1 ground), as a flat decal centred on the broch."""
    w = B.Broch('s1')
    xs, ys = w.xs, w.ys
    cell = np.floor(xs / 9 + np.sin(ys / 7) * 0.6) + np.floor(ys / 7 + np.sin(xs / 9) * 0.5) * 57
    ctone = np.array([hash01(int(c), 3) for c in cell.ravel()], np.float32).reshape(B.H, B.W)
    seam = ((xs / 9 + np.sin(ys / 7) * 0.6) % 1 < 0.13) | ((ys / 7 + np.sin(xs / 9) * 0.5) % 1 < 0.16)
    flags = (core.fbm(B.H, B.W, 18, 322) > 0.56) & w.clear & (np.hypot(xs - B.CX, ys - B.CY) < B.RIN - 6)
    col = core.ramp_lookup('stone', 3.6 + ctone * 1.6 - seam * 1.8)
    r = B.RIN
    size = (2 * r, 2 * r)
    sub = (slice(B.CY - r, B.CY + r), slice(B.CX - r, B.CX + r))
    rows = codes(col[sub], flags[sub])
    return [(('flags', '-', 0), rows)], size, (r, r)


# ---------------------------------------------------------------------------- the sails
def sail_sprite(stage):
    """The sail (with its posts, the oar ridge and, at S1, the drying lines) as one prop."""
    hz = B.raycast(stage)
    S = B.surface(stage, hz)
    img = B.paint_static(S, stage, np.zeros((B.H, B.W, 3), np.float32), np.ones((B.H, B.W), bool))
    m = S['kind'] == 5
    w = B.Broch(stage)
    canvas = np.zeros((B.H, B.W, 3), np.float32)
    cm = np.zeros((B.H, B.W), bool)
    canvas[m] = img[m]
    cm |= m
    for (_, spr, x, y, hgt, kind) in w.props:
        if kind != 'post':
            continue
        core.stamp(canvas, spr, x, y)
        core.stamp_mask(cmf := np.zeros((B.H, B.W), np.float32), spr, x, y)
        cm |= cmf > 0
    if stage == 's0':
        # The broken oar laid along the front as the ridge.
        oar = B._oar(70, broken=True)
        core.stamp(canvas, oar, (B.LEAN_X0 + B.LEAN_X1) / 2 + 2, B.LEAN_Y + 1 - 27)
        core.stamp_mask(om := np.zeros((B.H, B.W), np.float32), oar, (B.LEAN_X0 + B.LEAN_X1) / 2 + 2, B.LEAN_Y + 1 - 27)
        cm |= om > 0
        foot_y = B.LEAN_Y + 1
    else:
        # The ridge pole between the posts at the eave, and the drying lines with split fish.
        for x in range(166, 309):
            for dy, step in ((0, 5), (1, 3)):
                y = 168 - 48 + dy - 1
                canvas[y, x] = C('driftwood', step)
                cm[y, x] = True
        for (a, b) in w.lines:
            n = 40
            for k in range(n + 1):
                f = k / n
                x = a[0] + (b[0] - a[0]) * f
                yy = a[1] + (b[1] - a[1]) * f - (a[2] + (b[2] - a[2]) * f - 2.5 * math.sin(math.pi * f))
                canvas[int(yy), int(x)] = C('wool', 3)
                cm[int(yy), int(x)] = True
        for (x, y, z, ph) in w.fish:
            for dy in range(5):
                for dx in (0, 1):
                    yy, xx = int(y - z) + dy, int(x) + dx
                    canvas[yy, xx] = C('stone_warm', 4 - dy * 0.5 - dx)
                    cm[yy, xx] = True
        foot_y = 168
    ys, xs = np.nonzero(cm)
    spr = Sprite(xs.max() - xs.min() + 3, ys.max() - ys.min() + 3)
    for y, x in zip(ys, xs):
        spr.px(x - xs.min() + 1, y - ys.min() + 1, canvas[y, x])
    spr.ax = spr.w // 2
    spr.ay = int(foot_y - ys.min() + 1)
    spr.outline()
    # Where its anchor stands, in the mockup's world (the broch's centre is (CX, CY)).
    at = (xs.min() - 1 + spr.ax, foot_y)
    return spr, at


# ---------------------------------------------------------------------------- camp props
def fire_ring(n, radius, ry, kerb):
    spr = Sprite(2 * radius + 14, 2 * ry + 14, radius + 7, 2 * ry + 10)
    for k in range(n):
        a = k / n * math.tau + 0.2
        s = Sprite(9, 7, 4, 5)
        if kerb:
            stone(s, 4.5, 3.5, 3.6, 2.4, 'stone', 6, seed=k * 7 + 3)
        else:
            blob(s, 4.5, 3.5, 3.4 + hash01(k, 3) * 0.8, 2.5, 'stone', 5 + (k % 3 == 0))
        x = spr.ax + math.cos(a) * radius
        y = spr.ay - ry - 2 + math.sin(a) * ry
        for yy, xx in zip(*np.nonzero(s.mask)):
            spr.px(int(round(x)) - s.ax + xx, int(round(y)) - s.ay + yy, s.rgb[yy, xx])
    # Ash and charcoal in the ring.
    for y in range(spr.h):
        for x in range(spr.w):
            if ((x - spr.ax) / (radius - 3)) ** 2 + ((y - (spr.ay - ry - 2)) / (ry - 1.5)) ** 2 < 1 and not spr.mask[y, x]:
                spr.px(x, y, C('smoke', 1 + (hash01(x, y, 5) < 0.3)))
    return spr.outline()


def laid_fire():
    """Driftwood laid crossed in the ring, ready to light; also the logs under the flames."""
    spr = Sprite(20, 8, 10, 6)
    for k in range(-7, 8):
        spr.px(10 + k, 4 - round(k * 0.25), C('driftwood', 4 + (k > 0)))
        spr.px(10 + k, 3 + round(k * 0.25), C('driftwood', 3 + (k < 0)))
        spr.px(10 + k, 5, C('tar', 1 + (k % 2)))
    return spr.outline()


def skin_post():
    post = B._post(30)
    skin = B._waterskin()
    spr = Sprite(post.w + 8, post.h + 2, post.ax + 4, post.ay + 1)
    for yy, xx in zip(*np.nonzero(post.mask)):
        spr.px(xx + 4, yy + 1, post.rgb[yy, xx])
    for yy, xx in zip(*np.nonzero(skin.mask)):
        spr.px(xx + 4 + post.ax - skin.ax + 2, yy + 9, skin.rgb[yy, xx])
    return spr


