"""Builds the old broch and the first camp for the game (Stage 7) from the approved mockup's own
geometry and painting (docs/art/mockup-src/broch.py, scene_broch.py; decision DD-11: built to the
mockup), as palette-coded sheets the art compiler reads:

- bld_broch (kind building): the drystone tower, ray-cast in the game's 3/4 view and painted as
  the mockup paints it, lit from the upper left with no baked cast shadow (the game casts its own
  and grades the light by the hour). It is cut into bands of ground rows, one frame each, so that
  people sort in front of and behind each part of the wall (a person in the court is drawn over
  the north wall and under the south wall); the scene places band k at the broch's centre, its
  foot BAND rows further south than band k - 1 (assets/art/buildings.json).
- decal_broch: the old flagged floor uncovered in the court at S1.
- prop_sail_leanto (S0) and prop_sail_roof (S1): the torn sail as a lean-to on a broken oar, and
  stretched over the north of the court on a ridge pole and two posts, with the drying lines.
- prop_camp: the camp's things (sea chest, cask, salvage bags, an oar, bedding, the water skin on
  its post, the driftwood door, the fire ring, the kerbed hearth and its pot, the laid fire, the
  woodpile in four sizes).
- fx_fire: flames (6 frames), embers, smoke puffs, sparks and moths (kind decal: lit, no outline).
- actor_sheep: a ewe grazing and lying (Book 7 section 14, Life), four facings.

    python3 assets/art/authoring/broch_art.py && npm run art:compile

Colours are the mockup's, which are the palette's ramps; each pixel is written as the nearest
palette entry that is not a reserved accent.
"""
