# ---------------------------------------------------------------------------- fire and life
def fire_frames():
    """Flames, embers, smoke puffs, sparks and moths on 24 x 30 frames, pivot at the fire's base."""
    size, pv = (24, 30), (12, 26)
    out = []
    anims = {}

    def frame(draw):
        f = np.zeros((size[1], size[0], 3), np.float32)
        buf = np.full((size[1], size[0], 3), -1.0, np.float32)
        draw(buf)
        m = buf[..., 0] >= 0
        f[m] = buf[m]
        return codes(f, m)
    import scene_broch as SB
    n = 6
    for i in range(n):
        t = i / n * core.LOOP / 9 * 3
        out.append((('flames', '-', i), frame(lambda b, t=t: SB.draw_fire(b, pv[0], pv[1] - 2, t, 1.0, logs=False))))
    anims['flames'] = (n, 5)
    for i in range(2):
        def embers(b, i=i):
            for k in range(-5, 6):
                glow = 0.5 + 0.5 * math.sin(k * 1.9 + i * 2.2)
                b[pv[1] - 1, pv[0] + k] = C('fire', 1 + glow * 3)
                if abs(k) < 3:
                    b[pv[1] - 2, pv[0] + k] = C('fire', 2 + glow * 2)
        out.append((('embers', '-', i), frame(embers)))
    anims['embers'] = (2, 20)
    for i in range(4):
        def smoke(b, i=i):
            rad = 1.5 + i * 1.6
            cy = pv[1] - 6 - i * 2
            for y in range(size[1]):
                for x in range(size[0]):
                    d = math.hypot(x - pv[0], (y - cy) * 1.1)
                    if d < rad and core.bayer(size[1], size[0])[y, x] < 0.55 - i * 0.08:
                        b[y, x] = C('smoke', 4 - (y > cy) - i * 0.4)
        out.append((('smoke', '-', i), frame(smoke)))
    anims['smoke'] = (4, 1)
    for i in range(2):
        def spark(b, i=i):
            b[pv[1] - 2, pv[0]] = C('fire', 7 if i == 0 else 5)
            if i == 0:
                b[pv[1] - 3, pv[0]] = C('fire', 5)
        out.append((('spark', '-', i), frame(spark)))
    anims['spark'] = (2, 1)
    for i in range(2):
        def moth(b, i=i):
            y, x = pv[1] - 2, pv[0]
            b[y, x] = C('wool', 5)
            if i == 0:
                b[y - 1, x - 1] = C('wool', 4)
                b[y - 1, x + 1] = C('wool', 4)
            else:
                b[y, x - 1] = C('wool', 3)
                b[y, x + 1] = C('wool', 3)
        out.append((('moth', '-', i), frame(moth)))
    anims['moth'] = (2, 3)
    return out, size, pv, anims


def sheep_frames():
    """A half-wild ewe (Book 10: the starting flock): grazing with the head dipping and lifting,
    and lying chewing; drawn facing east, mirrored west; south and north use them by side."""
    size, pv = (28, 22), (14, 19)
    frames = []
    graze = []
    for frac in (0.06, 0.1, 0.3, 0.35):
        graze.append(fx.sheep(frac * core.LOOP, 0.0, True))
    lie = []
    for i in range(2):
        spr = sheep_lying(i)
        lie.append(spr)
    for facing, flip in (('s', False), ('n', True), ('e', False), ('w', True)):
        for i, spr in enumerate(graze):
            s = mirror(spr) if flip else spr
            rgb, m = place(s, size, pv)
            frames.append((('graze', facing, i), codes(rgb, m)))
        for i, spr in enumerate(lie):
            s = mirror(spr) if flip else spr
            rgb, m = place(s, size, pv)
            frames.append((('lie', facing, i), codes(rgb, m)))
    return frames, size, pv, {'graze': (4, 36), 'lie': (2, 48)}


def sheep_lying(i):
    import scene_broch as SB
    return SB.sheep_lying(i * core.LOOP / 4, 0.0)


def mirror(spr):
    s = Sprite(spr.w, spr.h, spr.w - 1 - spr.ax, spr.ay)
    s.rgb = spr.rgb[:, ::-1].copy()
    s.mask = spr.mask[:, ::-1].copy()
    return s


def write(name, text):
    with open(f'{SHEETS}/{name}.txt', 'w') as f:
        f.write(text)
    print(f'wrote {SHEETS}/{name}.txt')


def main():
    # The tower in bands.
    frames, size, pv, nb, top, boxes = broch_bands()
    write('bld_broch', sheet_text(
        'bld_broch', 'building', size, pv, frames, {'wall': (nb, 1)},
        ['The old broch on the machair (Book 4 SK_BROCH; Book 9 section 04): a roofless drystone tower,',
         'its court nine tiles across inside a wall a tile thick, the door on the south under a heavy',
         f'lintel, a breach in the north. Frames are bands of {BAND} ground rows, north to south; band k sits',
         f'with its foot {BAND} x k + {BAND - 1} rows below the tower\'s top edge ({top} from its centre).',
         'Architecture is drawn like terrain: no ink outline (decision S7-12).']))
    with open(f'{REPO}/assets/art/buildings.json', 'w') as f:
        json.dump({'about': 'Buildings drawn in bands of ground rows (assets/art/authoring/broch_art.py): '
                            'band k of a building sheet is placed at the building\'s centre x, its foot '
                            'top + band x k + band - 1 rows from its centre y. boxes: the drawn parts of '
                            'each band [x, y, w, h] on its canvas, for the cutaway.',
                   'bld_broch': {'band': BAND, 'top': top, 'bands': nb, 'boxes': boxes}}, f, indent=2)
        f.write('\n')
    # The flagged floor.
    frames, size, pv = floor_s1()
    write('decal_broch', sheet_text(
        'decal_broch', 'decal', size, pv, frames, {'flags': (1, 1)},
        ['The broch\'s old flagged floor, uncovered when the court was cleared for the sail shelter (S1),',
         'centred on the broch; flat, under people.']))
    # The sails.
    for name, stage, about in (('prop_sail_leanto', 's0', 'S0: the torn sail as a lean-to against the north-west inner wall on a broken oar and two forked sticks.'),
                               ('prop_sail_roof', 's1', 'S1: the sail stretched over the north of the court on a ridge pole and two posts, the eave 46 px up; drying lines of split fish.')):
        spr, at = sail_sprite(stage)
        print(f'{name}: anchor {at[0] - B.CX:+.1f}, {at[1] - B.CY:+.1f} px from the broch centre')
        sz = (spr.w + 2, spr.h + 2)
        pvt = (spr.ax + 1, sz[1] - 1)
        rgb, m = place(spr, sz, pvt)
        write(name, sheet_text(name, 'prop', sz, pvt, [((stage, '-', 0), codes(rgb, m))], {stage: (1, 1)},
                               [about, 'From the mockup\'s ray-cast sail, with its posts.'],
                               shadow=f'{max(8, sz[0] // 2)}x6'))
    # The camp's things.
    props = camp_props()
    size, pv = (48, 54), (24, 52)
    frames = []
    anims = {}
    for state, sprites in props.items():
        anims[state] = (len(sprites), 1)
        for i, spr in enumerate(sprites):
            # Pad first, so the ink outline closes where a drawing touched its own canvas.
            rgb, m = place(spr.padded(1).outline(), size, pv)
            frames.append(((state, '-', i), codes(rgb, m)))
    write('prop_camp', sheet_text(
        'prop_camp', 'prop', size, pv, frames, anims,
        ['The first camp\'s things (Book 7 section 06, S0 and S1): salvage, bedding, the water skin on',
         'its post, the driftwood door, the fire ring and the kerbed hearth, a laid fire, the pot, and',
         'the woodpile in four sizes (as the camp\'s driftwood grows).'], shadow='22x6'))
    frames, size, pv, anims = fire_frames()
    write('fx_fire', sheet_text(
        'fx_fire', 'decal', size, pv, frames, anims,
        ['The camp fire\'s flames, embers, smoke puffs, sparks and moths at night (Book 7 section 14:',
         'fire flickers and throws light; smoke bends in the wind). Lit by the fire\'s own pool.']))
    frames, size, pv, anims = sheep_frames()
    write('actor_sheep', sheet_text(
        'actor_sheep', 'sprite', size, pv, frames, anims,
        ['A half-wild ewe of the starting flock (Book 10 section 03), grazing and lying, from the',
         'mockup. South and north use the side views.'], shadow='16x4', facings='s n e w',
        poses={'lie': 'lying'}))


if __name__ == '__main__':
    main()
