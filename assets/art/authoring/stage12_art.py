BAYER = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]
BAYER = [[v / 16 for v in row] for row in BAYER]

#: Ramp and base step for each dye (Book 7 section 04: madder red, woad blue, weld yellow, undyed).
DYE = {'madder': ('madder', 3.4), 'woad': ('woad', 3.3), 'weld': ('trefoil', 2.5)}
UNDYED = ('wool', 4.4)


def marks():
    """Every mark content offers: (state suffix, pattern, dye or None)."""
    out = []
    for p in LAUNCH['marks']['patterns']:
        if not p['dyed']:
            out.append((p['key'], p['key'], None))
            continue
        for d in LAUNCH['marks']['dyes']:
            out.append((f"{p['key']}_{d['key']}", p['key'], d['key']))
    return out


def dyed(pattern, u, v):
    """Whether the cloth at (u, v), 0..1 across and down the sail, takes the dye."""
    if pattern == 'plain':
        return False
    if pattern == 'stripes_broad':
        return int(u * 5) % 2 == 1
    if pattern == 'stripes_narrow':
        return int(u * 9) % 2 == 1
    if pattern == 'lozenge':
        a = math.floor(u * 4 + v * 3.4)
        b = math.floor(u * 4 - v * 3.4)
        return (a + b) % 2 == 0
    if pattern == 'quartered':
        return (u < 0.5) != (v < 0.5)
    grid = DEVICES[pattern]
    # The device in the middle of the cloth, a little above centre.
    gu = (u - 0.16) / 0.68
    gv = (v - 0.1) / 0.74
    if not (0 <= gu < 1 and 0 <= gv < 1):
        return False
    return grid[int(gv * 16)][int(gu * 16)] == '#'


def sail(pattern, dye, k, drop=1.0):
    """The sail set (drop 1) or dropping (drop < 1: the cloth unrolled to that share, the rest still
    rolled at its foot), billowing in the wind (k the wind frame)."""
    s = Sprite(SAW, SAH, SAP[0], SAP[1])
    ox, oy = PX - SAP[0], PY - SAP[1]          # canvas = hull coordinates minus (ox, oy)
    billow = (0.82 + 0.18 * math.sin(k / 4 * math.tau)) * drop
    deep = SAIL_H * drop
    cloth = Sprite(SAW, SAH, SAP[0], SAP[1])
    n_u, n_v = SAIL_W * 4, int(deep * 4) + 1
    for j in range(n_v + 1):
        v = j / max(1, n_v)
        vv = v * drop                                    # where on the whole cloth this is
        for i in range(n_u + 1):
            u = i / n_u
            belly = math.sin(math.pi * u) * math.sin(math.pi * min(1.0, v))
            inset = billow * 2.2 * math.sin(math.pi * v)
            xl = PX - SAIL_W / 2 - 1.5 * v + inset
            xr = PX + SAIL_W / 2 + 1.5 * v - inset
            # A ripple running down the leech, and the foot lifted in the middle by the wind.
            flutter = math.sin(k / 4 * math.tau + v * 5.0) * 0.7 * (abs(u - 0.5) * 2) ** 3
            x = xl + (xr - xl) * u + flutter
            y = YARD + 2 + v * (deep - billow * 4.5 * math.sin(math.pi * u))
            ramp, base = DYE[dye] if dye is not None and dyed(pattern, u, vv) else UNDYED
            px_, py_ = int(math.floor(x - ox)), int(math.floor(y - oy))
            # The belly catches the light, ordered-dithered so the cloth has no hard-edged patches.
            dith = (BAYER[py_ % 4][px_ % 4] - 0.5) * 0.8
            shade = base + billow * 0.75 * belly - 0.45 + (0.5 - u) * 0.45 - v * 0.3 + dith
            seam = (u * 7) % 1.0 < 0.035 and 0.04 < u < 0.96
            if seam:
                shade -= 0.9                              # the panels' seams
            if u < 0.02 or u > 0.98 or (drop >= 1 and v > 0.975):
                shade = base - 1.5                        # the bolt rope
            cloth.px(px_, py_, C(ramp, shade))
    if drop < 1:
        # The rest still rolled up at the foot: a bundle across the cloth.
        yb = YARD + 2 + deep
        for x in range(int(PX - SAIL_W / 2), int(PX + SAIL_W / 2) + 1):
            for d in range(3):
                cloth.px(x - ox, int(yb + d - oy), C(UNDYED[0], 3.8 - d * 0.6 + ((x // 3) % 2) * 0.4))
    cloth.outline()
    s.rgb[cloth.mask] = cloth.rgb[cloth.mask]
    s.mask |= cloth.mask
    yard(s, YARD)
    # The sheets from the foot's corners down to the gunwales (set sail only).
    if drop >= 1:
        for t, sx in ((0.3, PX - SAIL_W / 2 - 1.5), (0.7, PX + SAIL_W / 2 + 1.5)):
            _, near, _ = hull_lines(t)
            line(s, sx - ox, YARD + 2 + SAIL_H - oy, xt(t) - ox, near - 2 - oy, C('tar', 2.0))
    return s


def yard(s, y, bundle=False):
    """The yard across the mast at height `y` (hull coordinates), with the sail furled on it."""
    ox, oy = PX - SAP[0], PY - SAP[1]
    for x in range(PX - SAIL_W // 2 - 4, PX + SAIL_W // 2 + 5):
        taper = abs(x - PX) > SAIL_W // 2
        s.px(x - ox, y - oy, C('driftwood', 4.6 if not taper else 4.0))
        if not taper:
            s.px(x - ox, y + 1 - oy, C('driftwood', 2.8))
        s.px(x - ox, y - 1 - oy, C('ink', 1))
        if bundle and abs(x - PX) <= SAIL_W // 2:
            for d in range(4):
                s.px(x - ox, y + 2 + d - oy, C('wool', 4.6 - d * 0.5 + ((x // 3) % 2) * 0.4))
            s.px(x - ox, y + 6 - oy, C('ink', 1))
            if x % 11 == 0:
                for d in range(5):
                    s.px(x - ox, y + 1 + d - oy, C('tar', 2))          # a gasket
    # The parrel round the mast.
    for d in (-1, 0, 1, 2):
        s.px(PX + d - ox, y - oy, C('tar', 1.5))


def hoist(k):
    """The yard going up the mast with the sail still furled on it (k: 0 low to 3 at the head)."""
    s = Sprite(SAW, SAH, SAP[0], SAP[1])
    _, near, _ = hull_lines(0.5)
    y = int(near - 14 + (YARD - (near - 14)) * (k + 1) / 4)
    yard(s, y, bundle=True)
    # The halyard from the masthead to the yard.
    ox, oy = PX - SAP[0], PY - SAP[1]
    for yy in range(16, y):
        s.px(PX + 3 - ox, yy - oy, C('tar', 2))
    return s


