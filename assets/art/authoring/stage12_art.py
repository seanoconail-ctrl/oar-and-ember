def smoke(k):
    """Smoke rising from Carrick Landing's fires and leaning downwind (6 frames, a loop)."""
    w, h = 32, 48
    s = Sprite(w, h, w // 2, h - 1)
    for j in range(16):
        f = j / 15
        rise = (j * 2.6 + k * 2.6 / 6 * 6 / 6 * 2) % 42
        y = h - 2 - rise
        x = w // 2 + rise * 0.28 + math.sin(rise * 0.25 + k) * 1.5
        r = 1.2 + rise * 0.07
        for yy in range(int(y - r), int(y + r) + 1):
            for xx in range(int(x - r), int(x + r) + 1):
                if (xx - x) ** 2 + (yy - y) ** 2 <= r * r and hash01(xx, yy, k + 11) > rise / 70:
                    s.px(xx, yy, C('smoke', 4.6 - rise * 0.03 + ((xx + yy) % 2) * 0.6))
    # The fire's glow at its foot.
    for d in (-1, 0, 1):
        s.px(w // 2 + d, h - 1, C('fire', 4 + (d == 0)))
    return s


