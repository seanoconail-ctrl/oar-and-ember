def token(pattern, dye, k):
    """The household's boat on the chart: a small hull with its sail in the household's mark."""
    w, h = 24, 16
    s = Sprite(w, h, w // 2, h - 2)
    bob = k
    for x in range(4, 20):
        u = (x - 4) / 15
        depth = 2 + int(math.sin(math.pi * u) * 1.5)
        for d in range(depth):
            s.px(x, 12 - d + bob, C('tar', 4 - d * 0.7))
    s.px(3, 9 + bob, C('tar', 3))
    s.px(20, 9 + bob, C('tar', 3))
    for y in range(2, 11):
        s.px(12, y + bob, C('driftwood', 4))
