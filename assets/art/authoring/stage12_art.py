def raw(spr, size, pivot):
    return S11.raw_rows(spr, size, pivot)


def cut(spr, below):
    """Drops every pixel at or below row `below` (the water hides them)."""
    out = Sprite(spr.w, spr.h, spr.ax, spr.ay)
    out.rgb[:below] = spr.rgb[:below]
    out.mask[:below] = spr.mask[:below]
    return out


# ======================================================================= the boat afloat
def afloat(k):
    """The patched hull afloat: cut at the waterline, with the water lapping along it."""
    hull = S11.hull('patched', k)
    s = cut(hull, WL)
    under = np.nonzero(hull.mask[WL])[0]
    if len(under) == 0:
        return s
    xa, xb = int(under.min()), int(under.max())
    for x in range(xa - 6, xb + 7):
        inside = xa <= x <= xb
        # The lap line along the hull: lit swash, broken where the swell runs past (4 frames).
        phase = (x * 0.31 + k * 1.6)
        lit = math.sin(phase) > -0.35
        if inside:
            s.px(x, WL, C('sea', 9 if lit else 7))
            if hash01(x, k, 3) < 0.35:
                s.px(x, WL - 1, C('sea', 8))                     # spray caught on the planking
            # The hull's dark reflection in the water under it, broken by ripples.
            for d in (1, 2):
                if (x + d + k) % 3 != 0:
                    s.px(x, WL + d, C('sea', 2 if d == 1 else 3))
        else:
            # Ripples spreading off stem and stern.
            dist = (xa - x) if x < xa else (x - xb)
            if (dist + k) % 3 == 0:
                s.px(x, WL + (dist + k) % 2, C('sea', 8))
    return s


def mast(k):
    """The rig standing with the yard hoisted away: mast, shrouds, stays and the pennant."""
    s = Sprite(SW, SH, PX, PY)
    _, near, far = hull_lines(0.5)
    step = int(far) + 3
    top = 14
    for y in range(top, step):
        f = (y - top) / (step - top)
        s.px(PX - 1, y, C('tar', 1.4))
        s.px(PX, y, C('driftwood', 5.2 - f * 1.4))
        s.px(PX + 1, y, C('driftwood', 3.3 - f * 0.8))
        s.px(PX + 2, y, C('tar', 1.4))
    s.px(PX, top - 1, C('tar', 2))
    s.px(PX + 1, top - 1, C('tar', 2))
    for (t, side) in ((0.43, 'near'), (0.57, 'near'), (0.45, 'far'), (0.55, 'far')):
        _, nr, fr = hull_lines(t)
        line(s, PX + 0.5, top + 2, xt(t), (nr if side == 'near' else fr) - 1,
             C('tar', 1.6 if side == 'near' else 2.4))
    _, nb, _ = hull_lines(0.97)
    _, ns, _ = hull_lines(0.03)
    line(s, PX + 1, top + 1, X1 - 2, nb - 18, C('tar', 2.2))
    line(s, PX, top + 1, X0 + 3, ns - 18, C('tar', 2.2))
    for j in range(10):
        wave = math.sin(k / 4 * math.tau - j * 0.7) * (1 + j * 0.15)
        s.px(PX + 2 + j, int(top + 1 + wave * 0.6 + j * 0.15), C('madder', 4 - (j > 6)))
        if j < 6:
            s.px(PX + 2 + j, int(top + 2 + wave * 0.6 + j * 0.15), C('madder', 3))
    return s


def oar_afloat():
    """The steering oar on the quarter, its blade under the water and the water round its loom."""
    s = cut(S11.steering_oar(), WL)
