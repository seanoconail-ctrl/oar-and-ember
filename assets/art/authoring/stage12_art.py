def coast_fields():
    """Land as a field of heights over the chart (> 0 is land), from Book 4 section 01's shape:
    the Irish coast along the south-west, the Scottish coast closing the north-east with Loch Arra
    reaching into it, the northern isles past Blue Men's Sound, Inis Rón, and Skarvholm in the
    middle of the sea."""
    ys, xs = np.mgrid[0:MH, 0:MW].astype(np.float32)
    n1 = value_noise(MH, MW, 24, 1201) - 0.5
    n2 = value_noise(MH, MW, 9, 1202) - 0.5
    wob = n1 * 26 + n2 * 9
    # The Irish shore: a line from the west edge to Saltvik and on south-east, with Kilbrecc's
    # headland, Carrick's bay and Saltvik's harbour.
    shore = (198 + xs * 0.17 + 18 * np.exp(-((xs - 232) / 26) ** 2)          # Carrick's bay
             - 22 * np.exp(-((xs - 124) / 18) ** 2)                            # Kilbrecc's headland
             - 10 * np.exp(-((xs - 46) / 22) ** 2)                             # Dún Fiach's point
             + 14 * np.exp(-((xs - 372) / 12) ** 2))                           # Saltvik's harbour
    shore = np.where(xs > 430, shore + (xs - 430) * 1.6, shore)
    irish = (ys - shore + wob) / 10
    # The Scottish coast: land east of a line running south-west from the top, cut by Loch Arra.
    edge = 392 + ys * 0.55 + 30 * np.exp(-((ys - 200) / 30) ** 2)            # Crowwick's headland
    # South of Crowwick the Scottish shore turns east along the bottom of the map's north-east.
    turn = 238 + (xs - 520) * -0.18 + wob * 0.6
    scot = np.minimum((xs - edge + wob) / 10, (turn - ys) / 10)
    # Loch Arra: a sea loch reaching east into the hills to Glen Arra at its head.
    lx = PLACES['GLEN_ARRA']['x']
    axis = 126 + (xs - 470) * 0.1 + 5 * np.sin((xs - 440) / 13) + n2 * 6
    loch = np.exp(-((ys - axis) / (3 + np.clip((lx - xs) / 30, 0, 4))) ** 2) * (xs < lx)
    scot = scot - loch * 30
    # Islands: Skarvholm, Inis Rón, the northern isles past Blue Men's Sound (Kaldness among them).
    def isle(cx, cy, rx, ry, amp=1.0):
        d = np.sqrt(((xs - cx) / rx) ** 2 + ((ys - cy) / ry) ** 2)
        return (1 - d) * 4 + wob * 0.09 * amp
    isles = np.maximum.reduce([
        isle(SK['x'], SK['y'], 17, 11),
        isle(PLACES['ISLE_INISRON']['x'], PLACES['ISLE_INISRON']['y'], 9, 6),
        isle(PLACES['ISLE_KALDNESS']['x'], PLACES['ISLE_KALDNESS']['y'], 40, 22),
        isle(150, 60, 26, 14),
        isle(214, 92, 20, 12),
        isle(108, 104, 14, 9),
        isle(SK['x'] + 30, SK['y'] - 22, 4, 3, 0.3),                             # a skerry
        isle(SK['x'] - 26, SK['y'] + 16, 3, 2, 0.3),
    ])
    return np.maximum.reduce([irish, scot, isles])


def chamfer(target):
    """Distance in pixels (3-4 chamfer, divided by 3) from each pixel to the nearest `target`."""
    big = 1e9
    d = np.where(target, 0.0, big).astype(np.float64)
    h, w = d.shape
    for y in range(h):
        row = d[y]
        up = d[y - 1] if y > 0 else None
        for x in range(w):
            v = row[x]
            if x > 0:
                v = min(v, row[x - 1] + 3)
            if up is not None:
                v = min(v, up[x] + 3)
                if x > 0:
                    v = min(v, up[x - 1] + 4)
                if x < w - 1:
                    v = min(v, up[x + 1] + 4)
            row[x] = v
    for y in range(h - 1, -1, -1):
        row = d[y]
        dn = d[y + 1] if y < h - 1 else None
        for x in range(w - 1, -1, -1):
            v = row[x]
            if x < w - 1:
                v = min(v, row[x + 1] + 3)
            if dn is not None:
                v = min(v, dn[x] + 3)
                if x < w - 1:
                    v = min(v, dn[x + 1] + 4)
                if x > 0:
                    v = min(v, dn[x - 1] + 4)
            row[x] = v
    return d / 3


def codes_big(rgb):
    """Palette codes for a whole opaque frame, a band of rows at a time (memory)."""
    out = []
    for y0 in range(0, rgb.shape[0], 24):
        band = rgb[y0:y0 + 24]
        out += codes(band, np.ones(band.shape[:2], bool))
    return out


def chart(variant):
    """The chart (variant 'chart'), its sea's sheen ('lit') and in cloud shadow ('shade')."""
    land = coast_fields()
    ys, xs = np.mgrid[0:MH, 0:MW].astype(np.float32)
    is_land = land > 0
    # Distance from the coast, in pixels, roughly (for shallows and the surf line).
    to_land = chamfer(is_land)
    to_sea = chamfer(~is_land)
    hn = value_noise(MH, MW, 22, 1301) * 0.7 + value_noise(MH, MW, 7, 1303) * 0.3
    hn2 = value_noise(MH, MW, 30, 1304)
    sea_n = value_noise(MH, MW, 6, 1302)
    out = np.zeros((MH, MW, 3), np.float32)
    lit = variant == 'lit'
    shade = -0.9 if variant == 'shade' else 0.0
    bayer = np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]], np.float32) / 16
    dz = np.sqrt((xs - SK['x']) ** 2 + ((ys - SK['y']) * 1.3) ** 2)
    for y in range(MH):
        for x in range(MW):
            b = bayer[y % 4, x % 4]
            if is_land[y, x]:
                inland = to_sea[y, x]
                h = hn[y, x]
                heath = hn2[y, x]
                if inland < 1.5:
                    col = C('ink', 1)                                          # the drawn coast
                elif inland < 3:
                    col = C('sand', 3.6 + shade + (b > 0.5) * 0.6)             # strand and shingle
                elif h > 0.78 and inland > 18:
                    col = C('stone', 3.6 + (h - 0.78) * 12 + shade + (b - 0.5) * 0.8)   # the hills
                elif heath + (b - 0.5) * 0.06 > 0.64 and inland > 8:
                    col = C('bracken', 0.6 + (heath - 0.62) * 4 + shade + (b - 0.5) * 1.1)       # heath and bog
                else:
                    g = 3.0 + h * 2.2 + (b - 0.5) * 0.9
                    col = C('moss' if h < 0.55 else 'grass', g + shade)
                # Hill hatching: short strokes on the slopes facing away from the light.
                if inland > 6 and h > 0.6 and (x + 2 * y) % 9 == 0 and hn[y, min(MW - 1, x + 2)] < h:
                    col = col * 0.82
                out[y, x] = col
                continue
            d = to_land[y, x]
            deep = min(1.0, d / 40)
            step = 6.4 - deep * 3.6 + (sea_n[y, x] - 0.5) * 0.8 + (b - 0.5) * 0.9
            # Rán's Reach: the deep water round Skarvholm runs darker.
            if 22 < dz[y, x] < 70:
                step -= 0.7 * math.sin(math.pi * (dz[y, x] - 22) / 48)
            if d < 2.5:
                step = 9.0 if (x + y) % 3 else 8.0                             # the surf line
            elif d < 5:
                step = 7.2 + (b > 0.5)
            if lit and d >= 2.5:
                step += 1.3                                                    # the sheen
            out[y, x] = C('sea', step + shade)
    # The frame: carved timber round the chart (Book 7 section 10).
    for y in range(MH):
        for x in range(MW):
            e = min(x, y, MW - 1 - x, MH - 1 - y)
            if e < 5:
                out[y, x] = C('tar', 1.0) if e in (0, 4) else C('driftwood', 4.4 - e * 0.5 + ((x + y) // 6 % 2) * 0.6)
    return out


def fog():
    """The mist over what is not yet known: soft, layered and drifting (smoke ramp)."""
    n = value_noise(MH, MW, 40, 1401) * 0.6 + value_noise(MH, MW, 12, 1402) * 0.4
    out = np.zeros((MH, MW, 3), np.float32)
    bayer = np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]], np.float32) / 16
    for y in range(MH):
        for x in range(MW):
            out[y, x] = C('smoke', 1.6 + n[y, x] * 2.6 + (bayer[y % 4, x % 4] - 0.5) * 0.8)
    return out


