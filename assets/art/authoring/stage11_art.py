def tangle(k):
    """The wreck's mast and yard fouled across the skerry's rocks, the torn sail flogging."""
    w, h = 72, 40
    s = Sprite(w, h, w // 2, h - 3)
    line(s, 6, 30, 64, 22, C('driftwood', 4.6), 2)                 # the mast, lying
    line(s, 14, 18, 52, 34, C('driftwood', 4), 2)                  # the yard across it
    for j in range(5):
        line(s, 20 + j * 7, 24 - j, 26 + j * 9, 34 + (j % 2), C('tar', 2.2))      # lines
    # The sail: a torn, heaped strip, its loose end lifting and falling.
    for x in range(22, 48):
        u = (x - 22) / 26
        lift = math.sin(k / 4 * math.tau + u * 3) * 3 * u
        for d in range(5 - int(u * 2)):
            s.px(x, int(23 - d - lift * (d / 4)), C('wool', 4.4 - d * 0.35 + ((x // 4) % 2) * 0.3))
    for x in range(10, 60, 3):
        s.px(x, 31 + (x % 2), C('kelp', 3))
    return s.outline()


