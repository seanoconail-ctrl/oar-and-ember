def rows_of(spr, size, pivot, outline=True):
    s = spr.padded(1)
    if outline:
        s.outline()
    rgb, mask = place(s, size, pivot)
    return codes(rgb, mask)


def raw_rows(spr, size, pivot):
    """A sprite placed by its own anchor (not its lowest row) on the canvas."""
    w, h = size
    rgb = np.zeros((h, w, 3), np.float32)
    mask = np.zeros((h, w), bool)
    dx, dy = pivot[0] - spr.ax, pivot[1] - spr.ay
    for y, x in zip(*np.nonzero(spr.mask)):
        X, Y = x + dx, y + dy
        if 0 <= X < w and 0 <= Y < h:
            rgb[Y, X] = spr.rgb[y, x]
            mask[Y, X] = True
    return codes(rgb, mask)


def line(spr, x0, y0, x1, y1, col, width=1):
    n = int(max(abs(x1 - x0), abs(y1 - y0)) * 1.5) + 1
    for k in range(n + 1):
        f = k / n
        x, y = x0 + (x1 - x0) * f, y0 + (y1 - y0) * f
        for d in range(width):
            spr.px(int(round(x)) + d, int(round(y)), col)


# ======================================================================= the T1 coastal boat
SW, SH = 208, 196          # canvas
PX, PY = 104, 186          # pivot: the near keel line at mid-length, on the shingle
X0, X1 = 20, 188           # stern post to stem (168 px: 7 tiles)


def hull_lines(t):
    """The boat's lines at `t` along it (0 stern, 1 stem): keel, near gunwale, far gunwale. The
    sheer rises hard to stem and stern, the keel has a little rocker, and the inside narrows to
    nothing at the ends, where the strakes meet the posts."""
    s = math.sin(math.pi * t)
    end = max(0.0, (abs(t - 0.5) - 0.36) / 0.14)
    keel = PY - 1 - 11 * (1 - s) ** 2.4 - 30 * end ** 1.6
    near = PY - 21 - 30 * (1 - s) ** 1.9
    far = near - 17 * s ** 0.7
    return keel, near, far


def xt(t):
    return X0 + (X1 - X0) * t


def tx(x):
    return (x - X0) / (X1 - X0)


def hull(state, k):
    """The hull, wrecked or patched; k is the wind frame (a frayed line on the stern post)."""
    s = Sprite(SW, SH, PX, PY)
    nz = value_noise(SH, SW, 3, 51)
    holes = [(0.34, 0.47, 2), (0.56, 0.63, 3)]          # (t0, t1, lowest strakes stove in)
    for x in range(X0, X1 + 1):
        t = tx(x)
        keel, near, far = hull_lines(t)
        # The inside, seen over the near gunwale: the far side's planking, ribs and the bilge.
        for y in range(int(far), int(near)):
            depth = (y - far) / max(1, near - far)
            col = C('tar', 1.3 + depth * 1.5 + (nz[y, x] - 0.5) * 0.6)
            if (x - X0) % 13 in (0, 1) and 0.06 < t < 0.94:
                col = C('driftwood', 3 if (x - X0) % 13 == 0 else 2)        # a rib
            if depth > 0.72:
                col = C('driftwood', 2.4 + (nz[y, x] > 0.6) * 0.6)          # the floorboards
            s.px(x, y, col)
        # The far gunwale's top edge.
        s.px(x, int(far), C('driftwood', 4))
        # The near side: four clinker strakes, each lit along its top and dark at its lap.
        span = max(1.0, keel - near)
        for y in range(int(near), int(keel) + 1):
            v = (y - near) / span
            strake = min(3, int(v * 4))
            within = v * 4 - strake
            col = C('tar', 4.6 - strake * 0.55 - (1.4 if within > 0.8 else 0) + (0.7 if within < 0.18 else 0)
                    + (nz[y, x] - 0.5) * 0.5)
            if within > 0.8 and (x * 5 + strake * 3) % 11 == 0:
                col = C('stone', 5)                                           # a rivet head
            if t < 0.07 or t > 0.93:
                col = C('tar', 3.4 + within * 0.4)
            hit = next(((a, b, n) for (a, b, n) in holes if a <= t <= b and strake >= 4 - n), None)
            if hit is not None:
                a, b, _ = hit
                edge = min(t - a, b - t) * (X1 - X0)
                if state == 'wrecked':
                    # Stove in: the dark of the hull inside, ragged plank ends round it.
                    if edge > 2 + hash01(x, strake, 7) * 3:
                        col = C('tar', 0.3 + (nz[y, x] > 0.7) * 0.6)
                    else:
                        col = C('driftwood', 3.5 + hash01(x, y, 8))
                else:
                    # Patched: a pale new board riveted over the hole, its grain along it.
                    col = C('driftwood', 5.2 - within * 1.2 + (nz[y, x] - 0.5) * 0.6)
                    if within > 0.82:
                        col = C('driftwood', 2.6)
                    if (edge < 1.5 or abs(within - 0.5) < 0.08) and (x + y) % 4 == 0:
                        col = C('stone', 6)                                   # new iron rivets
            # Weed and sand on the keel where it lies in the shingle.
            if keel - y < 2.5 and hash01(x, 3, 9) < 0.5:
                col = C('kelp', 2 + hash01(x, y, 10) * 2)
            s.px(x, y, col)
        # The near gunwale: a lit rail.
        s.px(x, int(near), C('driftwood', 5.5 if x % 9 else 4.5))
        s.px(x, int(near) + 1, C('tar', 2))
    # Three benches (sea chests) across the inside at a tile's spacing (Book 7 section 01: T1 three).
    for bt in (0.36, 0.5, 0.64):
        bx = int(xt(bt))
        _, near, far = hull_lines(bt)
        lid = int(near) - 8
        for x in range(bx - 7, bx + 8):
            for y in range(lid, int(near) - 1):
                edge = abs(x - bx) == 7
                s.px(x, y, C('tar', 1.8) if edge else C('driftwood', 4.2 if y < lid + 2 else 3.0))
        s.px(bx, lid + 3, C('stone', 6))          # a hasp
    # The mast step amidships (a dark socket in the keelson).
    _, near, far = hull_lines(0.5)
    for y in range(int(far) + 2, int(far) + 5):
        for x in range(PX - 2, PX + 3):
            s.px(x, y, C('tar', 0.5))
    # Stem and stern posts rising and curling in.
    for end, sign in ((X1, 1), (X0, -1)):
        _, near, _ = hull_lines(1.0 if sign > 0 else 0.0)
        for j in range(26):
            u = j / 25
            x = end + sign * (2 + 5 * u ** 2) - sign * (4 * max(0, u - 0.75) * 4)
            y = near + 3 - 24 * u
            s.px(int(round(x)), int(round(y)), C('tar', 3.5 + (j % 5 == 0)))
            s.px(int(round(x)) - sign, int(round(y)), C('tar', 2.5))
    # The bow's iron-shod forefoot, and a frayed line from the stern post stirring in the wind.
    for j in range(9):
        sway = math.sin(k / 4 * math.tau + j * 0.6) * (j / 8) * 2.5
        s.px(int(X0 - 6 - j * 0.6 + sway), int(near - 14 + j * 1.6), C('wool', 3 + (j % 2)))
    return s.outline()


def rig(k):
    """The rigging: mast stepped amidships, shrouds and stays, yard lowered with the sail furled
    along it, a pennant at the masthead (k the wind frame)."""
    s = Sprite(SW, SH, PX, PY)
    _, near, far = hull_lines(0.5)
    step = int(far) + 3
    top = 14
    for y in range(top, step):
        f = (y - top) / (step - top)
        s.px(PX - 1, y, C('tar', 1.4))
        s.px(PX, y, C('driftwood', 5.2 - f * 1.4))
        s.px(PX + 1, y, C('driftwood', 3.3 - f * 0.8))
        s.px(PX + 2, y, C('tar', 1.4))
    # The masthead's sheave block, and the shrouds to either gunwale, the stays fore and aft.
    s.px(PX, top - 1, C('tar', 2))
    s.px(PX + 1, top - 1, C('tar', 2))
    for (t, side) in ((0.43, 'near'), (0.57, 'near'), (0.45, 'far'), (0.55, 'far')):
        _, nr, fr = hull_lines(t)
        line(s, PX + 0.5, top + 2, xt(t), (nr if side == 'near' else fr) - 1, C('tar', 1.6 if side == 'near' else 2.4))
    _, nb, _ = hull_lines(0.97)
    _, ns, _ = hull_lines(0.03)
    line(s, PX + 1, top + 1, X1 - 2, nb - 18, C('tar', 2.2))
    line(s, PX, top + 1, X0 + 3, ns - 18, C('tar', 2.2))
    # The yard lowered fore and aft over the benches, the sail furled on it and lashed.
    for x in range(int(xt(0.2)), int(xt(0.8))):
        t = tx(x)
        _, nr, fr = hull_lines(t)
        y = int(nr - 9 + 2 * math.sin(math.pi * t))
        s.px(x, y + 2, C('driftwood', 4))
        bulge = 3.5 * max(0.0, math.sin(math.pi * (t - 0.2) / 0.6)) ** 0.6
        for d in range(int(bulge) + 1):
            s.px(x, y - d, C('wool', 4.6 - d * 0.5 + ((x // 3) % 2) * 0.4))
        s.px(x, y - int(bulge) - 1, C('wool', 1.5))
        s.px(x, y + 3, C('tar', 1.6))
        if x % 12 == 0:
            for d in range(int(bulge) + 2):
                s.px(x, y - d + 1, C('tar', 2))                              # a gasket
    # The pennant at the masthead, streaming east and flicking (4 frames).
    for j in range(10):
        wave = math.sin(k / 4 * math.tau - j * 0.7) * (1 + j * 0.15)
        s.px(PX + 2 + j, int(top + 1 + wave * 0.6 + j * 0.15), C('madder', 4 - (j > 6)))
        if j < 6:
            s.px(PX + 2 + j, int(top + 2 + wave * 0.6 + j * 0.15), C('madder', 3))
    # No ink round the lines: a rope is a line, not a shape (the yard and sail have dark edges).
    return s


def steering_oar():
    """The steering oar lashed on the near quarter at the stern: loom, withy, blade, tiller."""
    s = Sprite(SW, SH, PX, PY)
    t = 0.1
    _, near, _ = hull_lines(t)
    ax, ay = xt(t) + 2, near - 16
    bx, by = xt(t) - 7, PY + 6
    for j in range(80):
        f = j / 79
        x = ax + (bx - ax) * f
        y = ay + (by - ay) * f
        wide = 0 if f < 0.58 else int(1 + (f - 0.58) * 9)
        for d in range(-wide, wide + 1):
            s.px(int(round(x + d)), int(round(y)), C('driftwood', 5.4 - (d > 0) * 1.6 - f * 1.2))
    for y in range(int(near) - 2, int(near) + 3):
        for x in range(int(xt(t)) - 2, int(xt(t)) + 3):
            s.px(x, y, C('wool', 2.6 + ((x + y) % 2) * 0.6))                  # the withy
    for x in range(int(ax), int(ax) + 14):
        s.px(x, int(ay) + (x - int(ax)) // 5, C('driftwood', 4.4))            # the tiller
    return s.outline()


def hold():
    """The extended hold amidships: hides over sacks and a cask, held down by lashings."""
    s = Sprite(SW, SH, PX, PY)
    for x in range(int(xt(0.37)), int(xt(0.63))):
        t = tx(x)
        _, near, far = hull_lines(t)
        u = (t - 0.37) / 0.26
        mound = 9 * max(0.0, math.sin(math.pi * u)) ** 0.7
        for y in range(int(far - mound), int(near - 1)):
            hide = (x // 7 + y // 6) % 3
            col = C('earth', 3.6 + hide * 0.5 - (y - (far - mound)) * 0.04)
            if y < far - mound + 2:
                col = C('earth', 4.8)
            s.px(x, y, col)
        if x % 10 == 0:
            for y in range(int(far - mound), int(near)):
                s.px(x, y, C('wool', 2.5))                                    # a lashing
    return s.outline()


def bow_platform():
    """A raised fighting platform of wreck timber at the bow: deck planks on two posts."""
    s = Sprite(SW, SH, PX, PY)
    xa, xb = int(xt(0.8)), int(xt(0.95))
    for x in range(xa, xb):
        t = tx(x)
        _, near, far = hull_lines(t)
        deck = int(far) - 6
        for y in range(deck, int(near) - 4):
            plank = (y - deck) % 4
            s.px(x, y, C('driftwood', 4.8 - (plank == 3) * 1.6 - (y - deck) * 0.04))
        s.px(x, deck, C('driftwood', 5.6))
    for px_ in (xa + 2, xb - 3):
        t = tx(px_)
        _, near, far = hull_lines(t)
        for y in range(int(near) - 4, int(near) + 2):
            s.px(px_, y, C('driftwood', 3))
            s.px(px_ + 1, y, C('driftwood', 2))
    return s.outline()


def ready():
    """Launch-ready: three rollers laid under the keel down the shingle, and the oars in, their
    blades over the gunwale."""
    s = Sprite(SW, SH, PX, PY)
    for rt in (0.25, 0.5, 0.75):
        cx = int(xt(rt))
        for j in range(16):
            y = PY - 2 + j
            for d in range(-2, 3):
                s.px(cx + d + j // 6, y, C('driftwood', 4.2 - abs(d) * 0.6 + (j == 15)))
    # The oars in, laid fore and aft along the near gunwale, their blades over the stern.
    for k in range(3):
        for x in range(int(xt(0.22)), int(xt(0.78))):
            _, near, _ = hull_lines(tx(x))
            s.px(x, int(near) - 2 - k, C('driftwood', 5 - k * 0.6))
        for d in range(4):
            s.px(int(xt(0.22)) - 1 - d, int(hull_lines(0.22)[1]) - 2 - k + (d > 1), C('driftwood', 4.6))
    return s.outline()


