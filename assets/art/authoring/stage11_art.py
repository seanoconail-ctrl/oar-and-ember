def write_skiff():
    size, pivot = (124, 64), (62, 58)
    frames = [(('oar', '-', 0), raw_rows(SC.skiff(True), size, pivot)),
              (('bare', '-', 0), raw_rows(SC.skiff(False), size, pivot))]
    # Both stand on the keel's lowest row (the oar's blade rests on the sand beside it).
    for i, (key, rows_) in enumerate(frames):
        low = max(y for y, r in enumerate(rows_) if r.strip('.'))
        shift = pivot[1] - low
        blank = '.' * size[0]
        moved = [blank] * size[1]
        for y, r in enumerate(rows_):
            if 0 <= y + shift < size[1]:
                moved[y + shift] = r
        frames[i] = (key, moved)
    write('prop_skiff', sheet_text(
        'prop_skiff', 'prop', size, pivot, frames, {'oar': (1, 1), 'bare': (1, 1)},
        HEADER + ["The wreck-scavengers' skiff in Seal Cave (Book 4 section 02), drawn up in the mouth,",
                  'its steering oar on the quarter or taken (docs/art/mockup-src/sealcave.py).'],
        shadow='110x10', footprint='110x12'))


