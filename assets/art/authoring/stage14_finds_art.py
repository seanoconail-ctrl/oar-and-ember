def carving(s, pts, deep=2, light=6):
    for (x, y) in pts:
        s.px(x, y, C('stone', deep))
        s.px(x + 1, y + 1, C('stone', light))


def face_slab(s, seed, w=13, h=9, cy=19):
    for y in range(cy - h, cy + h):
        for x in range(19 - w, 19 + w + 1):
            u = (x - 19) / w
            v = (y - cy) / h
            if u ** 4 + v ** 4 < 1 - 0.08 * hash01(x // 2, y // 2, seed):
                s.px(x, y, C('stone', 4 + (y < cy - h + 3) - (y > cy + h - 3) - (hash01(x, y, seed) < 0.08)))


