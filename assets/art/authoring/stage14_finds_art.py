MAP_W, MAP_H = 640, 360
BS = 12                     # pixels a block on the page (must agree with src/scenes/regionMap.ts)
OX, OY = 32, -12


def read_grid():
    rows = open(f'{REPO}/docs/levels/skarvholm_blocks.txt').read().split('\n')[2:34]
    return [r[4:4 + 48] for r in rows]


def vellum():
    """The page: warm vellum, a few long fibres, soft old stains dithered in, and a ruled border."""
    from core import bayer
    rgb = np.zeros((MAP_H, MAP_W, 3), np.float32)
    rgb[:, :] = C('wool', 5)
    th = bayer(MAP_H, MAP_W)
    stains = [(120, 80, 70), (470, 270, 90), (560, 60, 40), (90, 300, 50)]
    for y in range(MAP_H):
        for x in range(MAP_W):
            v = 0.0
            for (cx, cy, r) in stains:
                d = math.hypot(x - cx, (y - cy) * 1.3) / r
                v = max(v, 0.35 * max(0.0, 1 - d) ** 1.5)
            if v > th[y, x]:
                rgb[y, x] = C('wool', 4)
            # Fibres: short streaks along the skin's grain.
            if hash01(x // 7, y, 501) < 0.025 and hash01(x, y // 3, 502) < 0.8:
                rgb[y, x] = C('wool', 4 if hash01(x // 7, y, 503) < 0.7 else 6)
    for y in range(MAP_H):
        for x in range(MAP_W):
            edge = min(x, y, MAP_W - 1 - x, MAP_H - 1 - y)
            if edge < 3:
                rgb[y, x] = C('wool', 2 + edge)
            elif edge in (8, 11):
                rgb[y, x] = C('earth', 3)
    return rgb


def ink_island(base):
    """All of Skarvholm inked in brown on the page."""
    g = read_grid()
    rgb = base.copy()
    H, W = len(g), 48
    ink = C('earth', 1)
    mid = C('earth', 3)
    soft = C('wool', 3)

    def cell(bx, by):
        return g[by][bx] if 0 <= bx < W and 0 <= by < H else '~'

    def land(c):
        return c not in '~-='

    def put(x, y, col):
        if 0 <= x < MAP_W and 0 <= y < MAP_H:
            rgb[y, x] = col

    for by in range(H):
        for bx in range(W):
            c = cell(bx, by)
            x0, y0 = OX + bx * BS, OY + by * BS
            for py in range(BS):
                for px in range(BS):
                    x, y = x0 + px, y0 + py
                    if c == '~':
                        # Sea hatched near the coast, plain further out.
                        near = any(land(cell(bx + dx, by + dy)) for dx in (-1, 0, 1) for dy in (-1, 0, 1))
                        if near and y % 4 == 0 and hash01(x // 3, y, 511) < 0.75:
                            put(x, y, mid if hash01(x // 5, y, 516) < 0.5 else soft)
                    elif c == '-':
                        if (x % 3 == 0 and y % 3 == 0):
                            put(x, y, mid)
                    elif c == '=':
                        if (x + 2 * y) % 6 < 2 and py in (5, 6):
                            put(x, y, ink)
                    elif c == '.':
                        if hash01(x, y, 512) < 0.08:
                            put(x, y, mid)
                    elif c == ',':
                        if hash01(x, y, 513) < 0.03:
                            put(x, y, mid)
                    elif c == '"':
                        # Heather: small tufts, staggered.
                        tx, ty = (px + (by % 2) * 3) % 6, py % 6
                        if (tx, ty) in ((1, 3), (2, 2), (3, 3)):
                            put(x, y, mid)
                    elif c in '^R':
                        # Rook Hill: short hachures running down from the summit.
                        sx, sy = OX + 22 * BS + 6, OY + 9 * BS + 6
                        ang = math.atan2(y - sy, x - sx)
                        tx, ty = px % 6, py % 6
                        if (tx, ty) == (2, 2) or ((tx, ty) == (2 + round(math.cos(ang)), 2 + round(math.sin(ang)))):
                            put(x, y, mid)
                    elif c == 'b':
                        # The bog: tufts over short level strokes of water.
                        tx, ty = (px + (by % 2) * 2) % 6, py % 6
                        if (tx, ty) in ((1, 1), (3, 1), (2, 0)):
                            put(x, y, ink)
                        if ty == 4 and tx in (0, 1, 2, 3):
                            put(x, y, soft)
                    elif c == '#':
                        if px % 3 == 0 and py < 6 + (bx % 3):
                            put(x, y, ink)
                    elif c == 'r':
                        if hash01(x // 2, y // 2, 515) < 0.3:
                            put(x, y, mid)
                    elif c == 'w':
                        if abs(px - 6 - int(2 * math.sin(y * 0.4))) < 1:
                            put(x, y, ink)
                    elif c == 'f':
                        if px % 3 == 0:
                            put(x, y, mid)
            # The coastline: ink where land meets sea or flats.
            if land(c):
                for (dx, dy) in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    if not land(cell(bx + dx, by + dy)):
                        for k in range(BS):
                            wob = int(round(math.sin((k + bx * 7 + by * 3) * 0.7)))
                            if dx == 1:
                                put(x0 + BS - 1 + wob, y0 + k, ink)
                            elif dx == -1:
                                put(x0 + wob, y0 + k, ink)
                            elif dy == 1:
                                put(x0 + k, y0 + BS - 1 + wob, ink)
                            else:
                                put(x0 + k, y0 + wob, ink)

    def ring(cx, cy, r, col, n=24):
        for k in range(n):
            a = k / n * math.tau
            put(int(round(cx + math.cos(a) * r)), int(round(cy + math.sin(a) * r)), col)

    def at(bx, by):
        return OX + bx * BS + BS // 2, OY + by * BS + BS // 2

    # Pictograms (Book 7 section 10): the broch, the ring, the cairn, the cell, the stack, the cave,
    # the falls, the summit's cairn plot, the spring, the sheepfold and the wreck.
    x, y = at(17, 22)
    for dy in range(-5, 5):
        for dx in (-4, 4):
            put(x + dx, y + dy, ink)
    for dx in range(-4, 5):
        put(x + dx, y - 5, ink)
        put(x + dx, y + 4, ink)
    x, y = at(27, 14)
    for k in range(9):
        a = k / 9 * math.tau
        px_, py_ = int(round(x + math.cos(a) * 5)), int(round(y + math.sin(a) * 4))
        put(px_, py_, ink)
        put(px_, py_ - 1, ink)
    x, y = at(31, 20)
    for dx in range(-7, 8):
        h = int(round(4 * math.cos(dx / 7 * math.pi / 2)))
        put(x + dx, y - h, ink)
    put(x + 7, y - 1, ink)
    put(x + 7, y, ink)
    x, y = at(11, 8)
    ring(x, y, 4, ink, 20)
    put(x + 4, y, rgb[y, x + 5].copy())
    put(x, y - 7, ink); put(x, y - 8, ink); put(x - 1, y - 7, ink); put(x + 1, y - 7, ink)
    x, y = at(3, 12)
    for dy in range(-6, 3):
        put(x - 2, y + dy, ink)
        put(x + 2, y + dy, ink)
    for dx in range(-2, 3):
        put(x + dx, y - 6, ink)
    x, y = at(41, 9)
    for dx in range(-4, 5):
        h = int(round(math.sqrt(max(0, 16 - dx * dx))))
        put(x + dx, y - h + 2, ink)
    x, y = at(20, 14)
    for dy in range(-4, 4):
        put(x - 1, y + dy, mid)
        put(x + 1, y + dy + 1, mid)
    x, y = at(22, 9)
    for dx in range(-3, 4):
        put(x + dx, y + 2 - abs(dx), ink)
    x, y = at(19, 19)
    ring(x, y, 2, ink, 12)
    x, y = at(28, 22)
    for dx in range(-3, 4):
        put(x + dx, y - 3, ink)
        put(x + dx, y + 3, ink)
    for dy in range(-3, 4):
        put(x - 3, y + dy, ink)
        put(x + 3, y + dy, ink)
    x, y = at(14, 29)
    for dx in range(-4, 5):
        put(x + dx, y + int(abs(dx) > 2), ink)
    put(x + 1, y - 3, ink); put(x + 1, y - 2, ink); put(x + 1, y - 1, ink)

    # The landings as boat shapes (Book 9 section 02).
    def boat(cx, cy):
        for dx in range(-5, 6):
            put(cx + dx, cy + (1 if abs(dx) < 4 else 0), ink)
        for dx in range(-3, 4):
            put(cx + dx, cy + 2, ink)
        put(cx - 5, cy - 1, ink); put(cx + 5, cy - 1, ink)
    for (bx, by) in [(22, 27), (32, 24), (12, 4), (43, 8), (42, 29)]:
        boat(*at(bx, by))

    # Tidal ways: a dashed line with a wave icon (the flats to the wreck, the causeway).
    def wave(cx, cy):
        for dx in range(-4, 5):
            put(cx + dx, cy + int(round(math.sin(dx * 1.2))), ink)
    wave(*at(39, 26))
    wave(*at(16, 28))

    # The main path loop and the cliff paths, in pale dashes (Book 9 section 02).
    path = [(18, 22), (19, 19), (20, 15), (22, 10), (25, 12), (27, 14), (30, 18), (31, 20),
            (32, 23), (26, 25), (21, 26), (18, 23)]
    for (a, b) in zip(path, path[1:]):
        (x0, y0), (x1, y1) = at(*a), at(*b)
        n = int(max(abs(x1 - x0), abs(y1 - y0)))
        for k in range(n):
            if k % 6 < 3:
                put(int(round(x0 + (x1 - x0) * k / n)), int(round(y0 + (y1 - y0) * k / n)), mid)
    cliff = [(22, 10), (16, 9), (12, 8), (9, 12), (6, 16), (5, 18)]
    for (a, b) in zip(cliff, cliff[1:]):
        (x0, y0), (x1, y1) = at(*a), at(*b)
        n = int(max(abs(x1 - x0), abs(y1 - y0)))
        for k in range(n):
            if k % 4 == 0:
                put(int(round(x0 + (x1 - x0) * k / n)), int(round(y0 + (y1 - y0) * k / n)), mid)

    # The interiors as inset sketches, each in a ruled box (decision S14-23).
    def inset(bx, by, bw, bh, draw):
        x0, y0 = OX + bx * BS, OY + by * BS
        w, h = bw * BS, bh * BS
        for xx in range(x0, x0 + w):
            for yy in range(y0, y0 + h):
                rgb[yy, xx] = C('wool', 5)
        for xx in range(x0, x0 + w):
            put(xx, y0, ink); put(xx, y0 + h - 1, ink)
        for yy in range(y0, y0 + h):
            put(x0, yy, ink); put(x0 + w - 1, yy, ink)
        draw(x0, y0, w, h)

    def deep(x0, y0, w, h):
        # The passage's way from A (east) to B (west): the pool, the crawl and the lowest point.
        pts = [(0.95, 0.45), (0.7, 0.45), (0.55, 0.4), (0.45, 0.35), (0.42, 0.6), (0.35, 0.72),
               (0.1, 0.72), (0.03, 0.66)]
        for (a, b) in zip(pts, pts[1:]):
            xa, ya = x0 + a[0] * w, y0 + a[1] * h
            xb, yb = x0 + b[0] * w, y0 + b[1] * h
            n = int(max(abs(xb - xa), abs(yb - ya))) + 1
            for k in range(n):
                put(int(round(xa + (xb - xa) * k / n)), int(round(ya + (yb - ya) * k / n)), ink)
                put(int(round(xa + (xb - xa) * k / n)), int(round(ya + (yb - ya) * k / n)) + 2, mid)
        wave(int(x0 + 0.2 * w), int(y0 + 0.85 * h))

    def cairn_in(x0, y0, w, h):
        # The chambers: the great chamber, the inner chamber, the passage and the spring.
        def box(a, b, c, d):
            for xx in range(int(x0 + a * w), int(x0 + c * w)):
                put(xx, int(y0 + b * h), ink); put(xx, int(y0 + d * h), ink)
            for yy in range(int(y0 + b * h), int(y0 + d * h) + 1):
                put(int(x0 + a * w), yy, ink); put(int(x0 + c * w), yy, ink)
        box(0.08, 0.3, 0.25, 0.65)
        box(0.38, 0.33, 0.62, 0.6)
        for xx in range(int(x0 + 0.62 * w), int(x0 + 0.95 * w)):
            put(xx, int(y0 + 0.47 * h), ink)
        for xx in range(int(x0 + 0.2 * w), int(x0 + 0.9 * w)):
            if xx % 4 < 2:
                put(xx, int(y0 + 0.85 * h), mid)
        ring(int(x0 + 0.15 * w), int(y0 + 0.47 * h), 2, ink, 10)

    inset(37, 3, 6, 3, deep)
    inset(29, 26, 6, 4, cairn_in)
    return rgb


