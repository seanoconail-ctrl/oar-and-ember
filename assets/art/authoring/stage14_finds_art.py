def sheet_text(name, kind, size, pivot, frames, anims, about, shadow=None):
    w, h = size
    lines = [
        '# Generated by assets/art/authoring/stage14_finds_art.py (Stage 14, work package C).',
        '# Do not edit by hand: change the script and run it again.',
    ] + [f'# {a}' for a in about] + [
        f'sheet: {name}', f'kind: {kind}', 'palette: book07', f'size: {w}x{h}',
        f'pivot: {pivot[0]},{pivot[1]}', f'footprint: {w}x{h}', 'facings: -', 'placeholder: false',
    ]
    if shadow:
        lines.append(f'shadow: {shadow}')
    for state, spec in anims.items():
        n, ticks = spec[0], spec[1]
        loop = ', loop' if len(spec) > 2 and spec[2] == 'loop' else ''
        lines.append(f'anim.{state}: frames {n}, ticks {ticks}{loop}')
    for (state, i), rows in frames:
        assert len(rows) == h and all(len(r) == w for r in rows), (name, state, i, len(rows))
        lines += ['', f'frame {state} - {i}'] + rows + ['end']
    return '\n'.join(lines) + '\n'


