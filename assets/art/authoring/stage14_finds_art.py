def page_shape(s, cx, cy, w=6, h=4, tilt=0.0, ramp='wool', base=6):
    """A vellum leaf, a little curled at one corner, with lines of a small hand across it."""
    for y in range(int(cy - h), int(cy + h) + 1):
        for x in range(int(cx - w), int(cx + w) + 1):
            dy = y - cy
            if abs(dy) <= h:
                curl = x == int(cx + w) and y == int(cy - h)
                s.px(x, int(round(y + (x - cx) * tilt)), C(ramp, base - 1 if curl or y == int(cy + h) else base))
    for y in range(int(cy - h) + 1, int(cy + h), 2):
        for x in range(int(cx - w) + 1, int(cx + w)):
            if hash01(x, y, 305) < 0.7:
                s.px(x, int(round(y + (x - cx) * tilt)), C('earth', 3))
    s.px(int(cx - w) + 1, int(cy - h) + 1, C('madder', 3))


