# --------------------------------------------------------------------------- grounds
def shingle(spr, cx, cy, w, seed):
    r = np.random.default_rng(seed)
    for _ in range(int(w * 1.6)):
        x = cx + r.uniform(-w, w)
        y = cy + r.uniform(-2.2, 1.8)
        s = r.uniform(1.0, 2.2)
        blob(spr, x, y, s, s * 0.7, 'stone' if r.random() < 0.6 else 'driftwood', 3 + int(r.integers(0, 3)))


def rock_ledge(spr, cx, cy, rx, ry, seed, ramp='stone', base=4):
    stone(spr, cx, cy, rx, ry, ramp, base, seed=seed)
    for y, x in zip(*np.nonzero(spr.mask)):
        if hash01(x, y, seed) < 0.05:
            spr.rgb[y, x] = C('wool', 4)


def weed(spr, cx, cy, n, sway, seed):
    r = np.random.default_rng(seed)
    for _ in range(n):
        x = cx + r.uniform(-8, 8)
        hgt = int(r.integers(3, 6))
        for j in range(hgt):
            lean = sway * (j / hgt)
            spr.px(int(round(x + lean)), int(round(cy - j * 0.6)), C('kelp', 3 + (j > 1)))


def wet_sheen(spr, k, seed, ramp='sea', step=8):
    """Glints of wet light that walk across what is drawn (k: frame)."""
    for y, x in zip(*np.nonzero(spr.mask)):
        if hash01(x + k * 3, y, seed) < 0.035:
            spr.rgb[y, x] = C(ramp, step)


