HEADER = ["Generated by assets/art/authoring/pt4_boat_art.py (the user's fourth playtest). Do not",
          'edit by hand: change the script and run it again.']
SW, SH, PX, PY, X0, X1 = S.SW, S.SH, S.PX, S.PY, S.X0, S.X1
HOLES = [(0.34, 0.47, 2), (0.56, 0.63, 3)]          # stage11_art.hull's holes: (t0, t1, strakes)


def hull_stage(stage, k):
    """The hull at a work stage: 'trim', 'boards' or 'rivets'; k the wind frame. Painted as
    stage11_art.hull paints it, but for the two holes, each in its own state."""
    # Each hole: 'open' (trimmed square), 'boarded' (new boards, pegged) or 'riveted'.
    state = {'trim': ('open', 'open'), 'boards': ('boarded', 'open'),
             'rivets': ('riveted', 'boarded')}[stage]
    s = Sprite(SW, SH, PX, PY)
    nz = value_noise(SH, SW, 3, 51)
    for x in range(X0, X1 + 1):
        t = S.tx(x)
        keel, near, far = S.hull_lines(t)
        for y in range(int(far), int(near)):
            depth = (y - far) / max(1, near - far)
            col = C('tar', 1.3 + depth * 1.5 + (nz[y, x] - 0.5) * 0.6)
            if (x - X0) % 13 in (0, 1) and 0.06 < t < 0.94:
                col = C('driftwood', 3 if (x - X0) % 13 == 0 else 2)
            if depth > 0.72:
                col = C('driftwood', 2.4 + (nz[y, x] > 0.6) * 0.6)
            s.px(x, y, col)
        s.px(x, int(far), C('driftwood', 4))
        span = max(1.0, keel - near)
        for y in range(int(near), int(keel) + 1):
            v = (y - near) / span
            strake = min(3, int(v * 4))
            within = v * 4 - strake
            col = C('tar', 4.6 - strake * 0.55 - (1.4 if within > 0.8 else 0) + (0.7 if within < 0.18 else 0)
                    + (nz[y, x] - 0.5) * 0.5)
            if within > 0.8 and (x * 5 + strake * 3) % 11 == 0:
                col = C('stone', 5)
            if t < 0.07 or t > 0.93:
                col = C('tar', 3.4 + within * 0.4)
            hit = next(((i, a, b) for i, (a, b, n) in enumerate(HOLES) if a <= t <= b and strake >= 4 - n),
                       None)
            if hit is not None:
                i, a, b = hit
                edge = min(t - a, b - t) * (X1 - X0)
                here = state[i]
                if here == 'open':
                    # Cut back square to sound wood: a clean dark hole, its fresh-cut rim pale.
                    col = C('driftwood', 5.4) if edge < 1.2 else C('tar', 0.3 + (nz[y, x] > 0.7) * 0.5)
                    if edge >= 1.2 and within > 0.86:
                        col = C('tar', 1.0)                                   # a rib seen through
                else:
                    # A new board, pale, its grain along it; pegged at its ends, or riveted.
                    col = C('driftwood', 5.2 - within * 1.2 + (nz[y, x] - 0.5) * 0.6)
                    if within > 0.82:
                        col = C('driftwood', 2.6)
                    if here == 'riveted':
                        if (edge < 1.5 or abs(within - 0.5) < 0.08) and (x + y) % 4 == 0:
                            col = C('stone', 6)
                    elif edge < 1.5 and abs(within - 0.5) < 0.2:
                        col = C('earth', 3.2)                                 # a wooden peg
            if keel - y < 2.5 and hash01(x, 3, 9) < 0.5:
                col = C('kelp', 2 + hash01(x, y, 10) * 2)
            s.px(x, y, col)
        s.px(x, int(near), C('driftwood', 5.5 if x % 9 else 4.5))
        s.px(x, int(near) + 1, C('tar', 2))
    for bt in (0.36, 0.5, 0.64):
        bx = int(S.xt(bt))
        _, near, far = S.hull_lines(bt)
        lid = int(near) - 8
        for x in range(bx - 7, bx + 8):
            for y in range(lid, int(near) - 1):
                edge = abs(x - bx) == 7
                s.px(x, y, C('tar', 1.8) if edge else C('driftwood', 4.2 if y < lid + 2 else 3.0))
        s.px(bx, lid + 3, C('stone', 6))
    _, near, far = S.hull_lines(0.5)
    for y in range(int(far) + 2, int(far) + 5):
        for x in range(PX - 2, PX + 3):
            s.px(x, y, C('tar', 0.5))
    for end, sign in ((X1, 1), (X0, -1)):
        _, near, _ = S.hull_lines(1.0 if sign > 0 else 0.0)
        for j in range(26):
            u = j / 25
            x = end + sign * (2 + 5 * u ** 2) - sign * (4 * max(0, u - 0.75) * 4)
            y = near + 3 - 24 * u
            s.px(int(round(x)), int(round(y)), C('tar', 3.5 + (j % 5 == 0)))
            s.px(int(round(x)) - sign, int(round(y)), C('tar', 2.5))
    for j in range(9):
        sway = math.sin(k / 4 * math.tau + j * 0.6) * (j / 8) * 2.5
        s.px(int(X0 - 6 - j * 0.6 + sway), int(near - 14 + j * 1.6), C('wool', 3 + (j % 2)))
    # Two shores of wreck timber propping the near side while the strakes are open.
    for st in (0.3, 0.7):
        _, nr, _ = S.hull_lines(st)
        bx = int(S.xt(st))
        for j in range(18):
            f = j / 17
            x = bx + 6 - f * 6
            y = nr + 2 + f * (PY - 2 - nr - 2)      # its foot on the shingle, above the keel's row
            s.px(int(round(x)), int(round(y)), C('driftwood', 4.6 - f))
            s.px(int(round(x)) + 1, int(round(y)), C('driftwood', 3.0 - f))
    return s.outline()


def rig_lying():
    """The mast laid fore and aft along the benches, its stays coiled on the thwarts."""
    s = Sprite(SW, SH, PX, PY)
    for x in range(int(S.xt(0.14)), int(S.xt(0.86))):
        t = S.tx(x)
        _, nr, fr = S.hull_lines(t)
        y = int(nr - 10 + 2 * math.sin(math.pi * t))
        taper = 0 if t > 0.78 else 1
        s.px(x, y, C('driftwood', 5.2))
        s.px(x, y + 1, C('driftwood', 3.6))
        if taper:
            s.px(x, y + 2, C('driftwood', 2.8))
        s.px(x, y - 1, C('tar', 1.4))
    # The masthead's block at the forward end.
    hx = int(S.xt(0.86))
    _, nr, _ = S.hull_lines(0.86)
    for dy in range(3):
        s.px(hx, int(nr - 11 + dy), C('tar', 2))
        s.px(hx + 1, int(nr - 11 + dy), C('tar', 2.4))
    # Coils of the salvaged stays on the after and forward thwarts: loops of line, wound flat.
    for ct in (0.36, 0.64):
        cx = int(S.xt(ct))
        _, nr, _ = S.hull_lines(ct)
        cy = int(nr) - 12
        for r in (4, 3, 2):
            for a in range(0, 360, 12):
                ax = cx + int(round(r * 1.5 * math.cos(math.radians(a))))
                ay = cy + int(round(r * 0.6 * math.sin(math.radians(a))))
                s.px(ax, ay, C('wool', 2.6 + (r % 2) * 0.8 + (a % 48 == 0) * 0.5))
    return s.outline()


def rig_stepped(k):
    """The mast stepped amidships, not yet stayed: a loose halyard swinging (k the wind frame);
    the yard with the furled sail laid along the benches."""
    s = Sprite(SW, SH, PX, PY)
    _, near, far = S.hull_lines(0.5)
    step = int(far) + 3
    top = 14
    for y in range(top, step):
        f = (y - top) / (step - top)
        s.px(PX - 1, y, C('tar', 1.4))
        s.px(PX, y, C('driftwood', 5.2 - f * 1.4))
        s.px(PX + 1, y, C('driftwood', 3.3 - f * 0.8))
        s.px(PX + 2, y, C('tar', 1.4))
    s.px(PX, top - 1, C('tar', 2))
    s.px(PX + 1, top - 1, C('tar', 2))
    # The halyard hanging from the sheave in a loose bight, swinging in the wind.
    for j in range(46):
        f = j / 45
        sway = math.sin(k / 4 * math.tau + f * 2.2) * 3.5 * math.sin(math.pi * f)
        s.px(int(round(PX + 3 + sway + f * 4)), top + 1 + j, C('tar', 2.2))
    # The yard and furled sail, lowered along the benches as in the finished rig.
    for x in range(int(S.xt(0.2)), int(S.xt(0.8))):
        t = S.tx(x)
        _, nr, fr = S.hull_lines(t)
        y = int(nr - 9 + 2 * math.sin(math.pi * t))
        s.px(x, y + 2, C('driftwood', 4))
        bulge = 3.5 * max(0.0, math.sin(math.pi * (t - 0.2) / 0.6)) ** 0.6
        for d in range(int(bulge) + 1):
            s.px(x, y - d, C('wool', 4.6 - d * 0.5 + ((x // 3) % 2) * 0.4))
        s.px(x, y - int(bulge) - 1, C('wool', 1.5))
        s.px(x, y + 3, C('tar', 1.6))
        if x % 12 == 0:
            for d in range(int(bulge) + 2):
                s.px(x, y - d + 1, C('tar', 2))
    return s


def main():
    frames = []
    for stage in ('trim', 'boards', 'rivets'):
        for k in range(4):
            frames.append(((f'hull_{stage}', '-', k),
                           S.raw_rows(hull_stage(stage, k), (SW, SH), (PX, PY))))
    write('ship_t1_work', sheet_text(
        'ship_t1_work', 'prop', (SW, SH), (PX, PY), frames,
        {'hull_trim': (4, 9, 'loop'), 'hull_boards': (4, 9, 'loop'), 'hull_rivets': (4, 9, 'loop')},
        HEADER + ["The T1 coastal boat's hull as the patch goes on (Book 10 hullStages): the holes cut back",
                  'square (trim), the aft hole boarded (boards), both boarded and the aft riveted (rivets).'],
        shadow='170x16', footprint='168x40'))
    parts = [(('lying', '-', 0), S.raw_rows(rig_lying(), (SW, SH), (PX, PY)))]
    for k in range(4):
        parts.append((('stepped', '-', k), S.raw_rows(rig_stepped(k), (SW, SH), (PX, PY))))
    write('ship_t1_rigwork', sheet_text(
        'ship_t1_rigwork', 'building', (SW, SH), (PX, PY), parts,
        {'lying': (1, 1), 'stepped': (4, 7, 'loop')},
        HEADER + ["The T1 coastal boat's rigging in hand (Book 10 riggingStages), drawn at the hull's pivot:",
                  'the mast laid along the benches with the stays coiled (lying), then stepped unstayed with',
                  'a loose halyard and the yard and sail laid along the benches (stepped).']))


if __name__ == '__main__':
    main()
