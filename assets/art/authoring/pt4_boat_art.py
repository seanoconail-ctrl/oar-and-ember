"""Builds the boat's work in hand (the user's fourth playtest, request 14; decisions DH-61 and
DH-62; Book 7 section 05; Book 10 section 08, "Boat work"), drawn with Stage 11's helpers and
palette ramps over the same T1 coastal boat (assets/art/authoring/stage11_art.py), so the boat
changes gradually as the household works on it:

- ship_t1_work (kind prop, the hull's own shadow): the hull between wrecked and patched, at the
  three stages Book 10 hullStages names. **trim** (25% of the patch's labour): the stove-in strakes
  cut back square to sound wood, their fresh edges pale, the ragged plank ends gone, a pair of
  shores propping the hull. **boards** (50%): the aft hole closed with new boards, still unriveted
  (pale, pegged at the ends), the forward hole trimmed and open. **rivets** (75%): both holes
  boarded, the aft patch riveted, the forward one pegged. Each has the hull's four wind frames (the
  frayed line on the stern post).
- ship_t1_rigwork (kind building, a layer like ship_t1_parts): the rigging in hand at Book 10
  riggingStages. **lying** (begun): the mast laid fore and aft along the benches with its stays
  coiled on the thwarts. **stepped** (50%): the mast stepped amidships, unstayed, a loose halyard
  swinging from the masthead (four frames), the yard and furled sail laid along the benches.

    python3 assets/art/authoring/pt4_boat_art.py && npm run art:compile
"""
