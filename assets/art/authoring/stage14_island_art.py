def holds():
    """Hand-holds cut in a climb, one tile of them: lit notches with a dark lip below each."""
    s = Sprite(24, 24, 12, 23)
    for k, (x, y) in enumerate(((7, 3), (15, 8), (6, 13), (14, 18), (9, 22))):
        for dx in range(3):
            s.px(x + dx, y - 1, C('stone', 8.5 - dx * 0.5))
            s.px(x + dx, y, C('stone', 6))
            if y + 1 < 24:
                s.px(x + dx, y + 1, C('ink', 1))
    for y in range(0, 24, 3):
        s.px(11 + (y // 3) % 2, y, C('wool', 4))                 # the rub of hands, chalky
    return s


def fall_frame(k, n=6):
    """The upper stream's falling sheet over the lip: white streaks racing down, darker gaps."""
    s = Sprite(26, 52, 13, 51)
    for x in range(2, 24):
        nn = hash01(x, 7)
        for y in range(0, 52):
            v = math.sin((y - k / n * 52 * (1 + nn)) / (2.0 + nn * 2) * 1.0 + nn * 9)
            col = C('sea', 9 if v > 0.5 else 7 if v > -0.3 else 5)
            if y < 2:
                col = C('sea', 10)
            s.px(x, y, col)
    return s


def churn_frame(k, n=6):
    s = Sprite(52, 22, 26, 20)
    for y in range(2, 20):
        for x in range(2, 50):
            d = math.hypot((x - 26) / 24, (y - 11) / 9)
            if d > 1:
                continue
            v = hash01(x // 2, y // 2, k * 7 + 1)
            if d < 0.5 and v > 0.35:
                s.px(x, y, C('sea', 10 if v > 0.7 else 9))
            elif abs(math.sin(d * 9 - k / n * math.tau)) < 0.2:
                s.px(x, y, C('sea', 8))
    return s


def haze_frame(k, n=8):
    """A damp haze moving on the draught: a sparse dither of pale specks drifting, so the dark of
    a passage is never still (each tile of the pattern drifts by its own phase)."""
    s = Sprite(48, 48, 24, 47)
    for i in range(70):
        x0 = hash01(i, 1) * 48
        y0 = hash01(i, 2) * 48
        sp = 0.6 + hash01(i, 3) * 0.8
        x = (x0 + k / n * 48 * sp) % 48
        y = (y0 - k / n * 12 * sp + 2 * math.sin(k / n * math.tau + i)) % 48
        tw = math.sin(k / n * math.tau * 2 + i)
        s.px(int(x), int(y), C('sky', 1 + (tw > 0) * 1))
    return s


def caustic_frame(k, n=8):
    """Light thrown off rippling water onto a wall: pale bands that wriggle and drift."""
    s = Sprite(48, 24, 24, 23)
    ph = k / n * math.tau
    for y in range(24):
        for x in range(48):
            a = math.sin(x / 5 + math.sin(y / 4 + ph) * 2.2 + ph)
            b = math.sin(y / 3.5 + math.sin(x / 6.5 - ph) * 2.0 - ph)
            if a * b > 0.62:
                s.px(x, y, C('sea', 7 + (a * b > 0.8)))
    return s


def fx_island():
    size, pivot = (52, 52), (26, 51)
    frames = []
    anims = {}
    frames.append((('holds', 0), canvas(holds(), size, pivot)))
    anims['holds'] = (1, 1)
    for k in range(6):
        frames.append((('fall', k), canvas(fall_frame(k), size, pivot)))
        frames.append((('churn', k), canvas(churn_frame(k), size, pivot)))
    anims['fall'] = (6, 5)
    anims['churn'] = (6, 6)
    for k in range(8):
        frames.append((('haze', k), canvas(haze_frame(k), size, pivot)))
        frames.append((('caustic', k), canvas(caustic_frame(k), size, pivot)))
    anims['haze'] = (8, 9)
    anims['caustic'] = (8, 7)
    frames.sort(key=lambda f: (list(anims).index(f[0][0]), f[0][1]))
    write('fx_island', sheet_text(
        'fx_island', 'decal', size, pivot, frames, anims,
        ['Water, light and cut marks for Skarvholm\'s new scenes (Book 7 sections 13 and 14): a tile',
         'of hand-holds on a marked climb, the upper stream\'s falling sheet and the churned pool at',
         'its foot, the passages\' damp haze and the light off water on their walls.']))


