def boulder_prop(k, rx, ry, base, weed):
    return I.boulder(k, rx=rx, ry=ry, base=base, weed=weed)


def slab():
    s = Sprite(70, 24, 35, 22)
    for x in range(2, 68):
        top = 4 + int(abs(x - 35) / 30)
        for y in range(top, 15):
            s.px(x, y, C('stone', 4.8 - (y - top) * 0.3 - (1.4 if x % 23 == 0 else 0)))
        for y in range(15, 21):
            s.px(x, y, C('ink', 0))
    return s.outline()


def shoring():
    """Timber shoring: two posts and a lintel, grey with age, set against a passage's wall."""
    s = Sprite(30, 40, 15, 38)
    for (x0, x1) in ((4, 8), (22, 26)):
        for x in range(x0, x1):
            for y in range(6, 38):
                s.px(x, y, C('driftwood', 3.6 - (x == x1 - 1) * 1.4 + (x == x0) * 0.8))
    for x in range(2, 28):
        for y in range(3, 7):
            s.px(x, y, C('driftwood', 4.4 - (y - 3) * 0.6))
    return s.outline()


def goods(k):
    s = Sprite(22, 16, 11, 14)
    if k % 2 == 0:
        for y in range(3, 14):
            for x in range(4, 18):
                if ((x - 11) / 7) ** 2 + ((y - 8.5) / 5.5) ** 2 <= 1:
                    s.px(x, y, C('earth', 3.8 - (x > 11) * 1.2 + (y < 6) * 0.8))
        for x in range(8, 15):
            s.px(x, 3, C('earth', 1))
        if k == 2:
            for x in range(5, 18, 3):
                s.px(x, 9, C('earth', 1.5))           # a cord pattern on the pot
    else:
        for x in range(3, 19):
            for y in range(8, 12):
                s.px(x, y, C('trefoil', 1.2 + (y == 8) * 1.0))  # a bronze bowl
        for (x, y) in ((4, 13), (8, 13), (12, 13), (16, 13)):
            s.px(x, y, C('wool', 5 if k == 1 else 3))         # beads, a pin
    return s.outline()


def door():
    s = Sprite(34, 62, 17, 60)
    for y in range(2, 60):
        for x in range(3, 31):
            s.px(x, y, C('stone', 4.4 + (x < 8) * 0.8 - (y > 52) * 1.0 + (hash01(x // 3, y // 3) - 0.5)))
    for k in range(3):
        for a in range(0, 360, 8):
            rr = 3 + k * 3.2
            x = 17 + math.cos(math.radians(a)) * rr
            y = 26 + math.sin(math.radians(a)) * rr
            s.px(int(round(x)), int(round(y)), C('stone', 2.4))
    return s.outline()


def stake():
    s = Sprite(8, 16, 4, 15)
    for y in range(2, 15):
        s.px(4, y, C('driftwood', 4 - (y > 12) * 2))
        s.px(3, y, C('driftwood', 3))
    s.px(4, 1, C('driftwood', 5))
    return s.outline()


def timbers():
    s = Sprite(72, 14, 36, 12)
    for k in range(3):
        for x in range(4, 68):
            for yy in range(2):
                s.px(x, 3 + k * 3 + yy, C('driftwood', 5 - yy * 2 - (x % 17 == 0)))
    return s.outline()


def lintel():
    s = Sprite(42, 14, 21, 12)
    for x in range(3, 39):
        for yy in range(3, 10):
            s.px(x, yy, C('stone', 5.2 - (yy - 3) * 0.4 + (x < 6) * 0.6))
    for (x, yy) in [(10, 7), (12, 8), (14, 8), (16, 8), (18, 8), (20, 8), (22, 7), (16, 6), (16, 5),
                    (17, 5), (24, 6), (8, 6)]:
        s.px(x, yy, C('stone', 2.2))
    return s.outline()


def turves():
    s = Sprite(18, 14, 9, 12)
    for (dx, dy) in ((-4, 0), (0, 0), (4, 0), (-2, -3), (2, -3), (0, -6)):
        for yy in range(3):
            for xx in range(4):
                s.px(9 + dx - 2 + xx, 9 + dy + yy, C('tar', 3 - yy * 0.6 + (xx == 0) * 0.6))
    return s.outline()


def waymark(k):
    """A waymark: a small cairn of stones piled by passers-by beside a way, each adding one
    (Chapter 1's waymark on the machair; Stage 14's along the island's ways, decision S14-45)."""
    s = Sprite(46, 28, 23, 25)
    layers = [(4, 9.5, 3.4), (3, 7.5, 3.0), (2, 5.6, 2.6), (1, 4.0, 2.2)][: 3 + (k % 2)]
    y = 21
    for row, (n, rx, ry) in enumerate(layers):
        for j in range(n):
            cx = 23 + (j - (n - 1) / 2) * rx * 0.9 + (hash01(k, row, j) - 0.5) * 2
            I.stone(s, cx, y, rx * 0.55, ry * 0.6, 'stone', 4.4 + hash01(k, row, j, 1) * 1.4, seed=k * 31 + row * 7 + j)
        y -= ry * 1.1
    s.ay = 23
    for yy, xx in zip(*np.nonzero(s.mask)):
        if hash01(xx, yy, k + 5) < 0.06:
            s.rgb[yy, xx] = C('trefoil', 1.4)               # lichen
    return s.outline()


