def sheet_text(name, kind, size, pivot, frames, anims, about, shadow=None, footprint=None):
    w, h = size
    lines = [f'# {a}' for a in HEADER + about] + [
        f'sheet: {name}', f'kind: {kind}', 'palette: book07', f'size: {w}x{h}',
        f'pivot: {pivot[0]},{pivot[1]}', f'footprint: {footprint or f"{w}x{h}"}',
        'facings: -', 'placeholder: false',
    ]
    if shadow:
        lines.append(f'shadow: {shadow}')
    for state, (n, ticks) in anims.items():
        lines.append(f'anim.{state}: frames {n}, ticks {ticks}' + (', loop' if n > 1 else ''))
    for (state, i), rows in frames:
        assert len(rows) == h and all(len(r) == w for r in rows), (name, state, i)
        lines += ['', f'frame {state} - {i}', *rows, 'end']
    return '\n'.join(lines) + '\n'


def put(frames, state, i, spr, size, pivot):
    rgb, m = place(spr, size, pivot)
    frames.append(((state, i), codes(rgb, m)))


def canvas(spr, size, pivot):
    """A sprite placed by its own anchor (water and light have no lowest row to stand on)."""
    w, h = size
    rgb = np.zeros((h, w, 3), np.float32)
    mask = np.zeros((h, w), bool)
    dx, dy = pivot[0] - spr.ax, pivot[1] - spr.ay
    for y, x in zip(*np.nonzero(spr.mask)):
        X, Y = x + dx, y + dy
        if 0 <= X < w and 0 <= Y < h:
            rgb[Y, X] = spr.rgb[y, x]
            mask[Y, X] = True
    return codes(rgb, mask)


def prop_cell():
    size, pivot = (160, 116), (80, 112)
    back, front = I.cell_ring()
    frames = []
    # Each half stands on its own feet (art lint); the plan places the back half 5 px above
    # the front so the two meet as drawn (zone_sk_geo.plan.json).
    put(frames, 'back', 0, back, size, pivot)
    put(frames, 'front', 0, front, size, pivot)
    put(frames, 'altar', 0, I.altar().padded(1), size, pivot)
    put(frames, 'cross', 0, I.cross_slab().padded(1), size, pivot)
    put(frames, 'cross_lit', 0, I.cross_slab(lit_edge=True).padded(1), size, pivot)
    write('prop_cell', sheet_text(
        'prop_cell', 'prop', size, pivot, frames,
        {'back': (1, 1), 'front': (1, 1), 'altar': (1, 1), 'cross': (1, 1), 'cross_lit': (1, 1)},
        ['The hermit\'s cell above Gull Geo (Book 9 section 03): a roofless beehive ring of drystone,',
         'its roof fallen when it burned, the doorway east; the burned altar against its west wall;',
         'the slab beside the doorway with the cross cut in it. The ring is drawn in two halves,',
         'placed at the same foot: the back (with the floor) and the front.'],
        shadow='120x16', footprint='136x40'))


