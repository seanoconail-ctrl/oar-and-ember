class Survivor(P.Resident):
    """A survivor in working clothes (the scavengers' cut: no sash, never the steerer's madder)."""

    def __init__(self, model, cloak):
        super().__init__(model, (), cloak=cloak)


class Derbail(P.Runa):
    """Derbáil: Runa's pinned hair and knot, her own heather-dyed dress; no wound bound on her
    (Hild's and Runa's leg hook binds a shin) and no tool on her shoulder."""

    def __init__(self):
        super().__init__()
        self.mats = DERBAIL_MATS

    def leg_hook(self, part, side, J, facing):
        return

    def extras(self, parts, facing, j, pose, prev, rows, lag_u, lag_f):
        P.work_tool(parts, facing, j, pose)


