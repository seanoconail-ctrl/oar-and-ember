def write(key):
    w = WHO[key]
    ch = w['make']()
    if key == 'derbail':
        P.CUR.update(head=P.HEAD_RUNA, braid=False)
    states = w['states']()
    names = w['names']
    sheets = P.render_character(ch, states, w['mats'], w['order'], names, {},
                                getattr(ch, 'soft', P.SOFT))
    anims = {state: (P.frames_of(state, fn), ticks, loop) for state, fn, ticks, loop in states}
    intro = INTRO.format(name=w['name'])
    for L, sh in sheets.items():
        sh.intro = intro + f'\n# {P.LAYER_NOTE[L]}'
        if L == 'body':
            sh.shadow = '16x5'
        with open(f'{MAPS}/{sh.name}.map.txt', 'w') as fh:
            fh.write(sh.text(anims, 'walk 0, walk 3, run 0, run 4', w['poses']))
    order = w['order']
    layers = {f: [names[L] for L in order[f] if L in names] for f in P.FACINGS}
    with open(f'{LAYERS}/{key}.layers.json', 'w') as fh:
        fh.write(json.dumps({'name': key, 'layers': layers}, indent=2) + '\n')
    P.CUR.update(head=P.HEAD_HILD, braid=True, cloth='dress')
    return sheets


def main():
    for key in WHO:
        write(key)
    if P.CUT:
        for c in sorted(P.CUT):
            print('cut off by the canvas:', c)
        raise SystemExit(1)
    print('wrote the survivors: ' + ', '.join(WHO))


if __name__ == '__main__':
    main()
