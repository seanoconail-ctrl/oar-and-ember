# ---------------------------------------------------------------------------- the poses
HUG_R = (-3.0, 3.2, -5.4)      # the right hand clutching the left upper arm, across the chest
HUG_L = (3.0, 3.6, -6.4)       # the left hand clutching the right, under it
HUG_ELBOW = {'R': (1.0, -0.4, 0.0), 'L': (1.0, -0.5, 0.0)}
SHAKE = (0.0, 0.6, 0.0, -0.6)  # the pelvis's quick tremble, a pixel either way


def anim_shiver():
    """Soaked and cold: arms wrapped round the body, shoulders hunched, a quick tremble (4 frames
    at 15 a second) in place of the slow breath."""
    out = []
    for i, r in enumerate(SHAKE):
        p = P.Pose(pel=(r, 0.0, 0.0), breath=-1 if i % 2 else 0, lean=(-0.3 * r, 0.4))
        p.hands = {'R': HUG_R, 'L': HUG_L}
        p.elbow = dict(HUG_ELBOW)
        p.grip = {'R': 'fist', 'L': 'fist'}
        out.append(p)
    return out


def anim_hug_wind():
    """Braced into the wind from the west, arms wrapped round, shivering; cloth and hair stream."""
    out = []
    for i, (w, r) in enumerate(zip((0.8, 1.0, 0.9, 1.0), SHAKE)):
        p = P.Pose(pel=(r, 0.0, 0.0), wind=w, flap=i, brace=1.0, breath=-1 if i % 2 else 0)
        p.hands = {'R': HUG_R, 'L': HUG_L}
        p.elbow = dict(HUG_ELBOW)
        p.grip = {'R': 'fist', 'L': 'fist'}
        out.append(p)
    return out


def anim_cling():
    """Holding the broken boat's gunwale in the wash: leaning on it with both hands forward at
    chest height, shaking, the head turning to call over the shoulder and back (6 frames)."""
    spec = [
        # turn, mouth, pelvis shake, lean forward
        (0, 0, 0.0, 1.4),
        (0, 0, 0.6, 1.4),
        (-1, 1, 0.0, 1.0),
        (-1, 1, -0.6, 1.0),
        (0, 0, 0.0, 1.4),
        (0, 0, -0.6, 1.6),
    ]
    out = []
    for turn, mouth, r, lean in spec:
        p = P.Pose(pel=(r, 0.0, 0.0), lean=(0.0, lean), turn=turn, mouth=mouth)
        p.hands = {'R': (2.0, 6.4, -3.2), 'L': (-2.0, 6.6, -3.6)}
        p.elbow = {'R': (1.0, -0.2, 0.2), 'L': (1.0, -0.2, 0.2)}
        p.grip = {'R': 'fist', 'L': 'fist'}
        p.feet_r = {'R': 0.5, 'L': -0.5}
        out.append(p)
    return out


def moving(heavy=False):
    """A person's walk and run with their starts and stops (Book 7 section 01; addendum 2.5)."""
    keep = ('walk', 'run', 'runstart', 'runstop', 'walkstart', 'walkstop')
    return [s for s in P.states_for(heavy, bow=False) if s[0] in keep]


def states_resident(call):
    return ([('idle', anim_shiver, 4, True),
             ('shift', P.anim_shift, 20, True),
             ('glance', P.anim_glance, 24, True),
             ('idlewind', anim_hug_wind, 6, True)]
            + moving()
            + [('call', call, 9, True),
               ('down', P.Lying('downed', 2), 40, True),
               ('carried', None, 5, True)])


def states_dress():
    keep = ('walk', 'run', 'runstart', 'runstop')
    return ([('idle', anim_shiver, 4, True),
             ('shift', P.anim_shift, 20, True),
             ('glance', P.anim_glance, 24, True),
             ('idlewind', anim_hug_wind, 6, True)]
            + [s for s in P.HILD_STATES if s[0] in keep]
            + [('call', P.anim_call, 10, True),
               ('down', None, 24, True),
               ('carried', None, 5, True)])


