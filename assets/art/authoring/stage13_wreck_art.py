HEADER = ['Generated by assets/art/authoring/stage13_wreck_art.py (Stage 13, the wreck on',
          'Sgeir Dhubh), from the mockup\'s painting (docs/art/mockup-src/sea_wreck.py).',
          'Do not edit by hand: change the script and run it again.']


def sheet_text(name, kind, size, pivot, frames, anims, about, shadow=None, footprint=None):
    w, h = size
    lines = [f'# {a}' for a in HEADER + about] + [
        f'sheet: {name}', f'kind: {kind}', 'palette: book07', f'size: {w}x{h}',
        f'pivot: {pivot[0]},{pivot[1]}', f'footprint: {footprint or f"{w}x{h}"}',
        'facings: -', 'placeholder: false',
    ]
    if shadow:
        lines.append(f'shadow: {shadow}')
    for state, (n, ticks) in anims.items():
        lines.append(f'anim.{state}: frames {n}, ticks {ticks}' + (', loop' if n > 1 else ''))
    for (state, i), rows in frames:
        assert len(rows) == h and all(len(r) == w for r in rows), (name, state, i)
        lines += ['', f'frame {state} - {i}', *rows, 'end']
    return '\n'.join(lines) + '\n'


def anchored(spr, size, pivot):
    """A sprite on the canvas by its own anchor (water pieces have no lowest row to stand on)."""
    w, h = size
    rgb = np.zeros((h, w, 3), np.float32)
    mask = np.zeros((h, w), bool)
    dx, dy = pivot[0] - spr.ax, pivot[1] - spr.ay
    for y, x in zip(*np.nonzero(spr.mask)):
        X, Y = x + dx, y + dy
        if 0 <= X < w and 0 <= Y < h:
            rgb[Y, X] = spr.rgb[y, x]
            mask[Y, X] = True
    return codes(rgb, mask)


def prop_sea_wreck():
    size, pivot = (116, 60), (58, 53)
    frames = []
    for k in range(4):
        rgb, m = place(SW.faoilean(k).padded(1), size, pivot)
        frames.append((('broken', k), codes(rgb, m)))
    rgb, m = place(SW.cask().padded(1), size, pivot)
    frames.append((('cask', 0), codes(rgb, m)))
    rgb, m = place(SW.iron_bundle().padded(1), size, pivot)
    frames.append((('iron', 0), codes(rgb, m)))
    write('prop_sea_wreck', sheet_text(
        'prop_sea_wreck', 'prop', size, pivot, frames,
        {'broken': (4, 14), 'cask': (1, 1), 'iron': (1, 1)},
        ['The Faoileán, an Ardcarn boat, broken-backed on the reef (Book 6 section 19): her bow',
         'lifted on the rocks, her stern settled, the sea slopping in the break; and the cask and',
         'the iron from her hold in the wash.'],
        shadow='90x12', footprint='90x10'))


def fx_sea_wreck():
    size = (44, 30)
    frames = []
    for k in range(6):
        frames.append((('spray', k), anchored(SW.spray_burst(k), size, (22, 27))))
    for k in range(4):
        frames.append((('kelp', k), anchored(SW.kelp(k), size, (22, 27))))
    for k in range(4):
        frames.append((('sail', k), anchored(SW.sail_awash(k), size, (22, 27))))
    write('fx_sea_wreck', sheet_text(
        'fx_sea_wreck', 'decal', size, (22, 27), frames,
        {'spray': (6, 6), 'kelp': (4, 12), 'sail': (4, 10)},
        ['Water and weed of the wreck on Sgeir Dhubh: spray on the rocks, kelp under the',
         'shallows and the sail awash. No outline and no ground shadow: they are water.']))


def main():
    prop_sea_wreck()
    fx_sea_wreck()
    print('wrote prop_sea_wreck and fx_sea_wreck')


if __name__ == '__main__':
    main()
