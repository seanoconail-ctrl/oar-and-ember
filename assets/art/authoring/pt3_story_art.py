# ------------------------------------------------------------------------------ the sea burial
SW, SH = 128, 60
SP = (64, 44)


def bier_points(wet, stream=0):
    """The bier as points on the ground plane: (u along it, v across it, height, colour)."""
    pts = []
    # Planks of the wreck, five across, with tarred seams and two lashings.
    for u in range(-22, 23):
        for v in range(-5, 6):
            seam = v in (-3, 0, 3)
            col = C('tar', 2) if seam else C('driftwood', 4 + ((u + 40) // 9 + v) % 2 - (wet > 1))
            if abs(u) in (14, 15):
                col = C('earth', 3 - (u < 0))
            pts.append((u, v, 0, col))
            pts.append((u, v, 1, col))
            if v == 5:
                pts.append((u, v, -1, C('driftwood', 2)))
    # The body wrapped in his cloak, head to the west: a long rounded bundle.
    cloak = 3 if wet == 0 else 2
    for u in range(-17, 19):
        for v in range(-4, 5):
            r = (v / 4.2) ** 2 + (max(0, abs(u) - 14) / 4) ** 2
            if r > 1:
                continue
            hgt = 2 + int(round(4.5 * math.sqrt(max(0, 1 - r))))
            fold = (u * 3 + v * 5) % 7 == 0
            c = C('stone', cloak + (v < 0) - fold)
            if wet >= 1 and v >= 2:
                c = C('stone', 1 + (v < 4))          # the hem darkened by the first wave
            if wet >= 2 and (u + v + stream) % 5 == 0 and v > 0:
                c = C('sea', 8)                       # water streaming off in 1 px runs
            for h in range(2, hgt + 1):
                pts.append((u, v, h, c))
            if v == -4 and u % 4 == 0:
                pts.append((u, v, hgt, C('woad', 2)))   # the trim
    # His face at the west end, his beard grey; a hand on his chest with the ring.
    for u in range(-17, -13):
        for v in range(-2, 3):
            pts.append((u, v, 6, C('skin_light', 3 + (v < 0))))
    for u in range(-14, -12):
        for v in range(-1, 2):
            pts.append((u, v, 6, C('stone', 7)))
    for v in (-1, 0):
        pts.append((-4, v, 7, C('skin_light', 3)))
    pts.append((-4, 1, 7, C('fire', 6)))            # the gold ring, one bright pixel
    return pts


def render_points(pts, angle=0.0, pitch=0.0, drop=0):
    """Projects ground-plane points (turned `angle` degrees, the west end dipping by `pitch`)."""
    s = Sprite(SW, SH, SP[0], SP[1])
    a = math.radians(angle)
    zb = np.full((SH, SW), -1e9, np.float32)
    for (u, v, h, col) in pts:
        x = u * math.cos(a) - v * math.sin(a)
        y = (u * math.sin(a) + v * math.cos(a)) * 0.55
        hh = h - max(0, -u) * pitch
        sx = int(round(SP[0] + x))
        sy = int(round(SP[1] - 3 + y - hh + drop))
        depth = y + hh * 0.01
        if 0 <= sx < SW and 0 <= sy < SH and depth >= zb[sy, sx]:
            zb[sy, sx] = depth
            s.px(sx, sy, col)
    return s.outline()


def foam_px(s, x, y, k=0):
    s.px(x, y, C('sea', 10 if (x + y + k) % 3 else 9))


def wave_sprite(k):
    """The big wave's foam band rushing up the shingle (k 0..3) and drawing back (4..7)."""
    s = Sprite(SW, SH, SP[0], SP[1])
    if k < 4:
        thick = 3 + k * 2
        rise = 0
    else:
        thick = 8 - (k - 4) * 2
        rise = (k - 4) * 2
    for x in range(2, SW - 2):
        edge = 30 - int(round(3 * math.sin(x * 0.13 + k) + 2 * math.sin(x * 0.31)))
        for d in range(thick):
            y = edge + d + rise
            if k >= 4 and (x * 7 + d * 3 + k) % 4 == 0:
                continue                             # lacy as it draws back
            col = C('sea', 10) if d < 2 else C('sea', 9 - min(2, d // 3))
            s.px(x, y, col)
        if k < 4 and x % 5 == 0:
            s.px(x, edge - 1, C('sea', 10))          # spray thrown up at the crest
    return s


def wash_sprite(k):
    """The first wave washing round the bier to both sides and past it, then draining away."""
    s = Sprite(SW, SH, SP[0], SP[1])
    rx, ry = 29 + k * 2, 7 + k
    thick = [4, 5, 5, 4, 3, 2][k]
    for t in range(0, 360, 1):
        a = math.radians(t)
        lump = thick + int(round(2 * hash01(t // 9, k, 7)))
        for d in range(lump):
            x = int(round(SP[0] + math.cos(a) * (rx - d * 0.8)))
            y = int(round(SP[1] - 4 + math.sin(a) * (ry - d * 0.45)))
            if hash01(x, y, 31 + k) < (0.85 if k < 3 else 0.55):
                s.px(x, y, C('sea', 10 if d < 2 else 9))
    return s


def over_sprite(k):
    """The second wave's foam over the whole bier, then breaking up as it drains off."""
    s = Sprite(SW, SH, SP[0], SP[1])
    cover = [0.95, 0.9, 0.8, 0.6, 0.4, 0.2][k]
    for x in range(SP[0] - 28, SP[0] + 29):
        for y in range(SP[1] - 16, SP[1] + 6):
            dx = (x - SP[0]) / 28
            dy = (y - (SP[1] - 5)) / 11
            if dx * dx + dy * dy > 1:
                continue
            if hash01(x, y, 17 + k) < cover:
                s.px(x, y, C('sea', 10 if hash01(x, y, 3) > 0.35 else 9))
    return s


def trail_sprite(k):
    s = Sprite(SW, SH, SP[0], SP[1])
    for i in range(14):
        x = SP[0] - 18 + i * 3 + (k % 2)
        y = SP[1] - 10 - int(i * 0.4) - k
        if (i + k) % 3 != 0:
            foam_px(s, x, y, k)
            foam_px(s, x + 1, y, k)
    return s


def ring_sprite(k):
    """The ring of foam and bubbles spreading where it went, and fading."""
    s = Sprite(SW, SH, SP[0], SP[1])
    r = 8 + k * 5
    keep = 1 - k / 9
    for t in range(0, 360, 3):
        a = math.radians(t)
        x = int(round(SP[0] + math.cos(a) * r))
        y = int(round(SP[1] - 6 + math.sin(a) * r * 0.42))
        if hash01(t, k, 5) < keep:
            foam_px(s, x, y, k)
    for i in range(10 - k):
        x = SP[0] + int((hash01(i, k, 9) - 0.5) * r * 1.2)
        y = SP[1] - 6 + int((hash01(i, k, 11) - 0.5) * r * 0.5)
        s.px(x, y, C('sea', 9))
    return s


def bubble_sprite(k):
    s = Sprite(SW, SH, SP[0], SP[1])
    for i in range(7):
        x = SP[0] - 9 + i * 3
        y = SP[1] - 6 - ((k * 2 + i * 3) % 7)
        s.px(x, y, C('sea', 10))
        if i % 2:
            s.px(x + 1, y, C('sea', 9))
    return s


def write_sea():
    frames = []
    for k, (wet, stream) in enumerate(((0, 0), (1, 0), (2, 0), (2, 2))):
        frames.append((('bier', '-', k), raw_rows(render_points(bier_points(wet, stream)), (SW, SH), SP)))
    for k in range(5):
        frames.append((('float', '-', k), raw_rows(render_points(bier_points(2, k), angle=k * 15), (SW, SH), SP)))
    for k in range(4):
        spr = render_points(bier_points(3, k), angle=60, pitch=0.04 * (k + 1), drop=k)
        frames.append((('tilt', '-', k), raw_rows(spr, (SW, SH), SP)))
    for k in range(8):
        frames.append((('wave', '-', k), raw_rows(wave_sprite(k), (SW, SH), SP)))
    for k in range(6):
        frames.append((('wash', '-', k), raw_rows(wash_sprite(k), (SW, SH), SP)))
    for k in range(6):
        frames.append((('over', '-', k), raw_rows(over_sprite(k), (SW, SH), SP)))
    for k in range(4):
        frames.append((('trail', '-', k), raw_rows(trail_sprite(k), (SW, SH), SP)))
    for k in range(8):
        frames.append((('ring', '-', k), raw_rows(ring_sprite(k), (SW, SH), SP)))
    for k in range(4):
        frames.append((('bubble', '-', k), raw_rows(bubble_sprite(k), (SW, SH), SP)))
    write('fx_sea_burial', sheet_text(
        'fx_sea_burial', 'decal', (SW, SH), SP, frames,
        {'bier': (4, 12), 'float': (5, 12), 'tilt': (4, 30), 'wave': (8, 6), 'wash': (6, 8),
         'over': (6, 9), 'trail': (4, 8, 'loop'), 'ring': (8, 11), 'bubble': (4, 6, 'loop')},
        HEADER + ['Thorkel taken by the sea (Book 7 section 07; decision DG-14): his body wrapped in his dark',
                  'cloak on a bier of the wreck\'s planks, the gold ring one bright pixel on his hand; wet,',
                  'soaked and streaming; afloat and turning; the planks tilting after him as he sinks; the',
                  'set of waves\' foam band, the wash round the bier, the foam over it, the trail, the ring',
                  'of foam and bubbles where it went. Masked by the water like a wader, never faded.']))


if __name__ == '__main__':
    write_shelter()
    write_sea()
