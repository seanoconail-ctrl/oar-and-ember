"""Builds the user's third playtest's story art (Book 7 sections 06, 07 and 14), painted with the
approved mockup's palette ramps (docs/art/mockup-src) and written as palette-coded sheets:

- prop_shelter_frame: the shelter's stages before the lean-to (decision DG-12), on the lean-to's own
  canvas so every stage stands exactly where prop_sail_leanto will: the torn sail folded with three
  oars (`folded`); the frame going up under the steerer's build loop (`raise`, 8 frames: each oar
  stood against the wall, the third laid across as the ridge and lashed where it crosses them, the
  guys pegged); the frame standing, its guys and the folded sail's loose corner stirring in the wind
  (`frame`, a loop); the sail hauled over the ridge and lashed along it, half lashed with its top
  corner flogging, then the foot weighted with stones (`haul`, 8 frames), before prop_sail_raise's
  `fill` frames settle it into the lean-to; and the second day's finishing beside it, turves cut and
  stacked on the weather side with a mallet and pegs (`turf`, 4 frames by the work's share).
- fx_sea_burial: Thorkel taken by the sea (decision DG-14): his body wrapped in his dark cloak on a
  bier of the wreck's planks, the ring a single bright pixel on his hand (`bier`: dry, the hem wet,
  soaked and streaming in 1 px runs); afloat and turning with the swell (`float`, 0 to 60 degrees);
  the planks tilting and sliding after him as he sinks (`tilt`); the set of waves bigger than the
  day's surf, a foam band rushing up the shingle and drawing back (`wave`); the first washing round
  the bier (`wash`); the second's foam over it (`over`); the foam trail as it drifts (`trail`); the
  ring of foam and bubbles where it went (`ring`); bubbles rising (`bubble`).

    python3 assets/art/authoring/pt3_story_art.py && npm run art:compile
"""
