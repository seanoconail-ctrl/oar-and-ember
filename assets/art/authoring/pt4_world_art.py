SMOKE_SIZE, SMOKE_PV = (32, 32), (16, 30)


def smoke(i, n=6):
    """A wisp of hearth smoke at age i/n: a soft dithered curl that grows, lifts and thins."""
    spr = Sprite(*SMOKE_SIZE, *SMOKE_PV)
    t = i / (n - 1)
    rad = 3 + t * 9
    cy = 26 - t * 10
    density = 0.62 - t * 0.42
    from core import bayer
    B = bayer(SMOKE_SIZE[1], SMOKE_SIZE[0])
    for y in range(SMOKE_SIZE[1]):
        for x in range(SMOKE_SIZE[0]):
            curl = 2.2 * math.sin((y + i * 2) * 0.45) * t
            d = math.hypot((x - 16 - curl) / 1.15, (y - cy) / 0.85)
            if d < rad:
                fall = 1 - d / rad
                if B[y, x] < density * (0.4 + fall):
                    spr.px(x, y, C('smoke', 4 - (y > cy) + (fall > 0.6) - t * 1.5))
    return spr


