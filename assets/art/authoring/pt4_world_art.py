def waymark(i):
    spr = Sprite(*FIND_SIZE, *FIND_PV)
    stones = [(12, 26, 4.2), (18, 26.5, 4.6), (24, 26, 4.0), (15, 22.5, 3.8), (21, 22.5, 3.9),
              (18, 19, 3.4), (16, 15.5, 2.8), (20, 15.8, 2.6), (18, 12.6, 2.4), (19, 10, 1.8)]
