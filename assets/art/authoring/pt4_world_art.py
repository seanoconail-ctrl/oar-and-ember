FLOOR_TILE0 = (29, 25)          # the decal's top-left world tile
FLOOR_SIZE = (312, 288)          # 13 x 12 tiles
FLOOR_PV = (156, 287)            # placed at (35.5, 37.0) tiles: its foot at the canvas's bottom


def zone_rows():
    return json.load(open(f'{REPO}/content/zones/zone_sk_machair.json'))['rows']


def floor(stage):
    rows = zone_rows()
    T = 24
    w, h = FLOOR_SIZE
    spr = Sprite(w, h, *FLOOR_PV)
    ox, oy = FLOOR_TILE0[0] * T, int(round(37.0 * T)) - FLOOR_PV[1]

    def blocked(wx, wy):
        tx, ty = int(wx // T), int(wy // T)
        if ty < 0 or ty >= len(rows) or tx < 0 or tx >= len(rows[0]):
            return True
        return rows[ty][tx] in 'R'

    # Distance in px to the wall (rock), sampled.
    def wall_dist(wx, wy):
        best = 99.0
        for dy in range(-8, 9, 2):
            for dx in range(-8, 9, 2):
                if blocked(wx + dx, wy + dy):
                    best = min(best, math.hypot(dx, dy))
        return best

    cxw, cyw = 35.5 * T, 31.6 * T
    door = (35.5 * T, 36.2 * T)
    hearth = (35.4 * T, 31.75 * T)
    bedw = (33.3 * T, 29.9 * T)
    path = [door, (35.6 * T, 34.0 * T), hearth, (34.4 * T, 30.6 * T), bedw]

    def seg_dist(px, py):
        best = 1e9
        for (ax, ay), (bx, by) in zip(path, path[1:]):
            vx, vy = bx - ax, by - ay
            t = max(0, min(1, ((px - ax) * vx + (py - ay) * vy) / (vx * vx + vy * vy)))
            best = min(best, math.hypot(px - ax - vx * t, py - ay - vy * t))
        return best

    for y in range(h):
        for x in range(w):
            wx, wy = ox + x, oy + y
            if blocked(wx, wy):
                continue
            # Only the court: inside the broch's ring.
            if math.hypot((wx - cxw) / 1.0, (wy - cyw) / 1.0) > 4.6 * T:
                continue
            n = hash01(x // 2, y // 2, 171)
            d = wall_dist(wx, wy)
            # The foot of the wall: damp, shadowed ground (depth), dithered so no edge runs straight.
            if d < 5 + 3 * n:
                if (x + y) % 2 == 0 or d < 3:
                    spr.px(x, y, C('earth', 1) if stage == 's1' else C('moss', 1))
                continue
            # The trodden path.
            sd = seg_dist(wx, wy)
            if sd < 7 + 4 * n:
                if sd < 4 + 2 * n or (x + y) % 2 == 0:
                    spr.px(x, y, C('earth', 3 + (hash01(x, y, 172) < 0.25)) if stage == 's0'
                           else C('earth', 2 + (hash01(x, y, 172) < 0.3)))
                continue
            # Ash and charcoal round the hearth, thinning out.
            hd = math.hypot((wx - hearth[0]) / 1.3, wy - hearth[1])
            if hd < 34 and hash01(x, y, 173) < 0.55 * (1 - hd / 34):
                spr.px(x, y, C('smoke', 1 + (hash01(x, y, 174) < 0.4)) if hash01(x, y, 175) < 0.8
                       else C('tar', 0))
                continue
            # S1: rushes strewn over the flags in drifts, by the beds.
            if stage == 's1':
                if hash01(x // 6, y // 3, 176) < 0.18 and hash01(x, y, 177) < 0.5:
                    spr.px(x, y, C('marram', 3 + (hash01(x, y, 178) < 0.4)))
            # Chips by the woodpile (38.3, 33.5).
            wd = math.hypot(wx - 38.3 * T, wy - 33.7 * T)
            if wd < 18 and hash01(x, y, 179) < 0.12:
                spr.px(x, y, C('driftwood', 5))
    return spr


