def bed(stage, lit=False):
    """The steerer's bed (requests 15 and 26): 2 tiles long and 1 deep (Book 7 section 01), its
    ground marked by a kerb of flat beach stones; the head at the west (wall) end."""
    spr = Sprite(60, 28, 30, 27)
    cx, cy = 30, 15.5
    rx, ry = 26.5, 10.5
    # The bedding: bracken heaped, heather tops showing, inside the kerb.
    r = np.random.default_rng(907)
    for k in range(26):
        bx, by = r.uniform(cx - rx + 6, cx + rx - 6), r.uniform(cy - ry + 4, cy + ry - 3)
        blob(spr, bx, by, r.uniform(3, 5.5), r.uniform(2, 3.2), 'bracken', 2)
    for y, x in zip(*np.nonzero(spr.mask)):
        if hash01(x, y, 61) < 0.22:
            spr.rgb[y, x] = C('violet', 1 + (hash01(x, y, 62) < 0.4))
        elif hash01(x, y, 63) < 0.08:
            spr.rgb[y, x] = C('bracken', 4)
    if stage == 's1':
        # A sheepskin under the sleeper (the finished shelter's comfort).
        for y in range(int(cy - 6), int(cy + 7)):
            for x in range(10, 49):
                d = ((x - 29.5) / 19.5) ** 2 + ((y - cy - 0.5) / 6.6) ** 2
                if d < 1 - 0.12 * hash01(x, y, 64):
                    spr.px(x, y, C('fleece', 3 + (hash01(x // 2, y, 65) < 0.4) - (y > cy + 4)))
    # The pillow: a rolled dark cloak at the west end.
    for y in range(int(cy - 5), int(cy + 4)):
        for x in range(7, 15):
            if ((x - 10.5) / 4) ** 2 + ((y - cy + 0.5) / 4.6) ** 2 < 1:
                spr.px(x, y, C('driftwood', 3 + (x < 10) - (y > cy + 1) + ((x + y) % 4 == 0)))
    # The madder blanket, folded back towards the foot: two layers, the fold's edge lighter.
    for y in range(int(cy - 6), int(cy + 7)):
        for x in range(30, 51):
            if ((x - 40) / 11) ** 2 + ((y - cy) / 6.8) ** 2 < 1:
                spr.px(x, y, wool_weave(x, y, 'madder', 3 - (y > cy + 3)))
    for y in range(int(cy - 6), int(cy + 7)):
        x = 30 + int(round(1.5 * math.sin(y * 0.9)))
        for k in range(2):
            if spr.mask[y, x + k]:
                spr.px(x + k, y, C('madder', 5 - k))
    for x in range(33, 49, 3):                     # the fringe at its end
        spr.px(x, int(cy + 6.5), C('madder', 4))
    # The kerb: flat beach stones laid round it, every stone its own (the mark on the floor).
    n = 30
    for k in range(n):
        a = k / n * math.tau
        sx = cx + math.cos(a) * rx
        sy = cy + math.sin(a) * ry
        s = Sprite(9, 7, 4, 5)
        stone(s, 4.5, 3.5, 2.6 + hash01(k, 71) * 0.8, 1.7 + hash01(k, 72) * 0.5,
              'stone_warm' if hash01(k, 73) < 0.35 else 'stone', 5, seed=k * 11 + 5)
        for yy, xx in zip(*np.nonzero(s.mask)):
            spr.px(int(round(sx)) - s.ax + xx, int(round(sy)) - s.ay + yy + 1, s.rgb[yy, xx])
    if lit:
        # The in-reach highlight (Book 7 section 13): a one-pixel edge just inside the ink line.
        edge(spr, C('wool', 6))
    spr.outline()
    return spr


