def head_of(sheet):
    """The person's head (hair and face) from their body sheet's lying frame, turned a quarter so
    the crown points east and the face turns up out of the pillow."""
    px = read_frame(sheet, 'sleep', 'e', 0)
    if not px:
        px = read_frame(sheet, 'down', 'e', 0)
    # The head is the cluster at the frame's east end above the body: rows 30 to 41, x >= 19.
    def keep(x, y):
        if y <= 38:
            return x >= 20
        if y == 39:
            return 22 <= x <= 31
        if y == 40:
            return 23 <= x <= 26          # the chin; the hand beside it stays under the blanket
        return False
    head = {(x, y): c for (x, y), c in px.items() if 29 <= y <= 40 and keep(x, y)}
    if not head:
        return {}
    xs = [x for x, _ in head]
    ys = [y for _, y in head]
    x0, y0 = min(xs), min(ys)
    h = max(ys) - y0 + 1
    # A quarter turn clockwise: (x, y) -> (h - 1 - y, x).
    return {(h - 1 - (y - y0), x - x0): c for (x, y), c in head.items()}


def sleeper(name, i):
    sheet, (bramp, bbase), (pramp, pbase), pose = SLEEPERS[name]
    spr = Sprite(*SLEEP_SIZE, *SLEEP_PV)
    # Breathing over four frames: the chest rises a pixel on the second and third.
    lift = (0, 1, 1, 0)[i]
    g = 21                         # the ground line (the bed's surface)
    x1 = 33                        # the blanket's neck edge (the head lies east of it)
    # How high the blanket stands over the body along it (px), by pose: shoulder, waist, hip,
    # thigh, knees and feet, from the neck back to the feet.
    if pose == 'side':
        x0, prof = 5, [(33, 7), (29, 8), (24, 6), (19, 8), (13, 6), (9, 6), (6, 4)]
    elif pose == 'curled':
        x0, prof = 11, [(33, 7), (29, 8), (25, 7), (20, 9), (15, 8), (12, 6)]
    elif pose == 'front':
        x0, prof = 4, [(33, 6), (29, 7), (23, 5), (17, 6), (10, 5), (6, 5), (4, 3)]
    else:  # back
        x0, prof = 4, [(33, 6), (28, 7), (22, 9), (16, 6), (10, 5), (6, 6), (4, 4)]
    def height(x):
        pts = sorted(prof)
        if x <= pts[0][0]:
            return pts[0][1]
        for (xa, ha), (xb, hb) in zip(pts, pts[1:]):
            if xa <= x <= xb:
                t = (x - xa) / (xb - xa)
                t = t * t * (3 - 2 * t)
                return ha + (hb - ha) * t
        return pts[-1][1]
    # The pillow, under the head at the east end: a rolled cloak, lit from the upper left.
    for y in range(g - 9, g + 1):
        for x in range(32, 45):
            d = ((x - 38.5) / 6.3) ** 2 + ((y - g + 4) / 4.4) ** 2
            if d < 1:
                spr.px(x, y, C(pramp, pbase + (y < g - 5) - (y > g - 2) - (x > 42) + ((x - y) % 6 == 0)))
    # The blanket: its lit top surface, its side in shade, a dark line where it meets the bed.
    for x in range(x0, x1 + 1):
        hgt = height(x) + (lift if x1 - 13 <= x <= x1 - 2 else 0)
        # Round the foot end and the neck edge.
        if x - x0 < 3:
            hgt -= (3 - (x - x0)) * 1.2
        top = int(round(g - 1 - hgt))
        for y in range(top, g + 1):
            k = y - top
            if k <= 1:
                step = bbase + 1
            elif y >= g - 1:
                step = bbase - 2 if y == g else bbase - 1
            elif k <= 4:
                step = bbase
            else:
                step = bbase - 1
            spr.px(x, y, wool_weave(x, y, bramp, step))
    # Folds: soft creases running down from the hip and the shoulder.
    for (fx, slope) in [(20, -0.5), (26, 0.4), (12, -0.3)]:
        if fx <= x0 + 2:
            continue
        top = int(round(g - 1 - height(fx)))
        for k in range(2, g - top - 1):
            x = int(round(fx + slope * k))
            if spr.mask[top + k, x]:
                spr.px(x, top + k, C(bramp, bbase - 1))
    # The blanket's turned-down edge at the neck: a lighter band, the border stripe.
    top = int(round(g - 1 - height(x1)))
    for y in range(top, g):
        spr.px(x1, y, C(bramp, bbase + 2))
        spr.px(x1 - 1, y, C(bramp, bbase + 1))
        spr.px(x1 - 3, y, C(bramp, bbase + 2 if y % 2 else bbase))
    # The head, turned on the pillow.
    head = head_of(sheet)
    if head:
        hw = max(x for x, _ in head) + 1
        hh = max(y for _, y in head) + 1
        ox = 34 + max(0, (9 - hw) // 2)
        oy = g - 4 - hh
        for (x, y), c in head.items():
            spr.px(ox + x, oy + y, c)
    # A hand over the blanket (face down: an arm flung out over the pillow's end).
    if pose == 'front':
        for k in range(7):
            spr.px(31 + k, g - 10 + (k > 4), C('skin_light', 3 + (k > 4)))
        spr.px(38, g - 9, C('skin_light', 4))
    elif pose in ('side', 'curled'):
        t = int(round(g - 1 - height(x1 - 6))) - lift
        spr.px(x1 - 6, t + 1, C('skin_light', 4))
        spr.px(x1 - 5, t + 1, C('skin_light', 4))
        spr.px(x1 - 6, t + 2, C('skin_light', 2))
    spr.outline()
    return spr


def mirrored(spr):
    m = Sprite(spr.w, spr.h, spr.w - 1 - spr.ax, spr.ay)
    m.rgb = spr.rgb[:, ::-1].copy()
    m.mask = spr.mask[:, ::-1].copy()
    return m


