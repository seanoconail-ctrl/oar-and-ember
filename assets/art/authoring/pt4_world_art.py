def glint(spr, x, y, k):
    """The four-pointed glint of a thing worth picking up (Book 7 section 18), k = 0..2."""
    col = [C('wool', 6), C('gull', 5), C('wool', 5)][k]
    spr.px(x, y, col)
    for d in range(1, 2):
        spr.px(x + d, y, C('wool', 5))
        spr.px(x - d, y, C('wool', 5))
        spr.px(x, y + d, C('wool', 5))
        spr.px(x, y - d, C('wool', 5))


def grass_tufts(spr, seed, cx, cy, n, sway, w=12):
    """Tufts of grass round a thing on the turf, each leaning with the wind's sway (in px)."""
    r = np.random.default_rng(seed)
    for _ in range(n):
        gx = cx + r.uniform(-w, w)
        gy = cy + r.uniform(-2, 1.5)
        hgt = int(r.integers(3, 6))
        for j in range(hgt):
            lean = sway * (j / hgt) ** 1.5
            spr.px(int(round(gx + lean)), int(round(gy - j)), C('grass', 4 + (j > hgt // 2) + (j == hgt - 1)))


def wrack(spr, cx, cy, seed):
    r = np.random.default_rng(seed)
    for _ in range(9):
        blob(spr, cx + r.uniform(-9, 9), cy + r.uniform(-1.5, 1.5), r.uniform(2, 4), 1.4, 'kelp', 3)
    for _ in range(5):
        x = cx + r.uniform(-10, 10)
        for j in range(int(r.integers(3, 7))):
            spr.px(int(x + j), int(cy + r.uniform(-2, 2)), C('driftwood', 4))


def cowries(i, taken=False):
    spr = Sprite(*FIND_SIZE, *FIND_PV)
