def close_outline(spr):
    """Pads by one pixel and inks only the edge pixels that have no ink yet (where a drawing ran
    to its own canvas's border), so the outline is one pixel all round (Book 7 section 11)."""
    spr = spr.padded(1)
    m = spr.mask
    ink = m & (np.abs(spr.rgb - INK).sum(-1) < 1)
    body = m & ~ink
    grow = np.zeros_like(m)
    grow[1:, :] |= body[:-1, :]
    grow[:-1, :] |= body[1:, :]
    grow[:, 1:] |= body[:, :-1]
    grow[:, :-1] |= body[:, 1:]
    add = grow & ~m
    spr.rgb[add] = INK
    spr.mask |= add
    return spr


def on_canvas(spr, size, pivot, ink=True):
    """A Sprite (its outline closed) placed on a frame canvas by its anchor at the pivot; returns codes rows."""
    if ink:
        spr = close_outline(spr)
    w, h = size
    rgb = np.zeros((h, w, 3), np.float32)
    mask = np.zeros((h, w), bool)
    low = np.nonzero(spr.mask.any(1))[0].max()
    for y, x in zip(*np.nonzero(spr.mask)):
        X, Y = x - spr.ax + pivot[0], y - low + pivot[1]
        assert 0 <= X < w and 0 <= Y < h, ('does not fit', spr.w, spr.h, size)
        rgb[Y, X] = spr.rgb[y, x]
        mask[Y, X] = True
    return codes(rgb, mask)


def read_frame(sheet, state, facing, i):
    """A frame of an existing sheet as {(x, y): rgb}."""
    t = open(f'{SHEETS}/{sheet}.txt').read()
    m = re.search(rf'^frame {state} {facing} {i}\n(.*?)\nend', t, re.S | re.M)
    out = {}
    if m is None:
        return out
    for y, row in enumerate(m.group(1).split('\n')):
        for x, c in enumerate(row):
            if c != '.':
                out[(x, y)] = _BY_CODE[c]
    return out


def edge(spr, col):
    """A one-pixel edge in `col` round what is drawn (the in-reach highlight, Book 7 section 13)."""
    m = spr.mask
    grow = np.zeros_like(m)
    grow[1:, :] |= m[:-1, :]
    grow[:-1, :] |= m[1:, :]
    grow[:, 1:] |= m[:, :-1]
    grow[:, :-1] |= m[:, 1:]
    e = grow & ~m
    spr.rgb[e] = col
    spr.mask |= e
    return spr


def wool_weave(x, y, ramp, base):
    """A wool blanket's weave: a faint twill of one step either way."""
    t = (x + y * 2) % 5
    return C(ramp, base + (1 if t == 0 else -1 if t == 3 else 0))


