"""Stage 14's art integration pass (decisions S14-140 to S14-169), written as palette-coded sheets
the art compiler reads, every colour a step of Book 7's ramps:

- ui_stamina_small (decal): Book 7 section 10's small stamina bar beside a climber, a swimmer or
  someone wading waist deep: 1 px columns of a bar 3 px deep inside a carved-wood frame (an end
  cap, a fill and an empty groove), and the same columns lit for the frame's one flash before a
  slide or a sink (decision S14-142).
- fx_seep (decal): bog meltwater seeping down the deep passage's walls in spring (decision
  S14-143): a dark wet runnel with a fresh green bloom of slime along it, a glistening trickle
  whose bright head runs down the face, and a drop that gathers at the wall's foot, falls and
  rings on the wet floor. Four lengths, each an 8-frame loop.

    python3 assets/art/authoring/stage14_integration_art.py && npm run art:compile
"""
import json
import os

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
SHEETS = f'{REPO}/assets/art/sheets'
_pal = json.load(open(f'{REPO}/assets/palette/book07.json'))
CODE = {(e['ramp'], e['step']): e['code'] for e in _pal['entries'] if 'ramp' in e}


def code(ramp, step):
    return CODE[(ramp, step)]


def sheet_text(name, kind, size, pivot, frames, anims, about):
    w, h = size
    lines = [
        '# Generated by assets/art/authoring/stage14_integration_art.py (Stage 14, the art',
        '# integration pass). Do not edit by hand: change the script and run it again.',
    ] + [f'# {a}' for a in about] + [
        f'sheet: {name}', f'kind: {kind}', 'palette: book07', f'size: {w}x{h}',
        f'pivot: {pivot[0]},{pivot[1]}', f'footprint: {w}x{h}', 'facings: -', 'placeholder: false',
    ]
    for state, (n, ticks, loop) in anims.items():
        lines.append(f'anim.{state}: frames {n}, ticks {ticks}' + (', loop' if loop else ''))
    for (state, i), grid in frames:
        rows = [''.join(c or '.' for c in row) for row in grid]
        assert len(rows) == h and all(len(r) == w for r in rows), (name, state, i)
        lines += ['', f'frame {state} - {i}'] + rows + ['end']
    return '\n'.join(lines) + '\n'


def write(name, text):
    with open(f'{SHEETS}/{name}.txt', 'w') as f:
        f.write(text)
    print(f'wrote {SHEETS}/{name}.txt')


def blank(w, h):
    return [[None] * w for _ in range(h)]


# ------------------------------------------------------------------- the small stamina bar
def stamina_small():
    """Columns 5 px tall: the carved-wood frame's top and bottom edges (tar), and inside them a
    bar 3 px deep. The fill is the big bar's green (grass 9, 8 and 6, lit from above); the empty
    groove is dark tar; the caps are the wood's end grain (bracken). The flash lights the frame's
    edges to pale wool for a moment: a shape cue as well as a colour one (the whole frame grows a
    bright rim), and it is never drawn with reduced flashes."""
    edge = code('tar', 1)
    lit = code('wool', 6)
    cols = {
        'cap': [edge, code('bracken', 3), code('bracken', 2), code('bracken', 2), edge],
        'fill': [edge, code('grass', 9), code('grass', 8), code('grass', 6), edge],
        'empty': [edge, code('tar', 2), code('tar', 3), code('tar', 2), edge],
        'cap_flash': [lit, code('bracken', 4), code('bracken', 3), code('bracken', 3), lit],
        'fill_flash': [lit, code('grass', 10), code('grass', 9), code('grass', 7), lit],
        'empty_flash': [lit, code('tar', 3), code('tar', 4), code('tar', 3), lit],
    }
    frames = [((k, 0), [[c] for c in v]) for k, v in cols.items()]
    anims = {k: (1, 1, False) for k in cols}
    about = [
        "Book 7 section 10's small stamina bar beside a climber, a swimmer or someone wading",
        'waist deep (decision S14-142): 1 px columns (an end cap, a fill and the empty groove) and',
        'the same lit for the frame\'s one flash before a slide or a sink.',
    ]
    write('ui_stamina_small', sheet_text('ui_stamina_small', 'decal', (1, 5), (0, 0), frames, anims, about))


# ------------------------------------------------------------------------ the spring seeps
def hashf(*v):
    h = 2166136261
    for x in v:
        h = ((h ^ (int(x) & 0xffffffff)) * 16777619) & 0xffffffff
    return h / 4294967296


SEEP_W, SEEP_H = 9, 30
LENGTHS = [14, 19, 24, 28]


def seep_frame(length, k, seed):
    """One frame of a seep `length` px long (k of 8): the runnel, its slime, the trickle and the
    drop. The pivot is the wall's foot at the bottom centre."""
    g = blank(SEEP_W, SEEP_H)
    foot = SEEP_H - 3          # the wall's foot (the row the drop leaves from)
    top = foot - length
    cx = SEEP_W // 2
    path = []
    x = cx
    for y in range(top, foot + 1):
        # The runnel wanders a pixel as it follows the rock.
        if hashf(seed, y // 4) < 0.25 and y % 4 == 0:
            x = max(2, min(SEEP_W - 3, x + (1 if hashf(seed, y, 7) < 0.5 else -1)))
        path.append((x, y))
    for (x, y) in path:
        t = (y - top) / max(1, length)
        # The wet stain: wider and darker towards the foot.
        width = 1 if t < 0.3 else 2
        for dx in range(-width, width + 1):
            xx = x + dx
            if not 0 <= xx < SEEP_W:
                continue
            edge = abs(dx) == width
            if edge:
                # Fresh green slime blooms along the runnel's edges, ragged.
                if hashf(seed, xx, y, 3) < 0.55 + 0.3 * t:
                    g[y][xx] = code('moss', 5 if hashf(seed, xx, y) < 0.5 else 4)
            else:
                g[y][xx] = code('sea', 2) if dx == 0 else code('moss', 3)
        # The trickle: a glistening line down the middle.
        g[y][x] = code('sea', 5)
    # The bright head of the water running down the face, three steps a frame, and a second.
    for head in ((k * length) // 8, ((k + 4) * length) // 8):
        i = head % len(path)
        x, y = path[i]
        g[y][x] = code('sea', 9)
        if i > 0:
            g[path[i - 1][1]][path[i - 1][0]] = code('sea', 7)
    # The drop at the foot: it gathers (frames 0 to 4), falls (5, 6), and rings the wet floor (7).
    fx, fy = path[-1]
    if k <= 4:
        g[fy][fx] = code('sea', 8 if k >= 3 else 7)
        if k >= 3:
            g[fy + 1][fx] = code('sea', 6)
    elif k <= 6:
        g[min(SEEP_H - 1, fy + k - 4)][fx] = code('sea', 9)
    else:
        for dx in (-2, -1, 1, 2):
            g[SEEP_H - 1][fx + dx] = code('sea', 8 if abs(dx) == 1 else 6)
        g[SEEP_H - 2][fx] = code('sea', 9)
    # The floor under the foot stays wet: a small dark pool lip.
    for dx in (-1, 0, 1):
        if g[foot + 1][fx + dx] is None:
            g[foot + 1][fx + dx] = code('sea', 3)
    return g


def seeps():
    frames = []
    anims = {}
    for n, length in enumerate(LENGTHS):
        state = f'seep{n}'
        anims[state] = (8, 7, True)
        for k in range(8):
            frames.append(((state, k), seep_frame(length, k, 900 + n * 31)))
    about = [
        "Bog meltwater seeping down the deep passage's walls in spring (decision S14-143): a dark",
        'wet runnel with a fresh green bloom of slime along it, a glistening trickle whose bright',
        "head runs down the face, and a drop that gathers at the wall's foot, falls and rings on",
        'the wet floor. Four lengths, each an 8-frame loop; the pivot is the foot of the wall.',
    ]
    write('fx_seep', sheet_text('fx_seep', 'decal', (SEEP_W, SEEP_H), (SEEP_W // 2, SEEP_H - 1),
                                frames, anims, about))


if __name__ == '__main__':
    stamina_small()
    seeps()
