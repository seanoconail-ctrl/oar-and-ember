def write_rain_cloth():
    frames_src, size, pivot = read_sheet('prop_sail_leanto')
    key = next(k for k in frames_src if k[0] == 's0')
    cloth = frames_src[key].mask
    ys, xs = np.nonzero(cloth)
    # Bead sites on the cloth, inside its edge; each bead's phase and life differ.
    inner = cloth & np.roll(cloth, 2, 0) & np.roll(cloth, -2, 0) & np.roll(cloth, 2, 1) & np.roll(cloth, -2, 1)
    cand = [(int(x), int(y)) for y, x in zip(*np.nonzero(inner))]
    cand.sort(key=lambda p: hash01(p[0], p[1], 41))
    sites = []
    for p in cand:                                            # spread over the cloth, 4 px apart
        if all(abs(p[0] - q[0]) + abs(p[1] - q[1]) > 6 for q in sites):
            sites.append(p)
        if len(sites) == 24:
            break
    edge_y = ys.max()
    frames = []
    n = 12
    for k in range(n):
        s = Sprite(size[0], size[1], pivot[0], pivot[1])
        for j, (x, y) in enumerate(sites):
            ph = (k + j * 5) % n
            if ph < 6:
                # Growing: a pin of light, then a bead with its highlight.
                s.px(x, y, C('sky', 4 if ph < 3 else 5))
                if ph >= 3:
                    s.px(x + 1, y, C('sky', 3))
                    s.px(x, y + 1, C('sea', 6))
            elif ph < 10:
                # Running down the cloth, leaving a darker wet line.
                run = (ph - 5) * 3
                for d in range(run):
                    yy = y + d
                    if yy < size[1] and cloth[yy, x]:
                        s.px(x, yy, C('wool', 2))
                yy = y + run
                if yy < size[1] and cloth[yy, x]:
                    s.px(x, yy, C('sky', 5))
        # Drops falling from the cloth's lower edge.
        for j in range(4):
            x = int(xs.min() + (xs.max() - xs.min()) * (j + 0.5) / 4)
            col = cloth[:, x]
            if not col.any():
                continue
            bottom = int(np.nonzero(col)[0].max())
            yy = bottom + 1 + (k * 2 + j * 3) % 8
            if yy < size[1]:
                s.px(x, yy, C('sea', 8))
        frames.append((('beads', '-', k), raw_rows(s, size, pivot)))
    write('fx_rain_cloth', sheet_text(
        'fx_rain_cloth', 'decal', size, pivot, frames, {'beads': (n, 10, 'loop')},
        HEADER + ['Rain on the sail shelter (Book 7 section 06; decision DE-27): drops beading on the cloth, each',
                  'growing to a bead with its highlight and then running down, leaving a wet line; drops falling',
                  'from the cloth\'s lower edge. Drawn over prop_sail_leanto on its canvas.']))
    _ = edge_y


# ------------------------------------------------------------------------- the Hag's Stone
HAG_ACCENT = '&'


def write_hag():
    """The Hag's Stone's glow recoloured into its reserved accent (Book 7 section 09)."""
    path = f'{REPO}/assets/art/sheets/fx_hag.txt'
    text = open(path, encoding='utf8').read()
    pal = json.load(open(f'{REPO}/assets/palette/book07.json'))
    by_code = {e['code']: e for e in pal['entries']}
    out, cur = [], None
    for line in text.split('\n'):
        if line.startswith('frame '):
            cur = line.split()[1]
        elif line == 'end':
            cur = None
        elif cur == 'glow' and line and not line.startswith('#'):
            row = []
            for c in line:
                e = by_code.get(c)
                if e is not None and not e.get('reserved') and c != HAG_ACCENT:
                    h = e['hex']
                    lum = sum(int(h[i:i + 2], 16) for i in (1, 3, 5)) / 3
                    # The bright, cold steps of the glow become the accent; the dimmer stay.
                    row.append(HAG_ACCENT if lum > 150 else c)
                else:
                    row.append(c)
            line = ''.join(row)
        out.append(line)
    text = '\n'.join(out)
    if 'reserved:' not in text:
        text = text.replace('placeholder: false\n', f'placeholder: false\nreserved: {HAG_ACCENT}\n', 1)
    if 'storm25_art.py' not in text:
        text = text.replace('sheet: fx_hag\n', '# Recoloured by assets/art/authoring/storm25_art.py: the glow\'s bright steps are the\n'
                            '# Cailleach\'s cold light, a reserved accent kept to this (decision DF-21, item 11).\nsheet: fx_hag\n', 1)
    with open(path, 'w', encoding='utf8') as f:
        f.write(text)
    print(f'wrote {path}')


