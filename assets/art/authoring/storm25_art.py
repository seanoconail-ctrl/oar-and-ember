def foam(k):
    """A foam streak along a swell's crest, the white running along it (6 frames)."""
    s = Sprite(36, 6, 18, 5)
    for x in range(36):
        run = (x + k * 3) % 36
        thick = 1 + (hash01(run // 3, 7) > 0.55)
        y = 3 + int(round(math.sin(x * 0.28 + k * 0.6)))
        edge = min(x, 35 - x)
        if edge < 2 and hash01(x, k) > 0.5:
            continue
        for d in range(thick):
            step = 10 if (run // 4) % 3 == 0 and d == 0 else 9 if d == 0 else 8
            if edge < 5:
                step -= 1
            s.px(x, y - d, C('sea', step))
        if hash01(x, k, 3) > 0.82:
            s.px(x, y + 1, C('sea', 7))
    return s


def crest(k):
    """A swell's crest: a lifted band of lighter water under its foam, wind-torn (4 frames)."""
    s = Sprite(64, 8, 32, 7)
    for x in range(64):
        h = 2 + int(round(1.5 + 1.5 * math.sin(x * 0.11 + k * 0.5)))
        edge = min(x, 63 - x)
        h = min(h, 1 + edge // 3)
        for d in range(h):
            s.px(x, 6 - d, C('sea', 5 if d < h - 1 else 6))
        if (x + 2 * k) % 9 < 2 and h > 1:
            s.px(x, 6 - h, C('sea', 7))
    return s


def burst(k):
    """A wave breaking against the hull: a white sheet thrown up and tearing into spray (6)."""
    s = Sprite(48, 40, 24, 39)
    rise = [0.35, 0.7, 1.0, 0.95, 0.75, 0.5][k]
    torn = [0.0, 0.1, 0.25, 0.45, 0.65, 0.85][k]
    for x in range(48):
        dx = (x - 24) / 24
        top = int(39 - 36 * rise * (1 - dx * dx) ** 0.7)
        for y in range(top, 40):
            frac = (y - top) / max(1, 39 - top)
            if hash01(x, y, k) < torn * (1 - frac):
                continue
            step = 10 if frac < 0.2 else 9 if frac < 0.5 else 8
            s.px(x, y, C('sea', step))
    return s


def spray(k):
    s = Sprite(3, 3, 1, 2)
    if k < 2:
        s.px(1, 1, C('sea', 10))
        s.px(0, 1, C('sea', 9))
        s.px(1, 0, C('sea', 9))
    else:
        s.px(1, 1, C('sea', 9 if k == 2 else 8))
    return s


def green(k):
    """Green water over the gunwale: a glassy sheet, foaming at its lip, sheeting off (8)."""
    s = Sprite(56, 30, 28, 29)
    flow = [0.2, 0.5, 0.85, 1.0, 1.0, 0.8, 0.5, 0.2][k]
    for x in range(56):
        dx = abs(x - 28) / 28
        if dx > flow:
            continue
        lip = int(4 + 3 * math.sin(x * 0.3 + k))
        bottom = 29 - int(6 * (1 - flow))
        for y in range(lip, bottom):
            frac = (y - lip) / max(1, bottom - lip)
            col = C('sea', 6) if frac < 0.15 else C('sea', 5) if (x + y + k) % 7 else C('sea', 7)
            if frac > 0.85 and hash01(x, y, k) > 0.5:
                col = C('sea', 9)
            s.px(x, y, col)
        s.px(x, lip, C('sea', 10 if (x + k) % 3 else 9))
    return s


def scupper(k):
    """Foam sheeting off the deck through a scupper (4)."""
    s = Sprite(6, 12, 3, 11)
    for y in range(12):
        if (y + k * 3) % 5 == 4:
            continue
        s.px(2 + (y // 4) % 2, y, C('sea', 9 if y < 6 else 8))
    return s


def rain(k):
    """A raindrop's streak slanting 25 degrees downwind (4)."""
    s = Sprite(6, 12, 3, 11)
    n = 6 + (k % 2) * 2
    for d in range(n):
        y = 11 - d
        x = 3 + int(round(d * math.tan(math.radians(25)))) - 2
        if 0 <= x < 6:
            s.px(x, y, C('sky', 5 if d < 2 else 4 if d < 5 else 3))
    return s


def bolt(k):
    """A forked bolt far off over the sea (3): the sky's lightest steps, never the hit-flash white."""
    s = Sprite(40, 120, 20, 119)
    r = np.random.default_rng(11 + k)
    x = 20.0
    pts = []
    for y in range(120):
        x += r.uniform(-1.4, 1.4)
        pts.append((int(round(x)), y))
        s.px(int(round(x)), y, C('sky', 5))
        s.px(int(round(x)) + 1, y, C('sky', 4))
    for _ in range(2):
        y0 = int(r.uniform(30, 80))
        x = pts[y0][0]
        for y in range(y0, min(120, y0 + 30)):
            x += r.uniform(-1.8, 0.6) * (1 if k % 2 else -1)
            s.px(int(round(x)), y, C('sky', 4 if y - y0 < 12 else 3))
    return s


def lantern(k):
    s = Sprite(5, 8, 2, 7)
    for y in range(1, 7):
        for x in range(5):
            edge = x in (0, 4) or y in (1, 6)
            s.px(x, y, C('tar', 1) if edge else C('fire', 6 if k else 5))
    s.px(2, 0, C('stone', 3))
    return s


