def mist(layer, k):
    """A bank of mist in ordered dither: a soft, ragged cloud, thickest low over the swells, torn
    into wisps at its edges, from the smoke (low) or sky (high) ramp's pale steps."""
    w, h = (160, 44) if layer == 'low' else (200, 36)
    s = Sprite(w, h, w // 2, h - 1)
    ramp = 'smoke' if layer == 'low' else 'sky'
    seed = (31 if layer == 'low' else 57) + k * 11
    n = fbm(h, w, 14, seed, octaves=3)
    wisp = fbm(h, w, 5, seed + 5, octaves=2)
    for y in range(h):
        for x in range(w):
            fx = (x - w / 2) / (w / 2)
            fy = (y - h * 0.62) / (h * 0.5)
            fall = 1 - (fx * fx + fy * fy)
            if fall <= 0:
                continue
            dens = (fall ** 0.8) * (0.25 + 1.1 * n[y, x]) * (0.6 if layer == 'low' else 0.42)
            dens *= 0.55 + 0.6 * wisp[y, x]
            if dens > BAYER[y % 4, x % 4] + 0.04:
                step = (5 if n[y, x] > 0.55 else 4) if layer == 'low' else (4 if n[y, x] > 0.5 else 3)
                s.px(x, y, C(ramp, step))
    return s


