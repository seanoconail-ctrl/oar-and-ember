HEADER = ['Generated by assets/art/authoring/storm25_art.py (design addendum 2.5). Do not edit by hand.']
STRIP = 16
ROLLS = (('port', 0.9), ('level', 1.0), ('starboard', 1.1))
BAYER = np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]) / 16.0


def bbox(sprites):
    m = np.zeros_like(sprites[0].mask)
    for s in sprites:
        m |= s.mask
    ys, xs = np.nonzero(m)
    return xs.min(), ys.min(), xs.max(), ys.max()


def rolled(src, waterline, f):
    """The sprite heeled: rows above the waterline scaled by f about it (nearest row)."""
    out = Sprite(src.w, src.h, src.ax, src.ay)
    for y in range(src.h):
        d = waterline - y
        sy = waterline - int(round(d / f)) if d > 0 else y
        if not 0 <= sy < src.h:
            continue
        for x in range(src.w):
            if src.mask[sy, x]:
                out.px(x, y, src.rgb[sy, x])
    return out


def write_hull():
    frames_src, size, pivot = read_sheet('ship_t1_launch')
    afloat = [frames_src[('afloat', '-', str(k))] for k in range(4)]
    x0, y0, x1, y1 = bbox(afloat)
    waterline = y1
    strips = (x1 - x0 + STRIP) // STRIP
    head = int(math.ceil((waterline - y0) * (max(f for _, f in ROLLS) - 1))) + 2
    top = y0 - head
    h = waterline - top + 2
    frames = []
    for name, f in ROLLS:
        for i in range(strips):
            for k in range(4):
                spr = rolled(afloat[k], waterline, f)
                s = Sprite(STRIP, h, 0, waterline - top)
                for y in range(h):
                    for x in range(STRIP):
                        X, Y = x0 + i * STRIP + x, top + y
                        if 0 <= X < spr.w and 0 <= Y < spr.h and spr.mask[Y, X]:
                            s.px(x, y, spr.rgb[Y, X])
                frames.append(((name, '-', i * 4 + k), raw_rows(s, (STRIP, h), (0, waterline - top))))
    anims = {name: (strips * 4, 9) for name, _ in ROLLS}
    write('ship_t1_storm', sheet_text(
        'ship_t1_storm', 'building', (STRIP, h), (0, waterline - top), frames, anims,
        HEADER + ['Thorkel\'s boat in the storm (Book 7 section 05; decision DF-17): the T1 hull afloat cut into',
                  f'{strips} strips of {STRIP} px (frame index = strip x 4 + the water\'s lapping frame), so the',
                  'game pitches it a strip at a time, in three roll frames: port (heeled towards the viewer, the',
                  'side foreshortened), level, and starboard (heeled away, more of the side showing).',
                  f'Strip 0\'s left edge is column {x0} of ship_t1_launch; the pivot row is its waterline, row {waterline}.']))
    return {'x0': int(x0), 'waterline': int(waterline), 'strips': int(strips), 'pivotX': pivot[0],
            'pivotY': pivot[1]}


def write_mast():
    frames_src, size, pivot = read_sheet('ship_t1_launch')
    masts = [frames_src[('mast', '-', str(k))] for k in range(4)]
    x0, y0, x1, y1 = bbox(masts)
    pad = 4
    left = x0 - pad
    w = x1 - x0 + 1 + 2 * pad
    h = pivot[1] + 1 - (y0 - 1)
    top = y0 - 1
    frames = []
    for j, (name, _) in enumerate(ROLLS):
        lean = (j - 1) * 2                                    # the head 2 px to port or starboard
        for k in range(4):
            src = masts[k]
            s = Sprite(w, h, pivot[0] - left, pivot[1] - top)
            foot = y1
            for y in range(y0, y1 + 1):
                dx = int(round(lean * (foot - y) / max(1, foot - y0)))
                for x in range(x0, x1 + 1):
                    if src.mask[y, x]:
                        s.px(x - left + dx, y - top, src.rgb[y, x])
            frames.append(((name, '-', k), raw_rows(s, (w, h), (pivot[0] - left, pivot[1] - top))))
    write('ship_t1_storm_mast', sheet_text(
        'ship_t1_storm_mast', 'building', (w, h), (pivot[0] - left, pivot[1] - top), frames,
        {name: (4, 7, 'loop') for name, _ in ROLLS},
        HEADER + ['The mast and yard of Thorkel\'s boat in the storm (decision DF-17), with the hull\'s three rolls:',
                  'its head leaning 2 px to port, upright, or 2 px to starboard; the pennant flogging.']))


