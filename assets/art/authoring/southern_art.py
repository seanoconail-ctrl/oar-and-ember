def frame_rows(spr, size, pivot, outline=True):
    s = spr.padded(1)
    if outline:
        s.outline()
    rgb, mask = place(s, size, pivot)
    return codes(rgb, mask)


# ---------------------------------------------------------------------- the Hag's Seat
def hagstone(wet=None):
    """A standing stone 52 px tall, broad at the foot, with a seat worn into its east side about a
    third of the way up. `wet` is the phase (0..1) of the water running down it, or None (dry)."""
    w, h = 30, 56
    s = Sprite(w, h, w // 2, h - 1)
    nz = value_noise(h, w, 5, 17)
    for y in range(h):
        u = (h - 1 - y) / (h - 1)            # 0 at the foot, 1 at the crown
        half = 11.5 - 4.5 * u ** 1.4 + 1.2 * math.sin(u * 7.3)
        cx = 15 + 1.5 * u
        x0, x1 = cx - half, cx + half
        # The seat: a step worn into the east side between a third and a half of the height.
        seat = 0.30 < u < 0.47
        if seat:
            x1 -= 5.5
        if u > 0.93:
            x0 += (u - 0.93) * 60
            x1 -= (u - 0.93) * 50
        for x in range(w):
            if not (x0 <= x + 0.5 <= x1):
                continue
            t = (x + 0.5 - x0) / max(1, x1 - x0)          # 0 west .. 1 east
            light = 1.0 - t * 1.25 + 0.25 * u
            step = 3 + round(light * 2.6 + (nz[y, x] - 0.5) * 1.4)
            if seat and t > 0.82:
                step -= 1
            col = C('stone', step - (2 if wet is not None else 0))
            # Lichen on the lit west face and the crown; grey-green crusts and a yellow one.
            lich = hash01(x // 2, y // 2, 5)
            if wet is None and t < 0.5 and lich > 0.86:
                col = C('moss', 5) if lich < 0.95 else C('trefoil', 2)
            if u > 0.85 and lich > 0.8:
                col = C('moss', 4 if wet is not None else 6)
            # Cracks running with the grain.
            if (x * 3 + y * 1) % 17 == 0 and 0.2 < t < 0.8 and nz[y, x] > 0.55:
                col = C('stone', 1)
            s.px(x, y, col)
        # The seat itself: the notch's worn floor, a flat ledge catching the light.
        if 0.27 < u < 0.30:
            for x in range(int(x1 - 6), int(x1)):
                if s.mask[y, x]:
                    s.px(x, y, C('stone', 7 - (2 if wet is not None else 0)))
    if wet is not None:
        # Rivulets: thin streams of light running down the face, each on its own phase.
        for k, (x, speed) in enumerate(((9, 1.0), (13, 1.3), (17, 0.9), (20, 1.15), (11, 0.8))):
            for y in range(4, h - 2):
                if not s.mask[y, x]:
                    continue
                ph = (y / h * 3.0 - wet * speed * 3 + k * 0.37) % 1.0
                if ph < 0.18:
                    s.rgb[y, x] = C('sea', 9 if ph < 0.06 else 8)
                elif ph < 0.4:
                    s.rgb[y, x] = C('stone', 6)
        # A dark wet stain spreading on the turf at its foot.
        for x in range(4, w - 4):
            if hash01(x, 3) > 0.3:
                s.px(x, h - 1, C('sand_wet', 1))
    return s


