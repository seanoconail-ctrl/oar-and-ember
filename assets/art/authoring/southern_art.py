def update_cairn_plan(cairn_props, fold_props, plants):
    with open(CAIRN_PLAN) as f:
        plan = json.load(f)
    keep = [p for p in plan['props'] if p['sheet'] not in ('bld_cairn', 'bld_fold', 'prop_cairn')]
    plan['props'] = cairn_props + fold_props + keep
    plan['plantsExtra'] = plants
    plan.pop('raised', None)
    with open(CAIRN_PLAN, 'w') as f:
        json.dump(plan, f, indent=2)
        f.write('\n')
    print(f'wrote {CAIRN_PLAN} ({len(cairn_props)} mound bands, {len(fold_props)} wall pieces, {len(plants)} tufts)')


