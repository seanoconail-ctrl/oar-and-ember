def watch(k):
    """The watch passing: the sun climbing over the sea's rim, a quarter of its arc a frame."""
    s = icon()
    for x in range(1, 15):
        s.px(x, 12, C('sea', 8.6))
        s.px(x, 13, C('sea', 6.4))
    a = math.radians(-70 + k * 46)
    cx, cy = 7.5 + math.sin(a) * 5.5, 11 - math.cos(a) * 6.5
    for y in range(16):
        for x in range(16):
            if (x - cx) ** 2 + (y - cy) ** 2 <= 4.2 and y < 12:
                s.px(x, y, C('fire', 6))
    for i in range(5):
        aa = math.radians(-70 + i * 35)
        s.px(int(round(7.5 + math.sin(aa) * 7)), int(round(11 - math.cos(aa) * 8)), C('wool', 4.4))
    s.outline(C('ink', 1))
    return s


def place(kind, k, faint=False):
    """A place's pictogram, inked on the chart; rumoured places drawn faint and broken."""
    s = icon()
    wall = C('stone', 5.6) if not faint else C('sand', 2.6)
    roof = C('tar', 4.4) if not faint else C('sand', 2.0)
    thatch = C('marram', 3.6) if not faint else C('sand', 3.0)
    if kind == 'hall':
        for y in range(9, 14):
            for x in range(3, 13):
                s.px(x, y, wall)
        for i in range(6):
            for x in range(3 + i // 2, 13 - i // 2):
                s.px(x, 8 - i // 1 + 0, thatch if i < 5 else roof)
        s.px(8, 12, roof)
        s.px(8, 13, roof)
        smoke = [(10, 3), (11, 2), (10, 1)] if k == 0 else [(10, 3), (9, 2), (10, 1)]
        for x, y in smoke:
            s.px(x, y, C('smoke', 4.6))
    elif kind == 'landing':
        for y in range(8, 12):
            for x in range(2, 9):
                s.px(x, y, wall)
        for x in range(2, 9):
            s.px(x, 7, thatch)
        for x in range(9, 15):
            s.px(x, 13 + (x == 9 or x == 14) * -1, roof)
            s.px(x, 14, C('sea', 7 if not faint else 6))
        s.px(12, 12 - k, C('driftwood', 4))
    elif kind == 'abbey':
        line(s, 7.5, 2, 7.5, 13, wall)
        line(s, 4, 6, 11, 6, wall)
        for y in range(4, 9):
            for x in range(5, 11):
                if 5 <= (x - 7.5) ** 2 + (y - 6) ** 2 <= 7:
                    s.px(x, y, wall)
        for x in range(4, 12):
            s.px(x, 14, roof)
    elif kind == 'fort':
        for y in range(3, 15):
            for x in range(1, 15):
                d = (x - 7.5) ** 2 / 42 + (y - 9) ** 2 / 22
                if 0.62 <= d <= 1:
                    s.px(x, y, C('earth', 4) if not faint else C('sand', 2.4))
        for y in range(8, 11):
            for x in range(6, 10):
                s.px(x, y, thatch)
        s.px(9, 6 - k, C('madder', 4) if not faint else C('sand', 3))
        s.px(9, 7, C('driftwood', 4))
    elif kind == 'harbour':
        for x in range(1, 15):
            s.px(x, 13, C('sea', 7 if not faint else 6))
        for m, h in ((4, 9), (8, 11), (12, 8)):
            line(s, m, 12, m, 12 - h + 2, C('driftwood', 4) if not faint else C('sand', 2.6))
            for x in range(m - 2, m + 3):
                s.px(x, 12, roof)
        s.px(8, 3 + k, C('wool', 6) if not faint else C('sand', 3))
    elif kind == 'camp':
        for cx in (4, 11):
            for i in range(5):
                for x in range(cx - i, cx + i + 1):
                    s.px(x, 9 + i, C('wool', 3.4 - (x < cx) * 0.6) if not faint else C('sand', 2.4))
        for x, y in ([(7, 6), (8, 4), (7, 2)] if k == 0 else [(8, 6), (7, 4), (8, 2)]):
            s.px(x, y, C('smoke', 4.4))
    elif kind == 'stone':
        for y in range(3, 14):
            for x in range(6, 10):
                if not (y < 4 and x in (6, 9)):
                    s.px(x, y, wall if (x + y) % 5 else C('stone', 4.2))
        for x in range(4, 12):
            s.px(x, 14, C('grass', 4) if not faint else C('sand', 2.4))
        s.px(8, 7 + k * 2, C('sea', 9))
    elif kind == 'seat':
        for y in range(9, 14):
            for x in range(2, 14):
                s.px(x, y, C('stone', 3.6) if not faint else C('sand', 2.4))
        for i in range(5):
            for x in range(2 + i, 14 - i):
                s.px(x, 8 - i, roof)
        s.px(2, 4 - k, roof)
        s.px(1, 3 - k, roof)
        s.px(13, 4 - k, roof)
        s.px(14, 3 - k, roof)
    s.outline(C('ink', 1))
    if faint:
        # Rumoured: the same pictogram in faded sepia, its fill hatched, as heard of, not seen.
        ink = C('ink', 1)
        for y, x in zip(*np.nonzero(s.mask)):
            if np.abs(s.rgb[y, x] - ink).max() < 1:
                s.rgb[y, x] = C('sand', 1.2)
            elif (x + y) % 2:
                s.mask[y, x] = False
            else:
                lum = s.rgb[y, x].mean() / 255
                s.rgb[y, x] = C('sand', 2.6 + lum * 2.4)
    return s


def whirl(k):
    """The Cailleach's Cauldron: a whirl turning, foam streaming round it."""
    s = icon()
    for i in range(70):
        f = i / 70
        a = f * math.tau * 2.2 + k * math.tau / 6
        r = 1 + f * 6.2
        x = 7.5 + math.cos(a) * r
        y = 8 + math.sin(a) * r * 0.75
        s.px(int(round(x)), int(round(y)), C('sea', 10 - f * 3.2))
    s.px(7, 8, C('sea', 1))
    s.px(8, 8, C('sea', 1))
    s.outline(C('ink', 1))
    return s


def broken(k):
    """Blue Men's Sound: broken water, crests standing up and falling in the strait."""
    s = icon()
    for j, (cx, cy) in enumerate(((4, 6), (11, 5), (7, 11), (13, 12), (2, 12))):
        h = (k + j) % 4
        for i in range(-2, 3):
            s.px(cx + i, cy + abs(i) - h // 2, C('sea', 9.6 - abs(i) * 0.6))
        if h == 3:
            s.px(cx, cy - 2, C('sea', 10))
    s.outline(C('ink', 1))
    return s


def dab(kind, k):
    """A route's brush dab, in the ink of its kind: known routes inked dark, rumoured ones faint
    sepia, the plotted course in madder."""
    s = icon()
    col = {'known': C('ink', 1), 'rumour': C('sand', 3.6), 'course': C('madder', 3.2)}[kind]
    hi = {'known': C('ink', 0), 'rumour': C('sand', 4.6), 'course': C('madder', 4.6)}[kind]
    shapes = [[(7, 7), (8, 7), (7, 8), (8, 8), (9, 8)], [(6, 7), (7, 7), (8, 7), (7, 8), (8, 8)],
              [(7, 7), (8, 7), (7, 8), (8, 8), (8, 9)]]
    if kind == 'rumour':
        shapes = [[(7, 7), (8, 8)], [(7, 7), (8, 7)], [(8, 7), (7, 8)]]
    if kind == 'course':
        shapes = [[(7, 7), (8, 7), (7, 8), (8, 8), (9, 8)], [(6, 7), (7, 7), (8, 7), (7, 8), (8, 8)],
                  [(7, 7), (8, 7), (7, 8), (8, 8), (8, 9)]]
    for i, (x, y) in enumerate(shapes[k]):
        s.px(x, y, hi if i == 0 else col)
    return s


def chevron(towards):
    s = icon()
    a = math.radians(POINT_DEG[towards])
    dx, dy = math.sin(a), -math.cos(a)
    px_, py_ = -dy, dx
    for t in range(3):
        for side in (-1, 1):
            x = 7.5 + dx * (1 - t) + px_ * side * t
            y = 7.5 + dy * (1 - t) + py_ * side * t
            s.px(int(round(x)), int(round(y)), C('madder', 4.4))
    s.outline(C('ink', 1))
    return s


