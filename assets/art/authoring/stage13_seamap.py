def write_icons():
    frames, anims = [], {}

    def add(name, sprites, ticks=12):
        anims[name] = (len(sprites), ticks, 'loop')
        for k, spr in enumerate(sprites):
            frames.append(((name, '-', k), raw(spr, (IW, IW), (8, 15))))

    add('wind_calm', [calm(k) for k in range(2)], 20)
    for p in POINT_DEG:
        for st in range(1, 5):
            add(f'wind_{p}_{st}', [wind_arrow(p, st, k) for k in range(2)], 10)
    for ph in ('flood', 'ebb', 'slack'):
        add(f'tide_{ph}', [tide(ph, k) for k in range(4)], 12)
    for v in ('clear', 'haze', 'fog', 'night'):
        add(f'vis_{v}', [visibility(v, k) for k in range(4)], 14)
    add('stores', [stores()], 60)
    add('watch', [watch(k) for k in range(4)], 15)
    for kind in ('hall', 'landing', 'abbey', 'fort', 'harbour', 'camp', 'stone', 'seat'):
        add(f'place_{kind}', [place(kind, k) for k in range(2)], 24)
        add(f'place_{kind}_faint', [place(kind, k, True) for k in range(2)], 24)
    add('haz_cauldron', [whirl(k) for k in range(6)], 8)
    add('haz_bluemen', [broken(k) for k in range(4)], 10)
    for kind in ('known', 'rumour', 'course'):
        add(f'dab_{kind}', [dab(kind, k) for k in range(3)], 60)
    for p in POINT_DEG:
        add(f'chev_{p}', [chevron(p)], 60)
    add('pin', [pin(k) for k in range(2)], 14)
    add('anchor', [anchor()], 60)
    write('ui_seaicons', sheet_text(
        'ui_seaicons', 'decal', (IW, IW), (8, 15), frames, anims,
        HEADER + ["The sea map's drawn marks (Book 7 section 10: shape-coded icons, never emoji): the wind",
                  'arrow by point and strength and the calm; the tide (flood, ebb, slack); visibility; the',
                  "stores; the watch; the places' pictograms, known and rumoured; the Cauldron and Blue",
                  "Men's Sound; the painted route's brush dabs and chevrons; the course's pin; the anchor."]))


def bolt(k):
    w, h = 24, 64
    s = Sprite(w, h, 12, 63)
    x = 12.0
    pts = []
    for y in range(0, 60):
        x += (hash01(y // 5, 41, 0) - 0.5) * 1.6
        pts.append((x, y))
        if y in (22, 38) and k == 0:
            bx = x
            for yy in range(y, y + 12):
                bx += 0.7 if y == 22 else -0.6
                s.px(int(round(bx)), yy, C('sea', 9.6))
    for x_, y in pts:
        s.px(int(round(x_)), y, C('clover_white', 3) if k == 0 else C('sea', 10))
        if k == 0:
            s.px(int(round(x_)) + 1, y, C('sea', 9))
    return s


