# ======================================================================= the chart's light
RAMPS = ['ink', 'sand', 'stone', 'bracken', 'moss', 'grass', 'sea', 'tar', 'driftwood']
R = {name: i for i, name in enumerate(RAMPS)}
#: What a pixel of the chart is: sea, the coast's ink, land, or the frame.
SEA, INK, LAND, FRAME = 0, 1, 2, 3


def chart_steps():
    """The chart of stage12_art.chart('chart'), as a ramp and a step per pixel and what it is
    (sea, ink, land or frame), so its light can be changed without moving a pixel of the coast.
    The same arithmetic as stage12_art.chart, pixel for pixel."""
    land = S12.coast_fields()
    ys, xs = np.mgrid[0:MH, 0:MW].astype(np.float32)
    is_land = land > 0
    to_land = S12.chamfer(is_land)
    to_sea = S12.chamfer(~is_land)
    hn = value_noise(MH, MW, 22, 1301) * 0.7 + value_noise(MH, MW, 7, 1303) * 0.3
    hn2 = value_noise(MH, MW, 30, 1304)
    sea_n = value_noise(MH, MW, 6, 1302)
    ramp = np.zeros((MH, MW), np.int32)
    step = np.zeros((MH, MW), np.float32)
    kind = np.zeros((MH, MW), np.int32)
    hatch = np.zeros((MH, MW), bool)
    surf = np.zeros((MH, MW), bool)
    dz = np.sqrt((xs - SK['x']) ** 2 + ((ys - SK['y']) * 1.3) ** 2)
    for y in range(MH):
        for x in range(MW):
            b = BAYER[y % 4, x % 4]
            if is_land[y, x]:
                inland = to_sea[y, x]
                h = hn[y, x]
                heath = hn2[y, x]
                kind[y, x] = LAND
                if inland < 1.5:
                    ramp[y, x], step[y, x], kind[y, x] = R['ink'], 1, INK
                elif inland < 3:
                    ramp[y, x], step[y, x] = R['sand'], 3.6 + (b > 0.5) * 0.6
                elif h > 0.78 and inland > 18:
                    ramp[y, x], step[y, x] = R['stone'], 3.6 + (h - 0.78) * 12 + (b - 0.5) * 0.8
                elif heath + (b - 0.5) * 0.06 > 0.64 and inland > 8:
                    ramp[y, x], step[y, x] = R['bracken'], 0.6 + (heath - 0.62) * 4 + (b - 0.5) * 1.1
                else:
                    g = 3.0 + h * 2.2 + (b - 0.5) * 0.9
                    ramp[y, x], step[y, x] = R['moss' if h < 0.55 else 'grass'], g
                if inland > 6 and h > 0.6 and (x + 2 * y) % 9 == 0 and hn[y, min(MW - 1, x + 2)] < h:
                    hatch[y, x] = True
                continue
            d = to_land[y, x]
            deep = min(1.0, d / 40)
            s = 6.4 - deep * 3.6 + (sea_n[y, x] - 0.5) * 0.8 + (b - 0.5) * 0.9
            if 22 < dz[y, x] < 70:
                s -= 0.7 * math.sin(math.pi * (dz[y, x] - 22) / 48)
            if d < 2.5:
                s = 9.0 if (x + y) % 3 else 8.0
                surf[y, x] = True
            elif d < 5:
                s = 7.2 + (b > 0.5)
            ramp[y, x], step[y, x], kind[y, x] = R['sea'], s, SEA
    for y in range(MH):
        for x in range(MW):
            e = min(x, y, MW - 1 - x, MH - 1 - y)
            if e < 5:
                kind[y, x] = FRAME
                hatch[y, x] = False
                if e in (0, 4):
                    ramp[y, x], step[y, x] = R['tar'], 1.0
                else:
                    ramp[y, x], step[y, x] = R['driftwood'], 4.4 - e * 0.5 + ((x + y) // 6 % 2) * 0.6
    return ramp, step, kind, hatch, surf


def paint(ramp, step, hatch):
    """RGB from ramps and steps, with the hills' hatching (as stage12_art.chart)."""
    out = np.zeros((MH, MW, 3), np.float32)
    for name, i in R.items():
        sel = ramp == i
        if not sel.any():
            continue
        out[sel] = np.array([C(name, s) for s in step[sel]], np.float32)
    out[hatch] *= 0.82
    return out


def light(ramp, step, kind, hatch, surf, variant):
    """The chart in one of the voyage's lights (steps moved, never pixels)."""
    s = step.copy()
    land = kind == LAND
    sea = kind == SEA
    frame = kind == FRAME
    open_sea = sea & ~surf
    bayer = np.tile(BAYER, (MH // 4 + 1, MW // 4 + 1))[:MH, :MW]
    if variant == 'land_lit':
        # A gust's sheen over the heath and grass: a step lighter, warmer on the hills.
        s[land] += 1.0 + (bayer[land] - 0.5) * 0.4
    elif variant in ('storm', 'storm_lit'):
        s[land] -= 1.6
        s[sea] -= 1.9
        s[frame] -= 0.8
        if variant == 'storm_lit':
            s[open_sea] += 1.6
    elif variant == 'flash':
        s[land] += 1.4
        s[sea] += 2.2
        s[frame] += 0.6
    elif variant in ('night', 'night_lit'):
        s[land] -= 2.6
        s[sea] -= 2.4
        s[frame] -= 1.4
        if variant == 'night_lit':
            s[open_sea] += 2.0
    s = np.maximum(s, 0)
    return paint(ramp, s, hatch if variant != 'flash' else np.zeros_like(hatch))


def fog_thin():
    """The upper layer of drifting fog: thinner and paler than ui_seamap's `fog`, with tears."""
    n = value_noise(MH, MW, 26, 1411) * 0.55 + value_noise(MH, MW, 9, 1412) * 0.45
    bayer = np.tile(BAYER, (MH // 4 + 1, MW // 4 + 1))[:MH, :MW]
    out = np.zeros((MH, MW, 3), np.float32)
    steps = 3.0 + n * 2.4 + (bayer - 0.5) * 0.9
    for y in range(MH):
        for x in range(MW):
            out[y, x] = C('smoke', steps[y, x])
    return out


def write_chart():
    ramp, step, kind, hatch, surf = chart_steps()
    base = paint(ramp, step, hatch)
    # The same coast as ui_seamap's chart, to the pixel.
    check = S12.chart('chart')
    assert np.abs(base - check).max() < 1e-3, 'the chart moved'
    frames = []
    names = ['land_lit', 'storm', 'storm_lit', 'flash', 'night', 'night_lit']
    for v in names:
        frames.append(((v, '-', 0), S12.codes_big(light(ramp, step, kind, hatch, surf, v))))
    frames.append((('fog_thin', '-', 0), S12.codes_big(fog_thin())))
    write('ui_seavoyage', sheet_text(
        'ui_seavoyage', 'decal', (MW, MH), (0, 0), frames,
        {n: (1, 1) for n in names + ['fog_thin']},
        HEADER + ["The chart of ui_seamap in the voyage's light (Book 7 sections 10 and 14), 640 x 360, on",
                  'the same coast to the pixel: a gust sheen over the land, the storm and its sheen, lit by',
                  'lightning, by night and its moonlit sheen, and the thin upper layer of drifting fog.']))


# ======================================================================= the boat token
TW, TH = 24, 16
TP = (12, 12)                      # the hull's middle at the waterline
#: Each heading's angle (screen: x right, y down; north up), and the chart's three-quarter squash.
ANGLE = {h: i * math.pi / 4 for i, h in enumerate(HEADINGS)}
SQUASH = 0.62
BOB = [0, 0, 1, 1]


def axes(heading):
    a = ANGLE[heading]
    ux, uy = math.sin(a), -math.cos(a) * SQUASH          # bow-ward
    vx, vy = math.cos(a), math.sin(a) * SQUASH           # to starboard
    return ux, uy, vx, vy


def hull(s, heading, k, oars=False):
    """The double-ended hull seen from above and a little astern: tarred strakes, a lighter
    sheer strake, the bow and stern posts, the benches between."""
    ux, uy, vx, vy = axes(heading)
    cx, cy = TP[0], TP[1] - 1 + BOB[k]
    half = 7.5
    for t in np.linspace(-1, 1, 61):
        w = 2.4 * (1 - t * t) ** 0.65
        for q in np.linspace(-w, w, max(3, int(w * 4))):
            x = cx + ux * half * t + vx * q
            y = cy + uy * half * t + vy * q
            edge = abs(q) > w - 0.7
            col = C('tar', 4.6 if edge else 2.6 + (q > 0) * 0.8)
            s.px(int(round(x)), int(round(y)), col)
    # The stem rises high and pale at the bow; the stern post is lower, with the steering oar
    # on the starboard quarter, so the heading reads at a glance (and north from south).
    bx, by = cx + ux * half * 1.1, cy + uy * half * 1.1
    s.px(int(round(bx)), int(round(by)), C('driftwood', 5.5))
    s.px(int(round(bx)), int(round(by)) - 1, C('driftwood', 6))
    s.px(int(round(bx + ux * 0.8)), int(round(by)) - 2, C('driftwood', 6.5))
    s.px(int(round(cx - ux * half * 1.05)), int(round(cy - uy * half * 1.05)) - 1, C('tar', 5))
    for i in range(4):
        x = cx - ux * half * (0.72 + 0.12 * i) + vx * (2.4 + 0.7 * i)
        y = cy - uy * half * (0.72 + 0.12 * i) + vy * (2.4 + 0.7 * i)
        s.px(int(round(x)), int(round(y)), C('driftwood', 3.2 if i < 3 else 2.4))
    # Two benches across.
    for t in (-0.35, 0.3):
        for q in (-1, 0, 1):
            s.px(int(round(cx + ux * half * t + vx * q)), int(round(cy + uy * half * t + vy * q)),
                 C('driftwood', 5))
    if oars:
        # Three oars a side sweeping: forward on frames 0-1, back on 2-3.
        sweep = [0.35, 0.15, -0.25, -0.05][k]
        for t in (-0.45, 0.0, 0.45):
            for side in (-1, 1):
                for r in (2.6, 3.4, 4.2):
                    x = cx + ux * half * (t + sweep * (r - 2.2) / 2) + vx * side * r
                    y = cy + uy * half * (t + sweep * (r - 2.2) / 2) + vy * side * r
                    s.px(int(round(x)), int(round(y)), C('driftwood', 5.5 if r > 4 else 4.5))


def mast_top(heading, k):
    cy = TP[1] - 1 + BOB[k]
    return TP[0], cy - 9


def rig(s, heading, k, state, pattern=None, dye=None):
    """The mast and yard, and the sail furled, set or reefed. The sail is drawn face-on, as the
    launch draws it (decision S12-15), skewed a little on the quarters to read the turn."""
    mx, top = mast_top(heading, k)
    cy = TP[1] - 1 + BOB[k]
    for y in range(top, cy):
        s.px(mx, y, C('driftwood', 4))
    ux = axes(heading)[0]
    skew = 0 if abs(ux) < 0.2 or abs(ux) > 0.9 else (1 if ux > 0 else -1)
    # The yard across the mast.
    yard = 5
    for dx in range(-yard, yard + 1):
        s.px(mx + dx, top + 1, C('driftwood', 5 if abs(dx) < yard else 3.5))
    if state in ('furled', 'row'):
        # The sail rolled along the yard: a bundle of cloth under it, lashed.
        for dx in range(-yard + 1, yard):
            s.px(mx + dx, top + 2, C('wool', 3.4 + ((dx + k) % 3 == 0) * 0.8))
        for dx in (-3, 0, 3):
            s.px(mx + dx, top + 2, C('tar', 4))
        return
    drop = 6 if state == 'set' else 3
    breathe = [0, 1, 1, 0][k]
    for j in range(drop):
        v = j / max(1, drop - 1)
        belly = int(round(math.sin(math.pi * v) * (0.8 + 0.4 * breathe)))
        lean = int(round(skew * v * 1.2))
        for dx in range(-yard + 1, yard):
            u = (dx + yard - 1) / (2 * yard - 2)
            ramp, base = (S12.DYE[dye] if dye is not None and S12.dyed(pattern, u, v * 0.92)
                          else S12.UNDYED)
            shade = 0.5 if dx < 0 else -0.1
            if abs(dx) >= yard - 1 - belly * 0:
                shade -= 0.4
            s.px(mx + dx + lean, top + 2 + j + (belly if abs(dx) < 2 else 0) * 0, C(ramp, base + shade))
    if state == 'reefed':
        # The reef band bunched along the foot, its points hanging.
        y = top + 2 + drop
        for dx in range(-yard + 1, yard):
            s.px(mx + dx + skew, y, C('wool', 2.6 + (dx % 2) * 0.6))
        for dx in (-3, -1, 1, 3):
            s.px(mx + dx + skew, y + 1, C('wool', 2.2))


def token(heading, state, k, pattern=None, dye=None):
    s = Sprite(TW, TH, TP[0], TP[1])
    hull(s, heading, k, oars=state == 'row')
    # A stern-facing boat shows the rig behind the hull; the rig is drawn over it otherwise.
    rig(s, heading, k, 'furled' if state == 'row' else state, pattern, dye)
    s.outline()
    return s


def write_token():
    frames, anims = [], {}
    states = [('furled', None, None, 'furled'), ('row', None, None, 'row')]
    for suffix, pattern, dye in S12.marks():
        states.append((f'set_{suffix}', pattern, dye, 'set'))
        states.append((f'reefed_{suffix}', pattern, dye, 'reefed'))
    for name, pattern, dye, kind in states:
        anims[name] = (4, 15, 'loop')
        for h in HEADINGS:
            for k in range(4):
                frames.append(((name, h, k), raw(token(h, kind, k, pattern, dye), (TW, TH), TP)))
    write('token_t1', sheet_text(
        'token_t1', 'decal', (TW, TH), TP, frames, anims,
        HEADER + ["The household's coastal boat on the sea map (Book 7 section 05): a 24 x 16 token with",
                  'eight headings (the facings), riding the swell over 4 frames: lying to with its sail',
                  'furled, rowing with the oars sweeping, and for every sail mark the sail set and reefed,',
                  "in the household's colours. Its wake is fx_seawake."],
        facings=' '.join(HEADINGS)))


def wake(heading, k):
    """Foam peeling off both quarters in a V astern, the flecks drifting back and fading."""
    w = 32
    s = Sprite(w, w, 16, 16)
    ux, uy, vx, vy = axes(heading)
    for side in (-1, 1):
        for j in range(16):
            back = (j + k * 16 / 6) % 16
            fade = back / 16
            x = 16 - ux * (5 + back) + vx * side * (2 + back * 0.45)
            y = 15 - uy * (5 + back) + vy * side * (2 + back * 0.45)
            if hash01(j, side, k // 3) > 0.15 + fade * 0.7:
                s.px(int(round(x)), int(round(y)), C('sea', 10 - fade * 2.6))
    # The churn right under the stern.
    for d in range(3):
        x = 16 - ux * (6 + d)
        y = 15 - uy * (6 + d)
        if (d + k) % 3:
            s.px(int(round(x)), int(round(y)), C('sea', 9.4))
    return s


def write_wake():
    frames = []
    for h in HEADINGS:
        for k in range(6):
            frames.append((('wake', h, k), raw(wake(h, k), (32, 32), (16, 16))))
    write('fx_seawake', sheet_text(
        'fx_seawake', 'decal', (32, 32), (16, 16), frames, {'wake': (6, 8, 'loop')},
        HEADER + ["The token's wake on the sea map (Book 7 section 05), on the token's pivot, for each of",
                  'the eight headings: foam peeling off both quarters in a V and fading astern (6 frames).'],
        facings=' '.join(HEADINGS)))


# ======================================================================= the chart's marks
IW = 16


def line(s, x0, y0, x1, y1, col):
    n = int(max(abs(x1 - x0), abs(y1 - y0)) * 2) + 1
    for i in range(n + 1):
        f = i / n
        s.px(int(round(x0 + (x1 - x0) * f)), int(round(y0 + (y1 - y0) * f)), col)


def icon():
    return Sprite(IW, IW, 8, 15)


POINT_DEG = {p: i * 45 for i, p in enumerate(['n', 'ne', 'e', 'se', 's', 'sw', 'w', 'nw'])}


def wind_arrow(towards, strength, k):
    """The wind arrow: a shaft pointing downwind (where the wind blows to), a solid head, and
    one feathered barb at the tail for each step of strength; its streamer flutters."""
    s = icon()
    a = math.radians(POINT_DEG[towards])
    dx, dy = math.sin(a), -math.cos(a)
    px_, py_ = -dy, dx
    cx, cy = 7.5, 7.5
    hx, hy = cx + dx * 6, cy + dy * 6
    tx, ty = cx - dx * 6, cy - dy * 6
    ink = C('ink', 1)
    line(s, tx, ty, hx - dx * 2, hy - dy * 2, C('wool', 6))
    # The head: a broad filled barb, pale with a shaded flank.
    for t in np.linspace(0, 1, 9):
        bx = hx - dx * 4 * t
        by = hy - dy * 4 * t
        for q in np.linspace(-2.6 * t, 2.6 * t, 9):
            s.px(int(round(bx + px_ * q)), int(round(by + py_ * q)), C('wool', 6 if q <= 0.3 else 4.6))
    for i in range(strength):
        bx = tx + dx * (i * 1.6)
        by = ty + dy * (i * 1.6)
        flap = (k + i) % 2
        line(s, bx, by, bx + px_ * 3 - dx * (1 + flap), by + py_ * 3 - dy * (1 + flap),
             C('madder', 4.6) if strength >= 4 else C('wool', 5))
    s.outline(ink)
    return s


def calm(k):
    """No wind: the water lying flat, two long low ripples."""
    s = icon()
    for j, y in enumerate((6, 10)):
        for x in range(2, 14):
            if (x + k + j) % 7 != 0:
                s.px(x, y + (1 if (x + k) % 6 == 0 else 0), C('sea', 9))
    s.outline(C('ink', 1))
    return s


def tide(phase, k):
    """The tide: a wave with a chevron rising (flood), falling (ebb), or a flat line (slack)."""
    s = icon()
    for x in range(1, 15):
        y = 11 + round(math.sin((x + k * 2) / 14 * math.tau * 1.5) * 1.4)
        s.px(x, y, C('sea', 9.5))
        s.px(x, y + 1, C('sea', 7))
    if phase == 'flood':
        for i in range(4):
            s.px(7 - i, 3 + i, C('wool', 6))
            s.px(8 + i, 3 + i, C('wool', 6))
        line(s, 7.5, 3, 7.5, 8, C('wool', 6))
    elif phase == 'ebb':
        for i in range(4):
            s.px(7 - i, 8 - i, C('wool', 6))
            s.px(8 + i, 8 - i, C('wool', 6))
        line(s, 7.5, 3, 7.5, 8, C('wool', 6))
    else:
        for x in range(3, 13):
            s.px(x, 5, C('wool', 6))
            s.px(x, 7, C('wool', 5))
    s.outline(C('ink', 1))
    return s


def visibility(kind, k):
    s = icon()
    if kind in ('clear', 'haze'):
        for y in range(4, 11):
            for x in range(4, 11):
                if (x - 7) ** 2 + (y - 7) ** 2 <= 9:
                    s.px(x, y, C('fire', 6.4 if (x + y) % 3 else 5.6))
        for i in range(8):
            a = i * math.pi / 4 + (k % 2) * math.pi / 8
            r = 5 + (i + k) % 2
            s.px(int(round(7 + math.sin(a) * r)), int(round(7 - math.cos(a) * r)), C('fire', 6))
        if kind == 'haze':
            for y in (5, 8, 11):
                for x in range(1, 15):
                    if (x + y + k) % 4 < 2:
                        s.px(x, y, C('smoke', 4.4))
    elif kind == 'fog':
        for j, y in enumerate((4, 7, 10, 13)):
            off = (k + j * 2) % 4
            for x in range(1 + off, 14 - (j % 2) * 2):
                s.px(x, y, C('smoke', 4.8 - j * 0.4))
    else:
        for y in range(3, 13):
            for x in range(3, 13):
                d1 = (x - 7.5) ** 2 + (y - 7.5) ** 2
                d2 = (x - 9.8) ** 2 + (y - 6.2) ** 2
                if d1 <= 20 and d2 > 14:
                    s.px(x, y, C('wool', 6))
        if k % 2:
            s.px(13, 3, C('wool', 6))
            s.px(2, 11, C('wool', 5))
        else:
            s.px(12, 12, C('wool', 6))
    s.outline(C('ink', 1))
    return s


def stores():
    """The ship's stores: a sack tied at the neck beside a small cask."""
    s = icon()
    for y in range(6, 15):
        for x in range(2, 9):
            if (x - 5.2) ** 2 / 10 + (y - 10.5) ** 2 / 20 <= 1:
                s.px(x, y, C('wool', 3.6 + (x < 5) * 0.6))
    for x in (4, 5, 6):
        s.px(x, 6, C('tar', 3))
    s.px(5, 5, C('wool', 4))
    for y in range(8, 15):
        for x in range(9, 14):
            s.px(x, y, C('driftwood', 3.6 + (x == 10) * 1.2))
        if y in (9, 13):
            for x in range(9, 14):
                s.px(x, y, C('tar', 3))
    s.outline(C('ink', 1))
