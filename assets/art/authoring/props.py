def write(name, body):
    with open(os.path.join(MAPS, f'{name}.map.txt'), 'w') as f:
        f.write(body)


def ground(g, row):
    """Move a drawing up or down so its lowest drawn row is `row` (the outline then lands on the pivot)."""
    rows = [y for y, r in enumerate(g) if any(c != '.' for c in r)]
    if not rows:
        return g
    d = row - rows[-1]
    h, w = len(g), len(g[0])
    out = blank(w, h)
    for y in range(h):
        if 0 <= y - d < h:
            out[y] = list(g[y - d])
    return out


def frames(state, grids, foot=None):
    if foot is not None:
        grids = [ground(g, foot - 1) for g in grids]
    return '\n'.join(f'\nframe {state} - {i}\n{text(g)}\nend' for i, g in enumerate(grids))


