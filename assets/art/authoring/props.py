# ---------------------------------------------------------------- heather
def heather(seed):
    rnd = random.Random(seed)
    g = blank(26, 16)
    for _ in range(9):
        ellipse(g, rnd.uniform(6, 20), rnd.uniform(6, 11), rnd.uniform(2.6, 4.2), rnd.uniform(2, 3.2), 'H')
    # Flowers in sprays on the tops of the sprigs, not spread evenly.
    for _ in range(rnd.randint(4, 6)):
        cx, cy = rnd.uniform(5, 21), rnd.uniform(4, 9)
        for _ in range(rnd.randint(2, 4)):
            x, y = int(cx + rnd.uniform(-1.6, 1.6)), int(cy + rnd.uniform(-1, 1))
            if 0 <= y < 16 and 0 <= x < 26 and g[y][x] == 'H':
                g[y][x] = 'v'
    return g


