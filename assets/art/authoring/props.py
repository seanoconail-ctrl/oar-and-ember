# ---------------------------------------------------------------- the wreck
def wreck():
    W, H = 80, 44
    g = blank(W, H)
    for x in range(6, 70):
        t = (x - 6) / 63
        top = round(18 - 9 * math.sin(math.pi * min(1, t * 1.15)) + (6 * (t - .8) if t > .8 else 0))
        bottom = round(top + 3 + 17 * math.sin(math.pi * min(1, t * 1.05)) ** 0.6)
        for y in range(max(0, top), min(H, bottom)):
            g[y][x] = 'T'
        if 0 <= top < H:
            g[top][x] = 'G'
    for x in range(8, 66):
        t = (x - 6) / 63
        top = 18 - 9 * math.sin(math.pi * min(1, t * 1.15))
        bottom = top + 3 + 17 * math.sin(math.pi * min(1, t * 1.05)) ** 0.6
        for frac in (.35, .55, .75):
            y = round(top + (bottom - top) * frac)
            if g[y][x] == 'T':
                g[y][x] = 'p'
    for x in range(58, 72):
        for y in range(0, H):
            if g[y][x] in 'TpG' and (x + y) % 5 != 0 and y < 30:
                g[y][x] = '.'
    for rx in (59, 63, 67):
        for y in range(14, 32):
            g[y][rx] = 'N'
            g[y][rx + 1] = 'N'
    for y in range(4, 16):
        g[y][34] = 'N'
        g[y][35] = 'N'
    for x in range(8, 70):
        col = [y for y in range(H) if g[y][x] != '.']
        if col and x % 3 != 1:
            g[col[-1]][x] = 'w'
    return g


