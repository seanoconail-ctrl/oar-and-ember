# ---------------------------------------------------------------- debris on the beach
def log(length, seed):
    rnd = random.Random(seed)
    g = blank(length + 10, 14)
    for x in range(3, length + 3):
        t = (x - 3) / length
        thick = 3.2 + math.sin(t * 9) * 0.6 - t * 0.8
        cy = 7 + math.sin(t * 4) * 1.5
        for y in range(int(cy - thick), int(cy + thick) + 1):
            g[y][x] = 'D' if (x * 7) % 9 else 'k'
    ellipse(g, 5, 7, 4, 5, 'D')
    for k in range(6):
        g[3 - k // 2][length // 2 + k] = 'D'
    return g


def planks():
    g = blank(30, 12)
    for (x0, y0, ln, ang) in [(2, 4, 24, 0.12), (6, 7, 20, -0.08)]:
        for k in range(ln):
            for w_ in range(3):
                g[int(y0 + k * ang + w_)][int(x0 + k)] = 'T'
        g[int(y0 + ln * ang)][x0 + ln - 3] = 'i'
    return g


def barrel():
    g = blank(16, 15)
    ellipse(g, 8, 7.5, 5.5, 6, 'T')
    for y in (3, 11):
        for x in range(2, 14):
            if g[y][x] == 'T':
                g[y][x] = 'i'
    for y in range(5, 9):
        g[y][11] = 'k'
    return g


def net():
    g = blank(20, 11)
    for y in range(1, 10):
        for x in range(1, 19):
            if ((x + y) % 3 == 0 or (x - y) % 3 == 0) and ((x - 10) / 9) ** 2 + ((y - 5) / 4.5) ** 2 < 1:
                g[y][x] = 'N'
    ellipse(g, 15, 3, 2, 1.6, 'F')
    return g


def rope():
    g = blank(16, 10)
    for k in range(70):
        a = k * 0.45
        rad = 2 + k / 18
        g[int(5 + math.sin(a) * rad * 0.55)][int(8 + math.cos(a) * rad)] = 'N'
    return g


def pad_to(g, w, h):
    out = blank(w, h)
    oy = h - len(g)
    ox = (w - len(g[0])) // 2
    for y, row in enumerate(g):
        for x, c in enumerate(row):
            out[oy + y][ox + x] = c
    return out


