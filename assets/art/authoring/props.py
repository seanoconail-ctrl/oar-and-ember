def small_stone(seed, w=14, h=10):
    g = blank(w, h)
    rnd = random.Random(seed)
    lumpy(g, w / 2, h / 2 + 1, rnd.uniform(3.5, 4.6), rnd.uniform(2.4, 3.0), 'R', seed)
    if seed % 2:
        lumpy(g, w / 2 + 2, h / 2 + 2, 2.2, 1.6, 'Q', seed + 9)
    for x in range(w):
        col = [y for y in range(h) if g[y][x] != '.']
        if col and seed % 3 == 0:
            g[col[-1]][x] = 'w'
    return g


