def gull(flap):
    g = blank(16, 10)
    for (x, y) in [(5, 4), (6, 4), (7, 4), (8, 4), (9, 4), (6, 3), (7, 3), (8, 3), (10, 4)]:
        g[y][x] = 'B'
    g[3][9] = 'H'
    g[4][11] = 'y'
    wing_y = [1, 3, 5, 3][flap]
    for k in range(5):
        yy = int(round(4 + (wing_y - 4) * (k / 4)))
        g[yy][6 - k] = 'K' if k >= 3 else 'G'
        g[yy][7 + k // 2] = 'G'
    return g


def gull_standing(turn):
    g = blank(16, 10)
    for (x, y) in [(6, 4), (7, 4), (8, 4), (5, 5), (6, 5), (7, 5), (8, 5), (9, 5), (6, 6), (7, 6), (8, 6)]:
        g[y][x] = 'B'
    for (x, y) in [(8, 4), (9, 5), (9, 6)]:
        g[y][x] = 'G'
    hx = 5 if turn else 7
    g[3][hx] = 'H'
    g[3][hx - 1 if turn else hx + 1] = 'y'
    g[7][6] = 'y'
    g[7][8] = 'y'
    return g


