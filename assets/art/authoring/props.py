def boulder(seed):
    rnd = random.Random(seed)
    g = blank(36, 28)
    lumpy(g, 18, 15, 12, 8.6, 'R', seed)
    # Lichen grows in patches on the crown, where rain and light reach; cracks run with the grain.
    for _ in range(rnd.randint(3, 5)):
        ellipse(g, rnd.uniform(10, 26), rnd.uniform(8, 13), rnd.uniform(1.4, 3.2), rnd.uniform(1, 1.8), 'l', 'R')
    for _ in range(2):
        x, y = rnd.uniform(11, 24), rnd.uniform(13, 18)
        for t in range(rnd.randint(3, 6)):
            xi, yi = int(x + t), int(y + t * 0.4 + rnd.choice((0, 0, 1)))
            if g[yi][xi] in 'Rl':
                g[yi][xi] = 'c'
    return g


