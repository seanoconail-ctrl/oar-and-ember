def blank(w, h):
    return [['.'] * w for _ in range(h)]


def text(g):
    return '\n'.join(''.join(r) for r in g)


def ellipse(g, cx, cy, rx, ry, ch, only=None):
    for y in range(len(g)):
        for x in range(len(g[0])):
            if ((x + .5 - cx) / rx) ** 2 + ((y + .5 - cy) / ry) ** 2 <= 1 and (only is None or g[y][x] in only):
                g[y][x] = ch


def lumpy(g, cx, cy, rx, ry, ch, seed):
    """An irregular stone outline: a lumpy radius."""
    rnd = random.Random(seed)
    ph = [rnd.random() * 6.28 for _ in range(4)]
    for y in range(len(g)):
        for x in range(len(g[0])):
            dx, dy = (x + .5 - cx) / rx, (y + .5 - cy) / ry
            a = math.atan2(dy, dx)
            rad = 1 + sum(0.11 * math.sin(a * (k + 2) + ph[k]) for k in range(4))
            if math.hypot(dx, dy) <= rad:
                g[y][x] = ch


def pile(w, h, n, seed):
    """A pile of boulders: alternating materials so the stones read apart; cracks and lichen."""
    rnd = random.Random(seed)
    g = blank(w, h)
    stones = []
    for i in range(n):
        rx = rnd.uniform(7, 15)
        ry = rx * rnd.uniform(0.6, 0.8)
        cx = rnd.uniform(rx + 2, w - rx - 2)
        cy = rnd.uniform(h * 0.35, h - ry - 2)
        stones.append((cy + ry, cx, cy, rx, ry, 'RQ'[i % 2], i))
    for _, cx, cy, rx, ry, ch, i in sorted(stones):
        lumpy(g, cx, cy, rx, ry, ch, seed * 31 + i)
        for t in range(int(rx)):
            x, y = int(cx - rx / 3 + t * 0.6), int(cy - ry / 4 + t * 0.45)
            if 0 <= y < h and 0 <= x < w and g[y][x] in 'RQ' and t % 4 != 3:
                g[y][x] = 'c'
        for t in range(3):
            x, y = int(cx - rx / 2 + rnd.uniform(0, rx)), int(cy - ry + 2)
            if 0 <= y < h and 0 <= x < w and g[y][x] in 'RQ':
                g[y][x] = 'l'
    # Weed where the tide reaches the foot of the pile, barnacles just above it.
    for x in range(w):
        col = [y for y in range(h) if g[y][x] != '.']
        if not col:
            continue
        bottom = col[-1]
        for y in range(max(0, bottom - 3), bottom + 1):
            if g[y][x] != '.' and (x * 7 + y) % 3 != 0:
                g[y][x] = 'w'
        for y in range(max(0, bottom - 6), max(0, bottom - 3)):
            if g[y][x] != '.' and (x * 5 + y * 3) % 4 == 0:
                g[y][x] = 'n'
    return g


