"""Combat v2's interface pieces and hit effects (design addendum 2.4 section 1; Book 7 sections 10,
12 and 14; decisions DE-3, DE-5, DE-7, DE-8, DE-9, DE-10).

    python3 assets/art/authoring/combat24_ui.py && npm run art:adopt && npm run art:sheets \\
        && npm run art:compile

Writes assets/art/proposed/sheets/ui_combat.txt (12 x 12 cells: the health bar's red column, the
awareness marks "?" and "!", the thin bar over an enemy, the lock-on brackets at the target's feet,
the binding and the ration for the bars' counts) and fx_combat.txt (16 x 16 cells: the parry's
bright star, sparks off mail and iron, splinters off a shield's boards, the dust of a sidestep).
Palette codes by ramp name, hand placed; deterministic.
"""
import json
import os

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
OUT = os.path.join(REPO, 'assets', 'art', 'proposed', 'sheets')
with open(os.path.join(REPO, 'assets', 'palette', 'book07.json'), encoding='utf8') as f:
    _PAL = json.load(f)
RAMP = {}
for _e in _PAL['entries']:
    if 'ramp' in _e:
        RAMP.setdefault(_e['ramp'], {})[_e['step']] = _e['code']


def c(ramp, step):
    return RAMP[ramp][step]


T = '.'
INK = c('ink', 0)


def blank(w, h):
    return [[T] * w for _ in range(h)]


def draw(g, rows, ox, oy, pal):
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch in pal:
                g[oy + y][ox + x] = pal[ch]
    return g


def write(name, kind, w, h, anims, notes):
    lines = [f'# Generated by assets/art/authoring/combat24_ui.py. Do not edit by hand: change the',
             '# script and run it again.']
    lines += [f'# {n}' for n in notes]
    lines += [f'sheet: {name}', f'kind: {kind}', 'palette: book07', f'size: {w}x{h}', 'pivot: 0,0',
              f'footprint: {w}x{h}', 'facings: -', 'placeholder: false']
    for state, frames, ticks, loop in anims:
        lines.append(f'anim.{state}: frames {len(frames)}, ticks {ticks}' + (', loop' if loop else ''))
    lines.append('')
    for state, frames, _, _ in anims:
        for i, g in enumerate(frames):
            assert len(g) == h and all(len(r) == w for r in g), (name, state, i)
            lines += [f'frame {state} - {i}', '\n'.join(''.join(r) for r in g), 'end', '']
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, f'{name}.txt'), 'w', encoding='utf8') as f:
        f.write('\n'.join(lines))


# ------------------------------------------------------------------------------------- ui_combat
RED = (c('madder', 1), c('madder', 2), c('madder', 3), c('madder', 5))  # shadow .. glint


def health_fill():
    """One column of the health bar's fill, on the stamina bar's rows (ui_stamina's 9-high bar)."""
    g = blank(12, 12)
    for y, ch in zip(range(3, 7), (RED[3], RED[2], RED[1], RED[0])):
        g[y][0] = ch
    return g


def health_end():
    g = blank(12, 12)
    for y, ch in zip(range(3, 7), (c('madder', 5), RED[3], RED[2], RED[1])):
        g[y][0] = ch
        g[y][1] = ch if y in (4, 5) else T
    return g


Q = ['.kkkk.',
     'kyyyyk',
     'kkkkyk',
     '..kyyk',
     '..kyk.',
     '..kk..',
     '..kyk.',
     '..kk..']
X = ['kk.',
     'kyk',
     'kyk',
     'kyk',
     'kyk',
     'kk.',
     'kyk',
     'kk.']


def mark(rows, colour, bob):
    g = blank(12, 12)
    pal = {'k': INK, 'y': colour}
    return draw(g, rows, 6 - len(rows[0]) // 2, 2 + bob, pal)


def ebar(kind):
    """One column of the thin bar over an enemy (3 px: ink, the fill or the empty groove, ink)."""
    g = blank(12, 12)
    mid = {'fill': RED[2], 'empty': c('ink', 1), 'end': INK}[kind]
    g[0][0] = INK
    g[1][0] = mid
    g[2][0] = INK
    if kind == 'fill':
        g[1][0] = RED[3]
    return g


def lock(phase):
    """Brackets on the ground round the locked target's feet (a dark ring with a warm edge)."""
    g = blank(12, 12)
    lit = c('fire', 6) if phase == 0 else c('fire', 5)
    rows = ['kk......kk',
            'ky......yk',
            '.ky....yk.',
            '..k....k..']
    flip = list(reversed(rows))
    pal = {'k': INK, 'y': lit}
    draw(g, rows, 1, 1 + phase, pal)
    draw(g, flip, 1, 7 - phase, pal)
    return g


BINDING = ['.kkkk.',
           'kwwwwk',
           'kwmwwk',
           'kwwwmk',
           '.kkkk.']
RATION = ['..kk..',
          '.kssk.',
          'ksfssk',
          'kssssk',
          '.kkkk.']


def small(rows, pal):
    g = blank(12, 12)
    return draw(g, rows, 3, 4, {'k': INK, **pal})


def ui_combat():
    q = c('fire', 6)
    x = c('fire', 4)
    write('ui_combat', 'decal', 12, 12, [
        ('hfill', [health_fill()], 1, False),
        ('hend', [health_end()], 1, False),
        ('mark_q', [mark(Q, q, 0), mark(Q, q, 1)], 12, True),
        ('mark_x', [mark(X, x, 0), mark(X, c('fire', 6), 0)], 4, True),
        ('ebar_fill', [ebar('fill')], 1, False),
        ('ebar_empty', [ebar('empty')], 1, False),
        ('ebar_end', [ebar('end')], 1, False),
        ('lock', [lock(0), lock(1)], 20, True),
        ('binding', [small(BINDING, {'w': c('wool', 5), 'm': c('madder', 3)})], 1, False),
        ('ration', [small(RATION, {'s': c('sea', 7), 'f': c('sea', 9)})], 1, False),
    ], ['Combat v2 (decisions DE-3, DE-8, DE-9): the health bar beside the stamina bar, the awareness',
        'marks ("?" suspicious, "!" turning alert), the thin bar over an enemy, the lock-on brackets,',
        'and the carried binding and ration.'])


# ------------------------------------------------------------------------------------- fx_combat
def star(r, bright):
    """The parry's bright star: four long rays and four short, a hot white core."""
    g = blank(16, 16)
    core = c('fire', 7)
    ray = c('fire', 6) if bright else c('fire', 5)
    tip = c('fire', 5) if bright else c('fire', 4)
    cx, cy = 8, 8
    for k in range(-r, r + 1):
        a = abs(k)
        col = core if a <= 1 else ray if a < r else tip
        g[cy][cx + k] = col
        g[cy + k][cx] = col
    for k in range(-(r // 2), r // 2 + 1):
        a = abs(k)
        col = core if a == 0 else ray
        g[cy + k][cx + k] = col
        g[cy + k][cx - k] = col
    return g


def sparks(i, iron):
    """Sparks off mail or iron (warm, few) or splinters off a shield's boards (wood, falling)."""
    g = blank(16, 16)
    pts = [[(8, 8), (7, 7), (9, 7)], [(6, 6), (10, 6), (8, 5), (11, 8)], [(4, 6), (12, 7), (9, 3)]][i]
    for (x, y) in pts:
        if iron:
            g[y][x] = c('fire', 7) if i == 0 else c('fire', 6) if i == 1 else c('fire', 5)
        else:
            g[y + i][x] = c('bracken', 4)
            if x + 1 < 16:
                g[y + i][x + 1] = c('bracken', 2)
    return g


def puff(i):
    g = blank(16, 16)
    cols = [c('sand', 5), c('sand', 4), c('sand', 3)]
    r = 2 + i
    for y in range(16):
        for x in range(16):
            d = ((x - 8) ** 2) / (r * r) + ((y - 12) ** 2) / ((r / 2 + 0.5) ** 2)
            if 0.55 < d <= 1.0 and (x + y + i) % 2 == 0:
                g[y][x] = cols[i]
    return g


def fx_combat():
    write('fx_combat', 'decal', 16, 16, [
        ('parry', [star(3, True), star(6, True), star(7, False), star(4, False)], 3, False),
        ('sparks', [sparks(i, True) for i in range(3)], 3, False),
        ('splinters', [sparks(i, False) for i in range(3)], 4, False),
        ('puff', [puff(i) for i in range(3)], 4, False),
    ], ['Combat v2 (decisions DE-5, DE-7, DE-10): the parry\'s bright spark, sparks off mail and iron,',
        'splinters off a shield\'s boards (an arrow\'s thunk, a blocked blow), and the dust of a',
        'sidestep.'])


if __name__ == '__main__':
    ui_combat()
    fx_combat()
