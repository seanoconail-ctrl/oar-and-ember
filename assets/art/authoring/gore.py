"""Writes assets/art/sheets/fx_gore.txt (Book 7 section 12, Stage 9): blood in the same pixel
language as everything else, from the palette's four blood codes (6 fresh, 7 dark, 8 dried,
9 highlight).

    python3 assets/art/authoring/gore.py

- spray     a droplet in flight (1 to 2 px), 3 frames as it falls and shrinks: 4 to 10 of these
            leave each hit in the blow's direction (Book 7: heavier for heavy and riposte hits)
- drops     4 scatters of drops left on the ground where blood fell
- pool      5 growing frames: the pool under the downed and the dead
- pool_low  the gore setting low: a smaller, darker, dried pool, 5 frames
- smear     2 drag trails, left behind someone carried or crawling
- flash     a pale hit flash (with the gore setting off, hits flash only), 3 frames
- tell      the charge's level-2 tell: a hard flash on the weapon, 4 frames (level 1 uses fx_glint)
Deterministic: every shape comes from a hashed pattern, no randomness.
"""
import math
import os

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
OUT = f'{REPO}/assets/art/sheets/fx_gore.txt'
GLINT_HI, GLINT, GLINT_LO = 'ĸ', 'ķ', 'ε'


def h(*v):
    x = 0
    for k in v:
        x = (x * 1103515245 + k * 2654435761 + 12345) & 0xFFFFFFFF
    return (x >> 8) / 0xFFFFFF


def grid(w, hh):
    return [['.'] * w for _ in range(hh)]


def rows(g):
    return [''.join(r) for r in g]


frames = []   # (state, i, w, h, rows)

# spray: 5 x 5
for i, pts in enumerate([[(2, 1, '9'), (2, 2, '6'), (1, 2, '6'), (2, 3, '7')],
                         [(2, 2, '6'), (2, 3, '7')],
                         [(2, 3, '7')]]):
    g = grid(5, 5)
    for x, y, c in pts:
        g[y][x] = c
    frames.append(('spray', i, 5, 5, rows(g)))

# drops: 12 x 8
for v in range(4):
    g = grid(12, 8)
    for k in range(7 + v):
        x = int(1 + h(v, k, 1) * 10)
        y = int(1 + h(v, k, 2) * 6)
        g[y][x] = '7' if h(v, k, 3) > 0.35 else '8'
        if h(v, k, 4) > 0.7 and x + 1 < 11:
            g[y][x + 1] = '6'
    frames.append(('drops', v, 12, 8, rows(g)))


def pool(state, dried):
    for i in range(5):
        g = grid(24, 10)
        rx = 3.5 + i * 2.0 if not dried else 2.5 + i * 1.4
        ry = 1.6 + i * 0.75 if not dried else 1.2 + i * 0.55
        for y in range(10):
            for x in range(24):
                dx = (x + 0.5 - 12) / rx
                dy = (y + 0.5 - 5) / ry
                wob = 0.12 * math.sin(x * 1.7 + y * 2.3)
                d = dx * dx + dy * dy
                if d <= 1 + wob:
                    if dried:
                        g[y][x] = '8'
                    elif d > 0.65:
                        g[y][x] = '7'
                    elif d < 0.12 and y < 5:
                        g[y][x] = '9'
                    else:
                        g[y][x] = '6' if (x + y) % 5 else '7'
        frames.append((state, i, 24, 10, rows(g)))


pool('pool', False)
pool('pool_low', True)

# smear: 14 x 6
for v in range(2):
    g = grid(14, 6)
    for x in range(1, 13):
        y = 2 + round(math.sin(x * 0.6 + v) * 0.8)
        g[y][x] = '7' if (x + v) % 3 else '8'
        if x % 4 != v:
            g[y + 1][x] = '8'
    frames.append(('smear', v, 14, 6, rows(g)))

# flash: 9 x 9 (hit flash, gore off)
for i, r in enumerate([1, 2, 3]):
    g = grid(9, 9)
    for k in range(-r, r + 1):
        g[4][4 + k] = GLINT if abs(k) < r else GLINT_LO
        g[4 + k][4] = GLINT if abs(k) < r else GLINT_LO
    g[4][4] = GLINT_HI if i < 2 else GLINT
    if i == 1:
        for dx, dy in ((1, 1), (-1, 1), (1, -1), (-1, -1)):
            g[4 + dy][4 + dx] = GLINT_LO
    frames.append(('flash', i, 9, 9, rows(g)))

# tell: 13 x 13 (the level-2 charge's flash on the weapon)
for i, r in enumerate([2, 4, 5, 3]):
    g = grid(13, 13)
    for k in range(-r, r + 1):
        g[6][6 + k] = GLINT if abs(k) < r - 1 else GLINT_LO
        g[6 + k][6] = GLINT if abs(k) < r - 1 else GLINT_LO
    for k in range(1, max(1, r - 1)):
        for sx, sy in ((1, 1), (-1, 1), (1, -1), (-1, -1)):
            g[6 + sy * k][6 + sx * k] = GLINT_LO
    g[6][6] = GLINT_HI
    frames.append(('tell', i, 13, 13, rows(g)))

states = []
for s, i, w, hh, r in frames:
    if s not in [x[0] for x in states]:
        states.append((s, w, hh))
W = max(f[2] for f in frames)
H = max(f[3] for f in frames)
out = ["# Generated by assets/art/authoring/gore.py. Do not edit by hand: change the script and run",
       "# python3 assets/art/authoring/gore.py.",
       "# Blood (Book 7 section 12; Stage 9): droplets in flight, drops, growing pools (and the gore",
       "# setting's smaller, darker ones), drag smears, the hit flash and the level-2 charge's tell.",
       "# Drawn on the decal layer (drops, pools, smears) or over people (spray, flash, tell); the gore",
       "# setting changes presentation only.",
       "sheet: fx_gore", "kind: decal", "palette: book07", f"size: {W}x{H}",
       f"pivot: {W // 2},{H // 2}", f"footprint: {W}x{H}", "facings: -", "placeholder: false"]
counts = {}
for s, i, *_ in frames:
    counts[s] = counts.get(s, 0) + 1
for s, _, _ in states:
    out.append(f"anim.{s}: frames {counts[s]}, ticks {3 if s in ('spray', 'flash') else 4}")
for s, i, w, hh, r in frames:
    g = grid(W, H)
    ox = W // 2 - w // 2
    oy = H // 2 - hh // 2
    for y, row in enumerate(r):
        for x, c in enumerate(row):
            g[oy + y][ox + x] = c
    out += ['', f'frame {s} - {i}', *rows(g), 'end']
open(OUT, 'w').write('\n'.join(out) + '\n')
print(f'wrote {OUT}')


