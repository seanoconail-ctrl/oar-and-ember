"""Builds the user's fourth playtest's story art (Book 7 sections 06 and 14; decision DH-11), painted
with the approved mockup's palette ramps (docs/art/mockup-src) and written as palette-coded sheets:

- prop_shelter_mark: where the shelter is worked, marked on the ground as the household would mark
  it, never a box or a circle (the user: "the spot shows where to do it"). On the lean-to's own
  width, its lowest row on the lean-to's foot, so each mark stands exactly where that stage is done:
  - `pegs` (the frame to stand): a stake driven where the first oar's foot will go, the cord run
    from it up towards the wall and out to a guy peg, a line scratched in the turf; the cord's loose
    ends stir in the wind (a loop).
  - `stones` (the sail to lash): the foot-stones gathered in a heap, ready to weight the sail's foot,
    a coil of lashing on them whose loose end stirs (a loop).
  - `turf` (the second day's finishing, at its build site): a turf spade standing in the ground, and
    the cutting line pegged out beside it with a cord that stirs (a loop).
  Each is drawn at the spot where that stage is worked, beside the lean-to's bed and never on it
  (decision DH-10), on its own small canvas.

    python3 assets/art/authoring/pt4_story_art.py && npm run art:compile
"""
import math
import os
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
sys.path.insert(0, f'{REPO}/docs/art/mockup-src')
sys.path.insert(0, os.path.dirname(__file__))
from core import C, Sprite, hash01   # noqa: E402
from broch_art import sheet_text, write   # noqa: E402
from rework24_art import raw_rows   # noqa: E402

HEADER = ["Generated by assets/art/authoring/pt4_story_art.py (the user's fourth playtest). Do not",
          'edit by hand.']
INK = C('ink', 0)

# A small canvas of its own, its lowest row on the ground at the spot where the stage is worked
# (beside the lean-to's bed, never on it: decision DH-10).
W, H = 40, 26
PIVOT = (20, H - 1)
FOOT = H - 1


def stake(s, x, top, foot=FOOT, wide=2):
    """A driftwood stake driven into the turf, ink outlined, its head bruised by the mallet."""
    for y in range(top, foot + 1):
        for dx in range(wide):
            s.px(x + dx, y, C('driftwood', 5 if dx == 0 else 4))
        s.px(x - 1, y, INK)
        s.px(x + wide, y, INK)
    for dx in range(-1, wide + 1):
        s.px(x + dx, top - 1, INK)
    s.px(x, top, C('driftwood', 6))
    for dx in range(-2, wide + 2):
        s.px(x + dx, foot, C('earth', 2 + (dx % 2)))


def cord(s, x0, y0, x1, y1, sag):
    n = max(1, int(max(abs(x1 - x0), abs(y1 - y0))))
    for k in range(n + 1):
        t = k / n
        x = x0 + (x1 - x0) * t
        y = y0 + (y1 - y0) * t + math.sin(t * math.pi) * sag
        s.px(int(round(x)), int(round(y)), C('earth', 3 if k % 4 else 2))


def tail(s, x, y, k, way=1, n=4):
    """A cord's loose end stirring in the wind (frame k of 4)."""
    for j in range(n):
        lift = int(round(math.sin(k * math.pi / 2 + j * 0.9) * (j / 2)))
        s.px(x + way * j, y + j // 2 - lift, C('earth', 3 - (j == n - 1)))


def scratch(s, x0, x1, y):
    """A line scratched in the turf: torn grass, the dark earth showing through."""
    for x in range(x0, x1 + 1):
        if hash01(x, y, 7) < 0.82:
            s.px(x, y, C('earth', 1 + (hash01(x, y, 3) > 0.6)))
        if hash01(x, y, 9) < 0.25:
            s.px(x, y - 1, C('grass', 3))


def pegs_sprite(k):
    """The frame to stand: a stake where the first oar's foot goes, the cord run from it up towards
    the wall, a second peg for the guy, and a line scratched in the turf between."""
    s = Sprite(W, H, PIVOT[0], PIVOT[1])
    scratch(s, 9, 31, FOOT - 1)
    stake(s, 10, FOOT - 9)
    stake(s, 29, FOOT - 4, FOOT, 1)
    cord(s, 12, FOOT - 7, 29, FOOT - 3, 1.5)
    cord(s, 12, FOOT - 8, 24, FOOT - 17, -1.0)
    tail(s, 24, FOOT - 18, k, 1, 5)
    tail(s, 8, FOOT - 8, (k + 2) % 4, -1)
    for dx in (-1, 0, 1):
        s.px(31 + dx, FOOT - 1, C('stone', 4 + (dx == -1)))
    return s


def stones_sprite(k):
    """The sail to lash: the foot-stones gathered in a heap, a coil of lashing on top."""
    s = Sprite(W, H, PIVOT[0], PIVOT[1])
    heap = ((8, FOOT - 3), (13, FOOT - 3), (18, FOOT - 3), (23, FOOT - 3),
            (10, FOOT - 6), (15, FOOT - 6), (20, FOOT - 6), (13, FOOT - 9), (18, FOOT - 9))
    for i, (x0, y0) in enumerate(heap):
        for dx in range(5):
            for dy in range(3):
                if dx in (0, 4) and dy in (0, 2):
                    continue
                shade = 3 + (dx < 2) + (dy == 0) - (hash01(x0, dx, i) > 0.8)
                s.px(x0 + dx, y0 + dy, C('stone', shade))
            s.px(x0 + dx, y0 + 3, INK) if dx not in (0, 4) else None
    for a in range(0, 360, 30):
        x = 17 + int(round(math.cos(math.radians(a)) * 4))
        y = FOOT - 12 + int(round(math.sin(math.radians(a)) * 1.5))
        s.px(x, y, C('earth', 3 if a % 60 else 2))
    tail(s, 21, FOOT - 12, k, 1, 6)
    return s


def turf_sprite(k):
    """The finishing: a turf spade standing in the ground, the cutting line pegged out beside it."""
    s = Sprite(W, H, PIVOT[0], PIVOT[1])
    stake(s, 3, FOOT - 4, FOOT, 1)
    stake(s, 35, FOOT - 4, FOOT, 1)
    cord(s, 4, FOOT - 3, 35, FOOT - 3, 1.2)
    scratch(s, 5, 34, FOOT)
    tail(s, 37, FOOT - 4, k, 1)
    x = 19
    for y in range(FOOT - 22, FOOT - 4):
        s.px(x, y, C('driftwood', 5))
        s.px(x + 1, y, C('driftwood', 4))
        s.px(x - 1, y, INK)
        s.px(x + 2, y, INK)
    for dx in range(-3, 5):
        s.px(x + dx, FOOT - 23, C('driftwood', 5 - (dx > 1)))
        s.px(x + dx, FOOT - 24, INK)
    for y in range(FOOT - 5, FOOT):
        for dx in range(-2, 4):
            s.px(x + dx, y, C('stone', 5 if dx < 1 else 4) if y == FOOT - 5 else C('driftwood', 4))
    for dx in range(-3, 5):
        s.px(x + dx, FOOT, C('earth', 1 + (dx % 2)))
    return s


def write_mark():
    frames = []
    for state, fn in (('pegs', pegs_sprite), ('stones', stones_sprite), ('turf', turf_sprite)):
        for k in range(4):
            frames.append(((state, '-', k), raw_rows(fn(k), (W, H), PIVOT)))
    # A mark on the ground (Book 7 section 11's decal: flat to the turf, drawn under people, no
    # outline round the thin cords and scratches; the stakes and the spade carry their own ink).
    write('prop_shelter_mark', sheet_text(
        'prop_shelter_mark', 'decal', (W, H), PIVOT, frames,
        {'pegs': (4, 14, 'loop'), 'stones': (4, 14, 'loop'), 'turf': (4, 14, 'loop')},
        HEADER + ["Where the shelter is worked (the user's fourth playtest, decision DH-11), marked on the",
                  'ground as the household would mark it: a stake and a cord where the frame goes (pegs),',
                  'the foot-stones gathered with a coil of lashing (stones), and on the second day a turf',
                  'spade with the cutting line pegged out (turf). The cords stir in the wind. Drawn at the',
                  "spot where each is worked, beside the lean-to's bed (decision DH-10)."],
        shadow='16x3'))


if __name__ == '__main__':
    write_mark()
